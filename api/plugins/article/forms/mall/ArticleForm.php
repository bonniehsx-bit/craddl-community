namespace app\plugins\article\forms\mall;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\plugins\article\models\Article;
use app\plugins\article\services\ArticleGoodsService;
use yii\base\UserException;

class ArticleForm extends BaseModel
{

    public $id;
    public $title;
    public $detail;
    public $video;
    public $cover_pic;
    public $created_by;
    public $cat_id;
    public $sub_title;
    public $sort;
    public $is_published;
    public $views;
    /** 挂的商品:[{goods_id, recommend, is_main}],数组或 JSON 字符串;不传(null)=不动现有挂载,传空数组=清空 */
    public $goods_list;

    public function rules()
    {
        return [
            [['id', 'cat_id', 'views', 'sort', 'is_published'], 'integer'],
            [['views'], 'default', 'value' => 0],
            [['sub_title'], 'string', 'max' => 128],
            [['title', 'detail', 'video', 'cover_pic', 'created_by'], 'string'],
            [['goods_list'], 'safe'],
        ]; // TODO: Change the autogenerated stub
    }


    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        if (!$this->title) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '文章标题不能为空');
        }
        if (!$this->detail) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '文章详情不能为空');
        }
        if (!$this->cover_pic) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '文章封面不能为空');
        }
        if ($this->id) {
            $article = Article::getOne($this->id);
            if (!$article) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '文章不存在！');
            }
        }
        if (!$article) {
            $article = new Article();
            $article->mall_id = \Yii::$app->mall->id;
        }
        $attrs = $this->attributes;
        // BaseModel 自带的 mall_id / page / limit / pagination 不是文章字段;不剔掉的话 mall_id 会被表单里的 0 覆盖
        unset($attrs['goods_list'], $attrs['mall_id'], $attrs['page'], $attrs['limit'], $attrs['pagination']);
        $article->attributes = $attrs;
        if (!$article->save()) {
            return $this->responseErrorMsg($article);
        }
        if ($this->goods_list !== null) {
            $items = is_string($this->goods_list) ? json_decode($this->goods_list, true) : $this->goods_list;
            if (!is_array($items)) {
                $items = [];
            }
            try {
                ArticleGoodsService::replace((int)$article->id, (int)$article->mall_id, $items);
            } catch (UserException $e) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '文章已保存,但挂商品没保存成功:' . $e->getMessage());
            }
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '保存成功');
    }

    public function search()
    {

        $article = Article::getOne($this->id);
        if (!$article) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '文章不存在！');
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', [
            'article'    => $article,
            'goods_list' => ArticleGoodsService::forAdmin((int)$article->id, (int)$article->mall_id),
        ]);
    }

    public function delete()
    {
        $article = Article::getOne($this->id);
        if (!$article) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '文章不存在！');
        }
        $article->is_delete = 1;
        if (!$article->save()) {
            return $this->responseErrorMsg($article);
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '删除成功');
    }
}
