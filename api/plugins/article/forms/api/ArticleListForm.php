namespace app\plugins\article\forms\api;


use app\core\ApiCode;
use app\helpers\DateHelper;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\helpers\GoodsMemberPriceHelper;
use app\plugins\article\models\Article;
use app\plugins\article\services\ArticleGoodsService;

class ArticleListForm extends BaseModel
{

    public $page;
    public $limit = 10;
    public $cat_id;


    public function rules()
    {
        return [
            [['page', 'limit', 'cat_id'], 'integer'],
        ]; // TODO: Change the autogenerated stub
    }


    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        $query = Article::find()->where(['is_delete' => 0, 'mall_id' => \Yii::$app->mall->id, 'is_published' => 1]);
        if ($this->cat_id) {
            $query->andWhere(['cat_id' => $this->cat_id]);
        }
        if ($this->page) {

            $query->page($pagination, $this->limit, $this->page);
        }


        $query->orderBy('sort desc, id desc');
        $list = $query->asArray()->all();
        // 每篇文章挂的商品摘要:件数 / 最多 3 张缩略图 / 最低价(只算能卖的)
        $goods = ArticleGoodsService::sellableByArticles(array_column($list, 'id'), (int)\Yii::$app->mall->id, GoodsMemberPriceHelper::currentLevelId());
        foreach ($list as &$item) {
            $item['created_at'] = $this->createdTime($item['created_at']);
            $gs = $goods[(int)$item['id']] ?? [];
            $item['goods_count'] = count($gs);
            $item['goods_thumbs'] = array_slice(array_column($gs, 'cover_pic'), 0, 3);
            $prices = array_map('floatval', array_column($gs, 'price'));
            $item['goods_min_price'] = $prices ? number_format(min($prices), 2, '.', '') : '';
            $item['goods_price_multi'] = ($prices && (count(array_unique($prices)) > 1 || array_filter(array_column($gs, 'price_multi')))) ? 1 : 0;
        }
        unset($item);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagination]);
    }


    private function createdTime($time)
    {
        $t = time() - $time;
        $f = array(
            '31536000' => '年',
            '2592000' => '个月',
            '604800' => '星期',
            '86400' => '天',
            '3600' => '小时',
            '60' => '分钟',
            '1' => '秒'
        );
        foreach ($f as $k => $v) {
            if (0 != $c = floor($t / (int)$k)) {
                return $c . $v . '前';
            }
        }
    }
}
