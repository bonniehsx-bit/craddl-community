namespace app\plugins\article\forms\api;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\helpers\GoodsMemberPriceHelper;
use app\plugins\article\models\Article;
use app\plugins\article\services\ArticleGoodsService;

class ArticleForm extends BaseModel
{

    public $id;

    public function rules()
    {
        return [
            [['id'], 'required'],
            [['id'], 'integer']
        ]; // TODO: Change the autogenerated stub
    }

    public function search()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        $article = Article::getOne($this->id);


        if (!$article) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '文章不存在');
        }
        if (!$article->is_published) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '文章未发布');
        }
        $article->views += 1;
        $article->save();
        $info = $article->attributes;
        $info['created_at'] = $this->createdTime($info['created_at']);
        // 文中挂的商品(只给能卖的,已套会员价);没挂就是空数组
        $goods = ArticleGoodsService::sellableByArticles([(int)$article->id], (int)$article->mall_id, GoodsMemberPriceHelper::currentLevelId());
        $info['goods_list'] = $goods[(int)$article->id] ?? [];
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['article' => $info]);
    }

    private function createdTime($time)
    {
        $t = time() - $time;
        $f = array(
            '31536000' => '年',
            '2592000' => '个月',
            '604800' => '星期',
            '86400' => '天',
            '3600' => '小时',
            '60' => '分钟',
            '1' => '秒'
        );
        foreach ($f as $k => $v) {
            if (0 != $c = floor($t / (int)$k)) {
                return $c . $v . '前';
            }
        }
    }
}
