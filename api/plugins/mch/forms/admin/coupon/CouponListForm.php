namespace app\plugins\mch\forms\admin\coupon;

use app\core\ApiCode;
use app\models\BaseModel;
use app\models\Coupon;
use app\models\UserCoupon;
use Yii;

// [新增]

class CouponListForm extends BaseModel
{

    public $status;

    public function rules()
    {
        return [
            [['status'], 'string']
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        $currentMch = Yii::$app->mch;

        $query = Coupon::find()->where([
            'mall_id' => Yii::$app->mall->id,
            'mch_id' => $currentMch->id,
            'is_delete' => 0,
        ]);

        // status 过滤原本只声明不使用,前端「可使用 / 已失效」切了也没反应。
        // 失效 = 手动停用(is_enabled=0) 或 固定期限券已过结束时间;
        // 领取后 N 天有效的券(time_type=0)没有绝对结束时间,永不按时间失效。
        $now = time();
        $expiredCond = [
            'or',
            ['is_enabled' => 0],
            ['and', ['time_type' => 1], ['<', 'end_at', $now], ['>', 'end_at', 0]],
        ];
        if ($this->status === 'expired') {
            $query->andWhere($expiredCond);
        } elseif ($this->status === 'valid') {
            $query->andWhere(['not', $expiredCond]);
        }

        $list = $query->orderBy(['id' => SORT_DESC])
            ->page($pagination, 10, $this->page) // 假设每页10条
            ->asArray()
            ->all();

        // ======================= [核心新增] 开始 =======================
        // 批量查询统计数据
        $couponIds = array_column($list, 'id');
        $stats = [];
        if (!empty($couponIds)) {
            $statsResult = UserCoupon::find()
                ->select('coupon_id, 
                          COUNT(id) as sent_count, 
                          SUM(CASE WHEN status = 1 THEN 1 ELSE 0 END) as used_count')
                ->where(['coupon_id' => $couponIds, 'is_delete' => 0])
                ->groupBy('coupon_id')
                ->asArray()
                ->all();
            $stats = array_column($statsResult, null, 'coupon_id');
        }

        // 将统计数据合并到列表项中
        foreach ($list as &$item) {
            $sentCount = $stats[$item['id']]['sent_count'] ?? 0;
            $usedCount = $stats[$item['id']]['used_count'] ?? 0;

            $item['sent_count'] = (int)$sentCount;
            $item['used_count'] = (int)$usedCount;

            if ($item['total_count'] == -1) {
                $item['remaining_count'] = '无限';
            } else {
                $item['remaining_count'] = max(0, $item['total_count'] - $sentCount);
            }

            // coupon.is_expire 这一列全库没有任何代码写过、恒为 0,
            // 前端却拿它判「已失效」—— 结果过期券在列表里一直显示可用。
            // 这里按结束时间实时算出来下发,不改库(避免为一个展示态去写表)。
            $item['is_expire'] = ((int) $item['time_type'] === 1
                && (int) $item['end_at'] > 0
                && (int) $item['end_at'] < $now) ? 1 : 0;
        }
        unset($item);
        // ======================= [核心新增] 结束 =======================

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', [
            'list' => $list,
            'pagination' => $pagination
        ]);
    }
}