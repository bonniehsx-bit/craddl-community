namespace app\models;

use Yii;

/**
 * This is the model class for table "{{%goods_comment}}".
 *
 * @property int $id
 * @property int $mall_id
 * @property int $user_id
 * @property int $order_id
 * @property int $goods_id
 * @property string|null $content
 * @property string|null $pic_list
 * @property int|null $updated_at
 * @property int|null $created_at
 * @property int|null $deleted_at
 * @property int $is_delete
 * @property int $grade_level
 * @property integer $is_second
 */
class GoodsComment extends BaseActiveRecord
{
    const GRADE_LEVEL_WELL = 3;     // 好评 (对应前端的 "好评"，通常是4-5星)
    const GRADE_LEVEL_MIDDLE = 2;   // 中评 (对应前端的 "中评"，通常是2-3星)
    const GRADE_LEVEL_BAD = 1;      // 差评 (对应前端的 "差评"，通常是1星)

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return '{{%goods_comment}}';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['mall_id', 'user_id', 'goods_id'], 'required'],
            [['mall_id', 'is_second', 'user_id', 'order_id', 'goods_id', 'updated_at', 'created_at', 'deleted_at', 'is_delete', 'grade_level'], 'integer'],
            [['content'], 'string', 'max' => 255],
            [['pic_list'], 'string', 'max' => 2048],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'mall_id' => 'Mall ID',
            'user_id' => 'User ID',
            'order_id' => 'Order ID',
            'goods_id' => 'Goods ID',
            'content' => 'Content',
            'pic_list' => 'Pic List',
            'updated_at' => 'Updated At',
            'created_at' => 'Created At',
            'deleted_at' => 'Deleted At',
            'is_delete' => 'Is Delete',
            'grade_level' => 'Grade Level',
        ];
    }

    public function beforeSave($insert)
    {

        if (!$this->order_id) {
            $this->order_id = 0;
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }


    public function getUser()
    {
        return $this->hasOne(User::class, ['id' => 'user_id']);
    }

    public function getGoods()
    {
        return $this->hasOne(Goods::class, ['id' => 'goods_id']);
    }
}
