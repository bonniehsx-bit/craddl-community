namespace app\models;

use Yii;

/**
 * This is the model class for table "{{%goods_info}}".
 *
 * @property int $id
 * @property int $mall_id
 * @property int $goods_id 对应的商品ID
 * @property string $attr_list 规格
 * @property string $detail 商品详情
 * @property int $deleted_at
 * @property int $updated_at
 * @property int $created_at
 * @property int $is_delete
 * @property string|null $pic_list
 * @property string|null $limit_area_list 限制购买的区域
 * @property string|null $remarks 备注
 * @property string|null $permission 权限
 * @property string $level_price
 * @property string $detail_pic_list
 * @property string $content
 * @property string|null $spec_template 规格组模板 (JSON格式) [新增]
 * @property string|null $source_url 商品来源链接（仅供后台查阅）
 */
class GoodsInfo extends BaseActiveRecord
{
    protected function getHiddenFields()
    {
        return array_merge(parent::getHiddenFields(), ['source_url']);
    }

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return '{{%goods_info}}';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        $rules = [
            [['spec_template'], 'safe'], // [新增] 允许 spec_template 被安全赋值
            [['content'], 'string', 'max' => 512],
            [['mall_id', 'goods_id', 'deleted_at', 'updated_at', 'created_at'], 'required'],
            [['mall_id', 'goods_id', 'deleted_at', 'updated_at', 'created_at', 'is_delete'], 'integer'],
            [['attr_list', 'level_price', 'detail', 'limit_area_list', 'pic_list', 'remarks', 'permission', 'detail_pic_list'], 'string'],
        ];
        // 兼容代码已更新、迁移尚未执行的旧商品保存流程。
        if ($this->hasAttribute('source_url')) {
            $rules[] = [['source_url'], 'string', 'max' => 2048];
        }
        return $rules;
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'mall_id' => 'Mall ID',
            'goods_id' => '对应的商品ID',
            'attr_list' => '规格',
            'detail' => '商品详情',
            'deleted_at' => 'Deleted At',
            'updated_at' => 'Updated At',
            'created_at' => 'Created At',
            'is_delete' => 'Is Delete',
            'pic_list' => '商品图片',
            'limit_area_list' => '限制购买的区域',
            'remarks' => '备注',
            'permission' => '权限',
            'level_price' => '会员价设置',
            'spec_template' => '规格组模板', // [新增]
            'source_url' => '来源链接',
        ];
    }

    public function beforeSave($insert)
    {
        $str = (string)$this->detail;
        if (!empty($str) && strpos($str, '<p><span style="color: rgb(0, 0, 0);"><img') !== false) {
            $str = str_replace('<p><span style="color: rgb(0, 0, 0);"><img', '<p><img', $str);
            $str = str_replace('width="750"></span></p>', 'width="750"></p>', $str);
            $this->detail = $str;
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }
}
