namespace app\models;

use app\helpers\JobHelper;
use Yii;

/**
 * This is the model class for table "{{%access_token}}".
 *
 * @property int $id 主键ID
 * @property int|null $model_id 模型ID
 * @property string|null $model 模型
 * @property string|null $token token
 * @property int|null $expire_at 过期时间
 * @property int $is_delete 是否删除
 * @property int|null $created_at 创建时间戳
 * @property int|null $updated_at 更新时间
 * @property int|null $deleted_at 删除时间
 * @property string $created_time 创建时间
 * @property string|null $updated_time 更新时间
 * @property string|null $deleted_time 删除时间
 * @property string $wx_openid
 * @property string $ip
 * @property  string $platform
 */
class AccessToken extends BaseActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return '{{%access_token}}';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['model_id', 'expire_at', 'is_delete', 'created_at', 'updated_at', 'deleted_at'], 'integer'],
            [['created_time', 'updated_time', 'deleted_time'], 'safe'],
            [['ip', 'platform'], 'string'],
            [['model', 'token', 'wx_openid'], 'string', 'max' => 512],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => '主键ID',
            'model_id' => '模型ID',
            'model' => '模型',
            'token' => 'token',
            'expire_at' => '过期时间',
            'is_delete' => '是否删除',
            'created_at' => '创建时间戳',
            'updated_at' => '更新时间',
            'deleted_at' => '删除时间',
            'created_time' => '创建时间',
            'updated_time' => '更新时间',
            'deleted_time' => '删除时间',
            'wx_openid' => '微信openid',
            'ip' => 'ip',
            'platform' => '平台'
        ];
    }

    public function beforeSave($insert)
    {
        if ($insert) {
            $this->ip = Yii::$app->request->getUserIP();
            $this->platform = Yii::$app->platform;
            if (!$this->expire_at) {
                $this->expire_at = time() + 7 * 24 * 3600;
            }
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function afterSave($insert, $changedAttributes)
    {
        // 只在签发时排一次到期清理。之后改 ip / 续期都不再排 —— 原先每次 save 都排一个,
        // 同一条令牌会堆出一串重复任务。续期过的令牌到点不会被删(见 AccessTokenJob),
        // 真过期后由 UserAccountTask 每日兜底清理
        if ($insert) {
            JobHelper::push(new \app\jobs\common\AccessTokenJob(['token' => $this->token]), max(0, $this->expire_at - time()));
        }
    }

    public function getUser()
    {
        return $this->hasOne(User::class, ['id' => 'model_id'])->where(['status' => User::STATUS_NORMAL]);
    }
}
