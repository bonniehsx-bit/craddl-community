namespace app\controllers\api;


use app\core\ApiCode;
use app\forms\api\wechat\WechatForm;
use app\helpers\CacheHelper;
use app\helpers\OptionHelper;
use app\helpers\ResponseHelper;
use app\helpers\WechatHelper;
use yii\web\Response;

class WechatController extends Controller
{


    public function beforeAction($action)
    {
        WechatHelper::init(\Yii::$app->mall->id);
        return parent::beforeAction($action); // TODO: Change the autogenerated stub
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-10-13
     * @Time: 22:40
     * @Note:
     */
    /**
     * 下发公众号的公开信息(仅 appid)。
     *
     * ⚠ 本接口**公开无鉴权**(本控制器未声明 behaviors,不挂 LoginFilter),
     * 原实现在 data 里只给了 appid,却又在外层挂了一个 `'setting' => $setting`,
     * 把 platform_wechat **整块**吐出去 —— 其中包含 **secret**(AppSecret)、
     * token、aes_key。任何人请求一次就能拿到该商城公众号的全部凭证:
     * 有了 appid+secret 可代该公众号调接口(发消息、取用户信息、拉 access_token),
     * 有了 token 可伪造能通过签名校验的回调。
     *
     * 现在只下发 appid。已确认前端(uniapp/admin)没有任何地方消费那个 setting 字段。
     */
    public function actionSetting()
    {
        $setting = OptionHelper::get('platform_wechat', \Yii::$app->mall->id);
        if (!$setting || empty($setting['appid'])) {
            return $this->asJson(['code' => ApiCode::CODE_FAIL, 'msg' => '未配置平台信息']);
        }
        return $this->asJson([
            'code' => ApiCode::CODE_SUCCESS,
            'msg'  => '',
            'data' => ['appid' => $setting['appid']],
        ]);
    }

    public function actionJssdk()
    {

        $form = new WechatForm();
        $form->attributes = $this->request->get();
        return $this->asJson($form->getJssdk());
    }

    public function actionWechatInfo()
    {

        $auth_code = \Yii::$app->request->post('auth_code');
        if (!$auth_code) {
            return  ResponseHelper::send(ApiCode::CODE_FAIL, '获取用户信息失败,请返回重试!');
        }
        $info = CacheHelper::get($auth_code);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['info' => $info]);
    }
}
