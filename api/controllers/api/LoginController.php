namespace app\controllers\api;


use app\forms\api\login\LoginByMpwxPhoneForm;
use app\forms\api\login\LoginForm;
use app\forms\api\login\MobileSignInForm;
use app\forms\api\login\MpwxPhoneForm;
use app\forms\api\login\PasswordResetForm;
use app\forms\api\login\SmsCodeForm;
use app\helpers\WechatHelper;

class LoginController extends Controller
{

    public function beforeAction($action)
    {
        WechatHelper::init(\Yii::$app->mall->id);
        return parent::beforeAction($action); // TODO: Change the autogenerated stub
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-10-13
     * @Time: 22:33
     * @Note:公众号登录
     */
    public function actionWechat()
    {
        $form = new LoginForm();
        $form->attributes = $this->request->get();
        return $this->asJson($form->loginByWechat());
    }

    public function actionWechatByAuthCode()
    {
        $form = new LoginForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->loginByWechatAuthCode());
    }

    public function actionApp()
    {
        $form = new LoginForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->loginByApp());
    }

    public function actionSmsCode()
    {
        $form = new SmsCodeForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->getCode());
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2022-03-24
     * @Time: 20:53
     * @Note:手机号注册
     */
    public function actionSign()
    {
        $form = new MobileSignInForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->signIn());
    }


    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2022-03-24
     * @Time: 21:14
     * @Note:手机号登录
     */
    public function actionMobile()
    {
        $form = new LoginForm();
        $form->attributes = $this->request->post();
        return $form->loginByMobile();
    }

    /**
     * Created by PhpStorm.
     * User：ganxi
     * Date：2022/5/4
     * Time：9:43
     * Note：重置密码
     */
    public function actionPasswordReset()
    {
        $form = new PasswordResetForm();
        $form->attributes = $this->request->post();
        return $form->reset();
    }

    /**
     * 新版小程序登录
     */
    public function actionMpwxNew()
    {
        $form = new  LoginForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->mpwxNew());
    }

    public function actionMpwxSession()
    {
        $form = new  LoginForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->getMpwxSession());
    }


    public function actionMpwxPhone()
    {
        $form = new MpwxPhoneForm();
        $form->attributes = $this->request->post();
        return $form->getPhone();
    }

    public function actionLoginByMpwxPhone()
    {
        $form = new LoginByMpwxPhoneForm();
        $form->attributes = $this->request->post();
        return $form->login();
    }
}
