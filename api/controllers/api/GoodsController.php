namespace app\controllers\api;


use app\controllers\api\filters\LoginFilter;
use app\forms\api\goods\CatLevelForm;
use app\forms\api\goods\DigitalGoodsListForm;
use app\forms\api\goods\GoodsCommentForm;
use app\forms\api\goods\GoodsCommentListForm;
use app\forms\api\goods\GoodsFavoriteForm;
use app\forms\api\goods\GoodsForm;
use app\forms\api\goods\GoodsListForm;
use app\forms\api\goods\HotSearchForm;
use app\forms\api\goods\RecommendGoodsListForm;
use app\forms\api\mall\CatForm;


class GoodsController extends Controller
{

    public function behaviors()
    {
        return array_merge(parent::behaviors(), [
            'login' => [
                'class' => LoginFilter::class,
                'ignore' => ['list', 'goods', 'cat', 'cat2', 'cat-goods', 'comment-list', 'recommend-list']
            ]
        ]); // TODO: Change the autogenerated stub
    }
 

    public function actionList()
    {
        $form = new GoodsListForm();
        $form->attributes = $this->request->get();
        return $form->getList();
    }

    public function actionGoods()
    {

        $form = new GoodsForm();
        $form->attributes = $this->request->get();
        return $form->search();
    }

    public function actionFavorite()
    {

        $form = new GoodsFavoriteForm();
        $form->attributes = $this->request->post();
        return $form->save();
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-10-13
     * @Time: 20:09
     * @Note:商品评价
     */
    public function actionComment()
    {
        $form = new GoodsCommentForm();
        $form->attributes = $this->request->post();
        return $form->save();
    }

    public function actionCommentList()
    {
        $form = new GoodsCommentListForm();
        $form->attributes = $this->request->get();
        return $form->getList();
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-10-13
     * @Time: 10:04
     * @Note:分类页面
     */
    public function actionCat()
    {
        $form = new CatForm();
        return $form->search();
    }

    public function actionCat2()
    {
        $form = new CatForm();
        return $this->asJson($form->search2());
    }

    /**
     * Created by PhpStorm.
     * User：ganxi
     * Date：2022/3/16
     * Time：17:54
     * Note：二级分类含有商品
     */
    public function actionCatGoods()
    {
        $form = new CatForm();
        return $form->searchCatWithGoods();
    }

    public function actionAllCat()
    {
        $form = new CatLevelForm();
        $form->attributes = $this->request->get();
        return $this->asJson($form->getAllList());
    }

    /**
     * Get recommended goods list
     * API path: /api/goods/recommend-list
     */
    public function actionRecommendList()
    {
        $form = new RecommendGoodsListForm();
        $form->attributes = $this->request->get();
        return $this->asJson($form->getList());
    }

    public function actionHotSearches()
    {
        $form = new HotSearchForm();
        return $form->get();
    }
}
