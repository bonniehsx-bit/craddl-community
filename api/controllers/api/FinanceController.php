namespace app\controllers\api;


use app\controllers\api\filters\LoginFilter;
use app\core\ApiCode;
use app\forms\api\finance\BalanceLogListForm;
use app\forms\api\finance\BalanceOverviewForm;
use app\forms\api\finance\BalanceToIntegralForm;
use app\forms\api\finance\BalanceTransferForm;
use app\forms\api\finance\CashSettingForm;
use app\forms\api\finance\CommissionLogListForm;
use app\forms\api\finance\CommissionOverviewForm;
use app\forms\api\finance\IntegralLogListForm;
use app\forms\api\finance\IntegralOverviewForm;
use app\forms\api\finance\PendingLogForm;
use app\forms\api\finance\PriceLogListForm;
use Yii;

class FinanceController extends Controller
{
    public function behaviors()
    {
        return array_merge(
            parent::behaviors(),
            ['login' => ['class' => LoginFilter::class]]
        ); // TODO: Change the autogenerated stub
    }


    public function actionBalanceOverview()
    {
        $form = new BalanceOverviewForm();
        $form->attributes = $this->request->get();
        return $form->getOverview();
    }

    public function actionIntegralOverview()
    {
        $form = new IntegralOverviewForm();
        $form->attributes = $this->request->get();
        return $form->getOverview();
    }

    public function actionCommissionOverview()
    {
        $form = new CommissionOverviewForm();
        $form->attributes = $this->request->get();
        return $form->getOverview();
    }

    public function actionBalanceTransfer()
    {
        $form = new BalanceTransferForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->transfer());
    }

    public function actionBalanceToIntegral()
    {
        $form = new BalanceToIntegralForm();
        $form->attributes = $this->request->post();
        return $form->save();
    }

    public function actionCashSetting()
    {
        $form = new CashSettingForm();
        return $form->search();
    }

    public function actionBalanceLog()
    {
        $form = new BalanceLogListForm();
        $form->attributes = $this->request->get();
        return $form->getList();
    }
    public function actionIntegralLog()
    {
        $form = new IntegralLogListForm();
        $form->attributes = $this->request->get();
        return $form->getList();
    }

    public function actionPriceLog()
    {
        $form = new PriceLogListForm();
        $form->attributes = $this->request->get();
        return $form->getList();
    }

    /**
     * 分润明细列表（含待结算/已结算/已失效三态）
     * 数据源：commission_log 表；类型元数据由 CommissionTypeRegistry 动态下发。
     */
    public function actionCommissionLog()
    {
        $form = new CommissionLogListForm();
        $form->attributes = $this->request->get();
        return $this->asJson($form->getList());
    }
}
