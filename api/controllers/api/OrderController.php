        return $form->getList();
    }

    /**
     * @Note: 订单列表顶部 tab 配置(后台「订单列表配置」驱动)。
     *        返回启用的状态 tab(名字 + status 值);商城未配置时回退默认 6 个,前端无需再写死。
     * @return \yii\web\Response
     */
    public function actionListConfig()
    {
        $cfg = \app\services\order\OrderListConfig::get((int)\Yii::$app->mall->id);
        $tabs = [];
        foreach ($cfg['status_tabs'] as $t) {
            if (!isset($t['enabled']) || $t['enabled']) {
                $tabs[] = [
                    'name'   => (string)($t['name'] ?? ''),
                    'status' => (int)($t['status'] ?? 0),
                ];
            }
        }
        return $this->asJson(['code' => 0, 'msg' => '', 'data' => ['tabs' => $tabs]]);
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-09-30
     * @Time: 23:44
     * @Note:订单详情
     * @return \yii\web\Response
     */
    public function actionDetail()
    {
