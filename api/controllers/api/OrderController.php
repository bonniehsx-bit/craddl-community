        return $form->cancel();
    }

    /**
     * 【新增】用户填写售后退货的快递单号
     * @return \yii\web\Response
     */
    public function actionRefundFillExpress()
    {
        if (\Yii::$app->request->isPost) {
            $form = new RefundFillExpressForm();
            // 接收 POST 请求的数据
            $form->attributes = \Yii::$app->request->post();
            // 调用 Form Model 的 save 方法来处理业务
            return $this->asJson($form->save());
        }
        // 如果不是 POST 请求，可以返回错误或不处理
        return $this->asJson(['code' => 1, 'msg' => '请求方式错误']);
    }

    /**
     * 轮询自提核销状态（轻量接口）
     * GET /api/order/pickup-status?order_id=xx
     */
