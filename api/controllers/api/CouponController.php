namespace app\controllers\api;


use app\controllers\api\filters\LoginFilter;
use app\forms\api\coupon\CouponCenterForm;
use app\forms\api\coupon\CouponForm;
use app\forms\api\coupon\CouponTransferForm;
use app\forms\api\coupon\CouponTransferLogForm;

class CouponController extends Controller
{
    public function behaviors()
    {
        return array_merge(
            parent::behaviors(),
            ['login' => ['class' => LoginFilter::class]]
        ); // TODO: Change the autogenerated stub
    }

    public function actionCouponCenter()
    {

        $form = new CouponCenterForm();

        return $form->search();
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-11-12
     * @Time: 0:03
     * @Note: 领取优惠券
     */
    public function actionCouponReceive()
    {
        $form = new CouponForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->receive());
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-11-12
     * @Time: 0:35
     * @Note: 用户优惠券
     * @return \yii\web\Response
     */
    public function actionUserCouponList()
    {
        $form = new CouponForm();
        $form->attributes = $this->request->get();
        return $this->asJson($form->getUserCouponList());
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-11-12
     * @Time: 0:35
     * @Note: 平台优惠券
     * @return \yii\web\Response
     */
    public function actionCouponList()
    {
        $form = new CouponForm();
        $form->attributes = $this->request->get();
        return $this->asJson($form->getCouponList());
    }

    /**
     * 优惠券转赠
     * POST: user_coupon_id, target_user_id
     */
    public function actionTransfer()
    {
        $form = new CouponTransferForm();
        $form->attributes = $this->request->post();
        return $this->asJson($form->transfer());
    }

    /**
     * 搜索转赠目标用户
     * GET: keyword
     */
    public function actionSearchTarget()
    {
        $form = new CouponTransferForm();
        $keyword = $this->request->get('keyword');
        return $this->asJson($form->searchTargetUser($keyword));
    }

    /**
     * 查询当前用户的优惠券转赠记录（含转出和收到）
     * GET: page, page_size
     */
    public function actionTransferLogs()
    {
        $form = new CouponTransferLogForm();
        $form->attributes = $this->request->get();
        return $this->asJson($form->getLogs());
    }
}
