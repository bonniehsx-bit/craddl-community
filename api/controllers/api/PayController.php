namespace app\controllers\api;


use app\controllers\api\filters\LoginFilter;
use app\forms\api\pay\AppPayDataForm;
use app\forms\api\pay\AppPayForm;
use app\forms\api\pay\MpLaunchPayForm;
use app\forms\api\pay\PayForm;

class PayController extends Controller
{
    public function behaviors()
    {
        return array_merge(parent::behaviors(),
            [
                'login' => [
                    'class' => LoginFilter::class,
                    'ignore' => ['app-pay-data', 'app-pay', 'mp-launch-pay']
                ]
            ]
        ); // TODO: Change the autogenerated stub
    }


    /**
     * @deprecated 旧版「App 借用小程序支付/H5支付」中转页(others/mp-pay、others/h5-pay,基于 order_no)的接口。
     * 新流程已改为 pages/mp-pay + /api/pay/mp-launch-pay(基于一次性 key)。前端旧中转页已删除。
     * 这两个接口暂保留:兼容尚未更新到新版的已发布 App 二进制(原生 App 不能强制更新),不能贸然删除。
     * 待老版本用户覆盖率降到可忽略后再一并下线(连同 AppPayForm / AppPayDataForm)。
     */
    public function actionAppPayData()
    {
        $form = new AppPayDataForm();
        $form->attributes = $this->request->get();
        return $form->search();
    }

    /** @deprecated 见 actionAppPayData 注释 —— 旧中转页支付接口,保留仅为兼容老版 App。 */
    public function actionAppPay()
    {
        $form = new AppPayForm();
        $form->attributes = $this->request->post();
        return $form->pay();
    }

    public function actionPayData()
    {
        $form = new PayForm();
        $form->attributes = $this->request->post();
        return $form->payData();
    }

    public function actionOrder()
    {
        $form = new PayForm();
        $form->attributes = $this->request->get();
        return $form->getOrder();
    }

    public function actionPayment()
    {
        $form = new PayForm();
        $form->attributes = $this->request->get();
        return $form->getPayment();
    }

    public function actionMpLaunchPay()
    {
        $form = new MpLaunchPayForm();
        $form->attributes = $this->request->get();
        return $form->launch();
    }
}