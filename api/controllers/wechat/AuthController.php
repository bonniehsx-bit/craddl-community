    /**
     * H5 静默获取 openid（snsapi_base，不弹授权页）
     *
     * 用途：微信环境 H5 进入时静默拿 openid（仅供支付/推送出方向，绝不用于身份认证）。
     * 流程与 actionWechat 一致，仅 scope 改为 snsapi_base；复用 auth_code → /api/wechat/wechat-info 换取。
     * 前端：window.location = apiroot + '/wechat/auth/openid&redirect_url=base64(当前页)&mall_id=xxx'
     */
    public function actionOpenid()
    {
        \Yii::$app->params['wechatConfig']['oauth']['scopes'] = ['snsapi_base'];
        WechatHelper::init($this->mall_id);
        $app = \Yii::$app->wechat->app;
        $code = $this->request->get('code');

        if (\Yii::$app->wechat->getIsWechat() && !$code) {
            $url = $app->getOAuth()->scopes(['snsapi_base'])
                ->redirect(ServerHelper::getHost() . $this->request->url);
            return \Yii::$app->response->redirect($url)->send();
        }
        $wechatUser = $app->getOAuth()->userFromCode($code);
        $raw = $wechatUser->getRaw(); // snsapi_base：{ openid, [unionid] }
        $redirect_url = $this->request->get('redirect_url');
        if ($redirect_url) {
            $redirect_url = base64_decode($redirect_url);
            $auth_code = \Yii::$app->security->generateRandomString();
            $redirect_url .= (str_contains($redirect_url, '?') ? '&' : '?') . 'auth_code=' . $auth_code;
            CacheHelper::set($auth_code, $raw, 20);
            return \Yii::$app->response->redirect($redirect_url)->send();
        }
        return \Yii::$app->response->redirect('/h5/#/pages/index/index?mall_id=' . $this->mall_id)->send();
    }

    public function actionWechat()
