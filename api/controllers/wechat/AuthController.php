    public function actionWechatLogin()
    {
        \Yii::$app->params['wechatConfig']['oauth']['scopes'] = ['snsapi_userinfo'];
        WechatHelper::init($this->mall_id);
        $app = \Yii::$app->wechat->app;
        $code = $this->request->get('code');
        if (\Yii::$app->wechat->getIsWechat() && !$code) {
            $url = $app->getOAuth()->scopes(['snsapi_userinfo'])
                ->redirect(ServerHelper::getHost() . $this->request->url);
            return \Yii::$app->response->redirect($url)->send();
        }
        $this->platform = ConstantHelper::PLATFORM_WECHAT;
        $wechatUser = $app->getOAuth()->userFromCode($code);
        $raw = $wechatUser->getRaw();
        $is_subscribe = 0;
        if ($raw) {
            $this->openId = $raw['openid'];
            $this->unionId = $raw['unionid'] ?? '';
            $this->pid = $this->request->get('pid');
            try {
                // V6 采用 client()->get() 访问基础接口
                $response = \Yii::$app->wechat->app->getClient()->get('cgi-bin/user/info', [
                    'query' => [
                        'openid' => $this->openId,
                        'lang' => 'zh_CN' // 可选
                    ]
                ]);
                $user_detail = $response->toArray();
                if ($user_detail && !empty($user_detail['subscribe'])) {
                    $is_subscribe = clone $user_detail['subscribe'] ? 1 : 0;
                }
            } catch (\Exception $e) {
                // 无权限或获取失败不阻塞主流程
            }
        }
        try {
            $user = $this->getUser($wechatUser);
        } catch (\Exception $e) {
            // 封禁 / 冷却期未满 / 保存失败 都会走到这里, 直接渲染错误页
            return $this->render($this->action->id, ['code' => 1, 'msg' => $e->getMessage()]);
        }
        if ($user && !$user->is_subscribe && $is_subscribe) {
            User::updateAll(['is_subscribe' => 1], ['id' => $user->id]);
        }
        $redirect_url = $this->request->get('redirect_url');
        if ($redirect_url) {
            $redirect_url = base64_decode($redirect_url);
            $auth_code = \Yii::$app->security->generateRandomString();
            if (str_contains($redirect_url, '?')) {
                $redirect_url .= '&auth_code=' . $auth_code;
            } else {
                $redirect_url .= '?auth_code=' . $auth_code;
            }
            CacheHelper::set($auth_code, $user->access_token, 20);
            return \Yii::$app->response->redirect($redirect_url)->send();
        }
        return \Yii::$app->response->redirect('/h5/#/pages/index/index?mall_id=' . $this->mall_id)->send();
    }

    public function actionMpwxLogin()
    {
        if ((!strpos($_SERVER["HTTP_USER_AGENT"], "MicroMessenger")) || (!strpos($_SERVER["HTTP_USER_AGENT"], "miniProgram"))) {
            echo "<script>alert('请在微信小程序中打开') </script>";
            die;
        }
        $this->platform = ConstantHelper::PLATFORM_MPWX;
        \Yii::$app->params['wechatConfig']['oauth']['scopes'] = ['snsapi_userinfo'];
        WechatHelper::init($this->mall_id);
        $app = \Yii::$app->wechat->app;
        $code = $this->request->get('code');
        $this->openId = $this->request->get('openId');
        $this->unionId = $this->request->get('unionId');
        $this->pid = $this->request->get('pid');
        if (\Yii::$app->wechat->getIsWechat() && !$code) {
            $url = $app->getOAuth()->scopes(['snsapi_userinfo'])
                ->redirect(ServerHelper::getHost() . $this->request->url);
            return \Yii::$app->response->redirect($url)->send();
        }
        $wechatUser = $app->getOAuth()->userFromCode($code);
        if (!$wechatUser) {
            return $this->render($this->action->id, ['code' => 1, 'msg' => '未获取到微信信息']);
        }
        if ($wechatUser) {
            try {
                $user = $this->getUser($wechatUser);
            } catch (\Exception $e) {
                return $this->render($this->action->id, ['code' => 1, 'msg' => $e->getMessage()]);
            }
            if (!$user) {
                return $this->render($this->action->id, ['code' => 1, 'msg' => '登录出现错误']);
            }
        }
        if ($this->pid) {
            if (!$user->parent_id || $user->parent_id == 0) { //没有上级 插入绑定队列
                JobHelper::push(new \app\jobs\user\BindParentJob(['user_id' => $user->id, 'parent_id' => $this->pid]));
            }
        }
        $level = OptionHelper::get('level_' . $user->level_id, $this->mall_id);
        $userData = $user->attributes;
        $userData['level_name'] = $level ? $level['name'] : '默认等级';
        return $this->render($this->action->id, ['code' => 0, 'msg' => '登录成功', 'access_token' => $user->access_token, 'user' => ['id' => $user->id, 'openid' => $user->openid, 'nickname' => $user->nickname, 'avatar_url' => $user->avatar_url, 'level_name' => $level ? $level['name'] : '默认等级']]);
    }


    /**
     * 绑定公众号推送通知（平台能力，不限于某个插件）
     *
     * 流程：
     *   小程序 WebView / H5 → GET /wechat/auth/bind-notification?user_token=xxx&mall_id=xxx
     *   → 微信 OAuth (snsapi_base)
     *   → 回调写入 User.wechat_openid + is_subscribe=1
     *   → 渲染结果页，页面调用 uni.postMessage + uni.navigateBack 通知小程序
     *
     * ⚠️ wechat_openid 只用于推送/支付出方向，绝不用于身份认证。
     */
    public function actionBindNotification()
    {
        WechatHelper::init($this->mall_id);
        $app  = \Yii::$app->wechat->app;
        $code = $this->request->get('code');

        if (!$code) {
            // ── 第一步：收到小程序发来的 user_token，缓存后跳转 OAuth ──
            // ⛔ 原来调的是 `User::findByAccessToken()` —— 这个方法在 User 上根本不存在
            //    （只有 IdentityInterface 的 findIdentityByAccessToken），第一步就 fatal，
            //    小程序 web-view 和 H5 两条绑定路径都是白屏。
            // ⛔ 空 token 必须先拦：库里有一批 access_token='' 的账号，按 token 查会随机匹到其中一个，
            //    等于把发起授权这个人的 openid 绑到陌生人账号上（他从此收到别人的推送）。
            $userToken = trim((string)$this->request->get('user_token', ''));
            $user = $userToken === '' ? null : User::findOne([
                'access_token' => $userToken,
                'mall_id'      => $this->mall_id,
                'is_delete'    => 0,
            ]);
            if (!$user) {
                return $this->render('bind-hw-notification', ['code' => 1, 'msg' => '登录已过期，请返回重试']);
            }

            // 用短期 nonce 传递 user_id，避免 token 暴露在 OAuth 回调 URL 里
            $nonce = \Yii::$app->security->generateRandomString(16);
            CacheHelper::set('hw_notify_bind_' . $nonce, $user->id, 300); // 5 分钟有效

            $callbackUrl = ServerHelper::getHost()
                . '/wechat/auth/bind-notification'
                . '?mall_id=' . $this->mall_id
                . '&state=' . $nonce;

            $url = $app->getOAuth()->scopes(['snsapi_base'])->redirect($callbackUrl);
            return \Yii::$app->response->redirect($url)->send();
        }

        // ── 第二步：OAuth 回调，保存 openid ──
        try {
            $wechatUser = $app->getOAuth()->userFromCode($code);
            $openid     = $wechatUser->getId();
        } catch (\Exception $e) {
            return $this->render('bind-hw-notification', ['code' => 1, 'msg' => '微信授权失败，请返回重试']);
        }

        $nonce  = $this->request->get('state', '');
        $userId = CacheHelper::get('hw_notify_bind_' . $nonce);
        if (!$userId) {
            return $this->render('bind-hw-notification', ['code' => 1, 'msg' => '授权已过期（超过5分钟），请返回重试']);
        }
        CacheHelper::delete('hw_notify_bind_' . $nonce);

        $user = User::findOne(['id' => $userId, 'mall_id' => $this->mall_id, 'is_delete' => 0]);
        if (!$user) {
            return $this->render('bind-hw-notification', ['code' => 1, 'msg' => '用户不存在']);
        }

        $user->wechat_openid = $openid;
        $user->is_subscribe  = 1;
        $user->save(false);

        return $this->render('bind-hw-notification', ['code' => 0, 'msg' => '']);
    }

    /**
     * 老路由别名：`bind-hw-notification`（名字带 hw 是因为最早只给智能奶瓶用）。
     * 已发布的小程序里 hardware 的 web-view 页写死了这个地址，**不能删**；新代码一律用 bind-notification。
     */
    public function actionBindHwNotification()
    {
        return $this->actionBindNotification();
    }

    /**
     * @param UserInterface $wechatUser
     * @return User
     * @throws \Exception 被拉黑 / 注销冷却期未满 / 保存失败时抛出, 调用方捕获并渲染错误
     */
    private function getUser(UserInterface $wechatUser)
    {
        // [修复] 查询不再过滤 is_delete=0, 否则已注销用户会走成"新用户注册",
        // 导致老账号余额/订单脱离, 且和 C 端注销页面"120 天可恢复"的承诺不一致
        $user = null;
        if ($this->unionId) {
            $user = User::findOne(['mall_id' => $this->mall_id, 'union_id' => $this->unionId]);
        }
        if (!$user) {
            $user = User::findOne(['mall_id' => $this->mall_id, 'openid' => $this->openId]);
        }

        if (!$user) {
            // 确实没老号, 走真正的新用户注册
            $user = new User();
            $user->mall_id = $this->mall_id;
            $user->nickname = $wechatUser->getNickname();
            $user->avatar_url = $wechatUser->getAvatar();
        } else {
            // 命中老号 -> 先走统一的封禁检查 (可能 lazy 自动解封)
            $banInfo = UserService::checkBanStatus($user);
            if ($banInfo !== null) {
                throw new \Exception($banInfo['msg']);
            }

            // 注销账户冷却期恢复 (和 LoginForm / MobileSignInForm 逻辑对齐)
            if ($user->status == User::STATUS_DELETE || $user->is_delete == 1) {
                if ($user->account_del_time) {
                    $deletedTimestamp = strtotime($user->account_del_time);
                    $coolDownSeconds = User::RE_REGISTER_COOL_DOWN_DAYS * 86400;
                    if (time() < ($deletedTimestamp + $coolDownSeconds)) {
                        throw new \Exception('账号注销冷却期未满（需' . User::RE_REGISTER_COOL_DOWN_DAYS . '天），请稍后再试。');
                    }
                }
                $user->is_delete = 0;
                $user->status = User::STATUS_NORMAL;
                $user->account_del_time = null;
                if (empty($user->mobile) && !empty($user->backup_mobile)) {
                    $user->mobile = $user->backup_mobile;
                    $user->backup_mobile = null;
                }
                \Yii::warning("微信 OAuth 激活已注销账户: {$user->id}");
            }

            if ($user->nickname == '微信用户') {
                $user->nickname = $wechatUser->getNickname();
                $user->avatar_url = $wechatUser->getAvatar();
            }
        }
        if ($this->unionId) {
            $user->union_id = $this->unionId;
        }
        $user->openid = $this->openId;
        $user->platform = $this->platform;
        $user->current_platform = $this->platform;
        $user->login_ip = $_SERVER["REMOTE_ADDR"];
        $user->access_token = \Yii::$app->security->generateRandomString();
        $user->auth_key = \Yii::$app->security->generateRandomString();
        if (!$user->save()) {
            $firstErr = $user->getFirstErrors();
            throw new \Exception(current($firstErr) ?: '用户保存失败');
        }
        return $user;
    }
