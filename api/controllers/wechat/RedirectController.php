namespace app\controllers\wechat;


use app\controllers\BaseController;
use app\helpers\ServerHelper;
use yii\web\Response;

/**
 * Class AuthController
 * @package app\controllers\wechat
 * 微信公众号授权登录专用控制器
 */
class RedirectController extends BaseController
{

    public $layout = false;
    private $openId;
    private $pid;
    private $unionId;
    private $platform;

    public function beforeAction($action)
    {
        \Yii::$app->response->format = Response::FORMAT_HTML;
        return parent::beforeAction($action); // TODO: Change the autogenerated stub
    }

    /**
     * H5 分享链接中转:前端把真实页面地址 base64 后挂在 id 上,这里解出来跳过去。
     * 存在的意义是让分享出去的链接落在微信 JS 安全域名下(否则 updateAppMessageShareData 不认)。
     *
     * ⚠ 本入口**公开无鉴权**,id 完全由外部控制,必须当不可信输入处理。原实现两个洞:
     *  1) 直接 `echo "<script>...replace('$url')...</script>"` 把解码内容拼进 JS 字符串 ——
     *     构造 id = base64("');alert(document.cookie);//") 即可在**本域**执行任意 JS,
     *     而 admin/mch 的会话 cookie 就在本域,等同会话劫持;
     *  2) 目标地址零校验 → 可做成「域名是自家、点开跳钓鱼站」的开放重定向,在微信里传播极具迷惑性。
     *
     * 现改为:严格 base64 解码 → 只允许 http/https → 主机名必须在白名单内 → 302 跳转。
     * 走 Location 头而不再输出 HTML/JS,从根上消除注入面。
     */
    public function actionH5()
    {
        $id = $this->request->get('id');
        if (!$id) {
            return $this->redirect('/h5');
        }

        // 严格模式:含非 base64 字符即判非法,顺带挡掉大部分构造流量
        $url = base64_decode((string) $id, true);
        if ($url === false || trim($url) === '') {
            \Yii::warning('[分享中转] id 不是合法 base64,已拒绝', 'share');
            return $this->redirect('/h5');
        }
        $url = trim($url);

        if (!$this->isAllowedTarget($url)) {
            // error 级别:正常分享不会走到这里 —— 要么域名白名单漏配,要么有人在打这个入口
            \Yii::error('[分享中转] 目标地址不在白名单,已拒绝: ' . mb_substr($url, 0, 300), 'share');
            return $this->redirect('/h5');
        }

        return $this->redirect($url);
    }

    /**
     * 目标是否可跳转:只认 http/https + 主机名在白名单内。
     * javascript:/data: 这类伪协议会因 scheme 不匹配被挡;
     * `//evil.com` 这种协议相对地址 parse_url 出来没有 scheme,同样被挡。
     */
    private function isAllowedTarget(string $url): bool
    {
        $parts = parse_url($url);
        if ($parts === false || empty($parts['scheme']) || empty($parts['host'])) {
            return false;
        }
        if (!in_array(strtolower($parts['scheme']), ['http', 'https'], true)) {
            return false;
        }
        // 拒绝带 userinfo 的地址(https://evil.com@ourhost/)。
        // 它的真实 host 其实是 @ 之后那个,并不构成开放重定向,但分享链接里用不到 userinfo,
        // 而不同客户端/代理对它的解析并不一致 —— 留着只会是混淆面,直接拒掉。
        if (isset($parts['user']) || isset($parts['pass'])) {
            return false;
        }
        return in_array(strtolower($parts['host']), $this->allowedHosts(), true);
    }

    /**
     * 白名单主机 = 本次请求域名 + APP_URL 配置域名 + option 里的 domain。
     * H5 与接口同域部署时(manifest 的 router.base=/h5/ 就是这种形态)天然覆盖;
     * 若 H5 用独立域名,把它配到 .env 的 APP_URL 或 option 的 domain 即可。
     */
    private function allowedHosts(): array
    {
        $hosts = [];

        // 请求域名:仅 Web 上下文有 hostInfo,控制台/队列里取不到,不能直接访问
        $req = \Yii::$app->has('request') ? \Yii::$app->request : null;
        if ($req instanceof \yii\web\Request) {
            try {
                $h = $this->hostOf((string) $req->hostInfo);
                if ($h !== '') {
                    $hosts[] = $h;
                }
            } catch (\Throwable $e) {
                // 某些反代配置下 hostInfo 会抛,忽略,后面还有 APP_URL 兜底
            }
        }
        $h = $this->hostOf((string) ServerHelper::getHost());
        if ($h !== '') {
            $hosts[] = $h;
        }
        try {
            $domain = \app\helpers\OptionHelper::get('domain');
            if (is_string($domain) && $domain !== '') {
                // option 里可能只存裸域名(无协议),补上再解析
                $h = $this->hostOf(preg_match('#^https?://#i', $domain) ? $domain : 'https://' . $domain);
                if ($h !== '') {
                    $hosts[] = $h;
                }
            }
        } catch (\Throwable $e) {
            // 读配置失败不该让分享全挂,前两项已覆盖同域部署
        }

        return array_values(array_unique(array_filter($hosts)));
    }

    private function hostOf(string $url): string
    {
        if ($url === '') {
            return '';
        }
        $host = parse_url($url, PHP_URL_HOST);
        return $host ? strtolower($host) : '';
    }
}
