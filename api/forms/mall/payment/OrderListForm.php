namespace app\forms\mall\payment;

use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\CommonPayOrder;
use app\models\User;

class OrderListForm extends BaseModel
{

    public $order_no;

    public $search_date;

    public $payment;


    public function rules()
    {
        return [
            [['order_no', 'search_date', 'payment'], 'safe']
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        $query = CommonPayOrder::find()->alias('o')
            ->leftJoin(['u' => User::tableName()], 'u.id=o.user_id')
            // 不带 mall_id 的话这里列的是全平台已支付订单(还 join 出了昵称和头像),
            // 任一商城的运营都能看到别家商城的支付流水。
            ->where(['o.is_delete' => 0, 'o.is_pay' => 1, 'o.mall_id' => \Yii::$app->mall->id]);
        if ($this->order_no) {
            $query->andWhere(['like', 'o.order_no', $this->order_no]);
        }
        if ($this->search_date) {
            $query->andWhere(['like', 'o.created_time', $this->search_date]);
        }
        if ($this->payment) {
            $query->andWhere(['o.payment' => $this->payment]);
        }
        // 🔒 不能用 `o.*`:那会把 payment_config(含 merchantPrivateKey 签名私钥)、key
        // (pay_data_key,等同一次性支付凭证)、pay_openid 一起发到后台前端。
        // asArray() 绕过模型的 fields()/getHiddenFields(),这里只能显式列字段。
        // 下面这份清单 = admin/src/views/payment/order.vue 实际渲染的列 + 定位/审计需要的标识列。
        // 新增列要在这里显式加,别图省事改回 o.*。
        $list = $query->select([
            'o.id', 'o.mall_id', 'o.order_no', 'o.out_trade_no', 'o.user_id',
            'o.order_id', 'o.order_class', 'o.pay_price', 'o.total_price',
            'o.payment', 'o.transaction_id', 'o.platform', 'o.remarks', 'o.err_msg',
            'o.is_pay', 'o.pay_at', 'o.is_cancel', 'o.cancel_at', 'o.expire_at',
            'o.is_refund', 'o.refund_at', 'o.refund_price', 'o.refund_remarks',
            'o.refund_order_no', 'o.is_refund_fail', 'o.is_need_refund',
            'o.is_push_wechat', 'o.push_errors', 'o.push_retry_count',
            'o.created_at', 'o.created_time', 'o.updated_at',
            'u.nickname', 'u.avatar_url',
        ])
            ->orderBy('o.id DESC')
            ->page($pagination)
            ->asArray()
            ->all();
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagination]);
    }
}