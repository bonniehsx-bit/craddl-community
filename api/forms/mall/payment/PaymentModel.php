namespace app\forms\mall\payment;

use app\core\ApiCode;
use app\helpers\OptionHelper;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\payments\BasePayment;

class PaymentModel extends BaseModel
{
    public $payment;

    public function rules()
    {
        return [
            [['setting'], 'safe'],
        ]; // TODO: Change the autogenerated stub
    }

    public function init()
    {
        parent::init(); // TODO: Change the autogenerated stub
        // ⛔ 从没配过支付方式的商城,OptionHelper::get 返回的是 **null** 而不是空数组。
        //    生产是 PHP 8.4,读 null 下标和 foreach(null) 都会被 Yii 的 ErrorHandler
        //    转成 ErrorException —— 不是 warning,是接口直接 500。
        //    实测:新商城打开任意一个支付方式配置页必然 500。
        $this->payment = OptionHelper::get('payments', $this->mall_id) ?: [];
    }

    public function getPayment($payType)
    {
        // 该网关没配过时返回空数组,让前端拿到一份空表单而不是 500
        return $this->payment[$payType] ?? [];
    }

    public function getPaymentList()
    {
        $paymentList = [];
        foreach ($this->payment as $key => $value) {
            /**
             * @var BasePayment $payment
             */
            try {
                $payment = \Yii::createObject($key, [$this->mall_id]);
                $paymentList[] = $payment->getDisplay();
            } catch (\Exception $exception) {

            }
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['payments' => $paymentList]);
    }
}