namespace app\forms\mall\order;


use app\core\ApiCode;
use app\helpers\ExpressHelper;
use app\helpers\Json;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\Order;

class ExcelSendForm extends BaseModel
{


    public $excel_data;

    public function rules()
    {
        return [
            [['excel_data'], 'string']
        ]; // TODO: Change the autogenerated stub
    }

    private $expressCache = null;

    /**
     * 批量导入发货。
     *
     * 这里原先是**另写一份发货逻辑**:直接 $order->status = STATUS_SHIPPED 就算发完了。
     * 结果是绕过了单笔发货的全部约定 —— 不校验订单是不是待发货(关闭/未付款的单也能发)、
     * 不校验同城配送、不问插件能不能发(未开奖的拼团单能被整表发出去)、
     * 不回写 order_detail 的 is_send 与 express_log_id(明细永远显示未发货)、
     * 不设置 delivery_status、更不触发发货事件(买家收不到发货通知,
     * 靠 EVENT_ORDER_SHIPPED 驱动的插件全部失效)。
     *
     * 现在收口到 OrderShipmentService,和后台单笔发货同一条路。分两趟走:
     *   ① 校验趟:全表先过一遍 assertShippable,任何一行不合格就整体拒绝,一件货都不发。
     *      Excel 是人工填的,错行是常态,不能发到一半才报错。
     *   ② 执行趟:逐单发货,各自独立事务 + 各自触发事件。
     * 不把执行趟包在一个大事务里,是因为发货事件必须在提交后触发;
     * 套一层外部事务会让事件在外层提交之前就发出去,通知发了货却可能回滚。
     */
    public function send()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        try {
            $list = Json::decode($this->excel_data);
            if (empty($list)) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '暂无发货数据！');
            }

            $service = new \app\services\order\actions\OrderShipmentService();
            $tasks = [];

            // ───────── ① 校验趟:只读,不写任何东西 ─────────
            foreach ($list as $item) {
                // 跳过空行数据
                if (empty($item['订单ID']) || empty($item['快递单号']) || empty($item['快递名称'])) {
                    continue;
                }

                // 订单ID 直接来自上传的 Excel,是完全可控的外部输入。不带 mall_id 的话,
                // 表格里填上别家商城的订单ID 就能把人家的订单改成「已发货」。
                // 查不到就报「订单不存在」——正好也不泄露别家订单的存在性。
                $order = Order::findOne([
                    'id' => $item['订单ID'],
                    'mall_id' => \Yii::$app->mall->id,
                ]);
                if (!$order) {
                    throw new \Exception('订单不存在：ID ' . $item['订单ID']);
                }
                // 已发货的单单独给一句更好懂的话,不然会落到「订单不是待发货状态」
                if ($order->status == Order::STATUS_SHIPPED) {
                    throw new \Exception('订单：' . $order->order_no . '已发货，请检查');
                }
                // 两道守门人都要在校验趟跑完,不能留到执行趟才发现 ——
                // 否则表格里第 50 行有问题时,前 49 单的货已经发出去了
                $service->assertShippable($order);            // 状态 / 同城 / 静态名单
                $service->assertManualShipAllowed($order);    // 插件按单封印(未开奖的拼团单等)

                $tasks[] = [
                    'order' => $order,
                    'name' => $item['快递名称'],
                    'no' => strval($item['快递单号']),
                ];
            }

            if (empty($tasks)) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '暂无发货数据！');
            }

            // ───────── ② 执行趟:逐单发货 ─────────
            $done = 0;
            foreach ($tasks as $t) {
                try {
                    // sendType=0 整单发货。收件人信息由服务端从订单本身取,
                    // 不用 Excel 里那几列 —— 表格可能是旧的,订单才是权威。
                    // getExpress 查不到会自动建一条快递公司(写库),所以放在执行趟,
                    // 别让「只是校验一下」留下数据
                    $express = $this->getExpress($t['name']);
                    $service->ship($t['order'], 0, [], $t['name'], $express ? $express['code'] : '', $t['no']);
                    $done++;
                } catch (\Throwable $e) {
                    // 校验趟已经全过了,走到这里基本是并发或数据库异常。
                    // 前面成功的不回滚(它们已提交且已发通知),据实报告发到第几单。
                    \Yii::error('批量发货中断,已成功 ' . $done . ' 单: ' . $e->getMessage());
                    return ResponseHelper::send(
                        ApiCode::CODE_FAIL,
                        '已成功发货 ' . $done . ' 单，处理到订单 ' . $t['order']->order_no
                            . ' 时中断：' . $e->getMessage() . '。请核对后重新导入剩余部分。'
                    );
                }
            }

            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '发货完成！共 ' . $done . ' 单');
        } catch (\Exception $e) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, $e->getMessage());
        }
    }

    private function getExpress($express_name)
    {
        if (empty($express_name)) {
            return null;
        }

        // 引入本地变量缓存，防止在 1000 条订单循环下把数据库打死（N+1查询）
        if ($this->expressCache === null) {
            $this->expressCache = ExpressHelper::express();
        }

        foreach ($this->expressCache as $item) {
            if ($item['name'] == $express_name) {
                return $item;
            }
        }

        // 核心：如果不存该快递公司，自动帮用户入库补充，同时防止同一批次不断重复插入
        $express = new \app\models\Express();
        $express->mall_id = 0; // 全局通用
        $express->name = $express_name;
        $express->code = '';
        $express->key = '';
        $express->ali_key = '';
        $express->r_datas = '[{"style":"默认风格","spec":"默认风格","size":"150","isdefault":1}]';
        $express->sort = 100;

        if ($express->save()) {
            $newItem = $express->toArray();
            $this->expressCache[] = $newItem;
            return $newItem;
        }

        return null;
    }
}
