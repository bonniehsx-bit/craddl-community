namespace app\forms\mall\order;


use app\core\ApiCode;
use app\models\BaseModel;
use app\models\Order;

class OrderAddressModifyForm extends BaseModel
{

    public $name;
    public $mobile;
    public $address;
    public $order_id;


    public function rules()
    {
        return [
            [['mobile', 'address', 'name', 'order_id'], 'required'],
            [['order_id'], 'integer'],
            [['address', 'name', 'mobile'], 'string'],

        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // 只认主键会跨商城:order_id 是前端传的,不带 mall_id 就等于任一商城的运营
        // 都能改别家订单的收货地址(改完直接发货到指定地址)。租户边界必须在查询里。
        $order = Order::findOne([
            'is_delete' => 0,
            'id' => $this->order_id,
            'mall_id' => \Yii::$app->mall->id,
        ]);
        if (!$order) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '订单不存在，或已被删除');
        }
        $order->name = $this->name;
        $order->mobile = $this->mobile;
        $order->address = $this->address;

        if (!$order->save()) {
            return $this->responseErrorMsg($order);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');
    }
}
