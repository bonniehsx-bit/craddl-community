namespace app\forms\mall\goods;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\helpers\UserHelper;
use app\models\BaseModel;
use app\models\GoodsComment;
use yii\helpers\Json;

class CommentForm extends BaseModel
{
    public $id;
    public $goods_id;
    public $user_id;
    public $content;
    public $pic_list;
    public $grade_level;


    public function rules()
    {
        return [
            [['id', 'goods_id', 'user_id', 'content', 'pic_list', 'grade_level'], 'trim'],
            [['id'], 'integer'],
        ]; // TODO: Change the autogenerated stub
    }

    public function delete()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $comment = GoodsComment::getOne($this->id);
        if (!$comment) {
            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '删除成功');
        }
        if (!$comment->is_second) {
            $second = GoodsComment::findOne(['user_id' => $comment->user_id, 'is_second' => 1, 'order_id' => $comment->order_id, 'goods_id' => $comment->goods_id, 'is_delete' => 0]);
            if ($second) {
                $second->is_second = 0;
                $second->save();
            }
        }
        $comment->is_delete = 1;
        $comment->save();
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '删除成功');
    }

    public function save()
    {
        $comment = new GoodsComment();
        $comment->mall_id = $this->mall_id;
        $comment->goods_id = $this->goods_id;
        $comment->user_id = $this->user_id;
        $comment->content = $this->content;
        if ($this->pic_list) {
            if (is_string($this->pic_list)) {
                $decoded = json_decode($this->pic_list, true);
                if (json_last_error() === JSON_ERROR_NONE && is_array($decoded)) {
                    $this->pic_list = $decoded;
                } else {
                    // 兼容旧逻辑或非JSON字符串
                    $this->pic_list = explode(',', $this->pic_list);
                }
            }
        } else {
            $this->pic_list = [];
        }
        $comment->pic_list = Json::encode($this->pic_list);
        $comment->grade_level = $this->grade_level;
        if (!$comment->save()) {

            return $this->responseErrorMsg($comment);
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '保存成功');
    }
}
