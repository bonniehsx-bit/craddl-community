namespace app\forms\mall\finance;


use app\core\ApiCode;
use app\models\Admin;
use app\models\BaseModel;
use app\models\ChargeLog;
use app\models\PriceLog;
use app\models\User;

class ChargeListForm extends BaseModel
{
    public $page;
    public $limit;
    public $keyword;
    public $user_id;
    public $type;
    public $nickname;
    public $search_date;
    public $is_export;


    public function rules()
    {
        return [
            [['search_date'], 'safe'],
            [['nickname'], 'string'],
            [['page', 'limit', 'user_id', 'type', 'is_export'], 'integer'],
            [['keyword'], 'string'],
            [['limit'], 'default', 'value' => 10]

        ]; // TODO: Change the autogenerated stub
    }


    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $query = ChargeLog::find()
            ->alias('c')
            ->leftJoin(['u' => User::tableName()], 'u.id=c.user_id')
            // ⚠ 商城隔离:漏了这一条,本商城后台会列出全平台所有商城的充值记录(串号)
            ->andWhere(['c.mall_id' => \Yii::$app->mall->id])
            ->andWhere(['c.is_delete' => 0, 'u.is_delete' => 0]);
        if ($this->type != '') {
            if ($this->type == 0) {
                $query->andWhere(['type' => 0]);
            }
            if ($this->type == 1) {
                $query->andWhere(['type' => 1]);
            }
            if ($this->type == 2) {
                $query->andWhere(['type' => 2]);
            }
        }
        if ($this->keyword) {
            $query->andWhere(['like', 'u.nickname', $this->keyword]);
        }

        if ($this->nickname) {
            $query->andWhere(['like', 'u.nickname', $this->nickname]);
        }
        if ($this->user_id) {
            $query->andWhere(['c.user_id' => $this->user_id]);
        }

        if ($this->search_date) {
            $begin_at = strtotime($this->search_date[0]);
            $end_at = strtotime($this->search_date[1]);
            $query->andWhere(['>=', 'c.created_at', $begin_at]);
            $query->andWhere(['<=', 'c.created_at', $end_at]);
        }

        if ($this->is_export) {
            $list = $query
                ->select('u.nickname,u.avatar_url,c.*')
                ->orderBy('c.id DESC')
                ->asArray()->all();
        } else {
            $list = $query->page($pagination, $this->limit, $this->page)
                ->select('u.nickname,u.avatar_url,c.*')
                ->orderBy('c.id DESC')
                ->asArray()->all();
        }

        foreach ($list as &$item) {

            if ($item['after_num'] > $item['before_num']) {
                $item['charge_type'] = '增加';
            } else {
                $item['charge_type'] = '减少';
            }

            $item['created_at'] = date('Y-m-d H:i:s', $item['created_at']);
            $admin = Admin::findOne($item['admin_id']);
            if ($admin) {
                $item['admin'] = $admin->name;
            } else {
                $item['admin'] = '-';
            }
        }
        unset($item);
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagination]);
    }
}
