namespace app\forms\mall\finance;

use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\RefundFailLog;

class RefundRetryForm extends BaseModel
{
    public $id;

    public function rules()
    {
        return [

            [['id'], 'integer'],
        ]; // TODO: Change the autogenerated stub
    }

    public function retry()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // ⚠ mall_id 是越权闸门,不能少:只按 id 查的话,A 商城管理员传一个 B 商城的 id
        // 就能对别人商城的退款发起重试。眼下 retry 逻辑是空的所以没出事,
        // 等谁把真实退款动作补上,这里就是一个跨商城资金操作口子。
        $model = RefundFailLog::findOne([
            'status' => [0, 1],
            'id' => $this->id,
            'mall_id' => \Yii::$app->mall->id,
        ]);
        if (!$model) {
            return $this->responseErrorInfo($model);
        }
        //退款失败重试的逻辑还没有实现
        return ResponseHelper::send(ApiCode::CODE_FAIL, '失败重试的逻辑还未实现');
    }
}
