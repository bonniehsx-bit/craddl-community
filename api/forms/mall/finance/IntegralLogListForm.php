namespace app\forms\mall\finance;


use app\core\ApiCode;
use app\models\BaseModel;
use app\models\IntegralLog;
use app\models\IntegralPriceLog;
use app\models\PriceLog;
use app\models\User;

class IntegralLogListForm extends BaseModel
{
    public $page;
    public $limit;
    public $keyword;
    public $user_id;
    public $nickname;
    public $content;
    public $is_export;
    public $search_date;
    /** 业务类型筛选(order_base/exchange/parking_deduct/expire...,见 IntegralTypeRegistry) */
    public $biz_type;

    public function rules()
    {
        return [
            [['search_date'], 'safe'],
            [['page', 'limit', 'is_export', 'user_id', 'is_export'], 'integer'],
            [['keyword'], 'string'],
            [['nickname', 'content', 'biz_type'], 'string'],
            [['limit'], 'default', 'value' => 10]
        ]; // TODO: Change the autogenerated stub
    }


    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        $query = IntegralLog::find()
            ->alias('l')
            ->leftJoin(['u' => User::tableName()], 'u.id=l.user_id')
            // ⚠ 商城隔离:漏了这一条,本商城后台会列出全平台所有商城的积分流水(串号)
            ->andWhere(['l.mall_id' => \Yii::$app->mall->id])
            ->andWhere(['l.is_delete' => 0, 'u.is_delete' => 0]);
        if ($this->keyword) {
            $query->andWhere(['like', 'l.content', $this->keyword]);
        }
        if ($this->user_id) {
            $query->andWhere(['l.user_id' => $this->user_id]);
        }
        if ($this->nickname) {
            $query->andWhere(['like', 'u.nickname', $this->keyword]);
        }
        if ($this->biz_type) {
            $query->andWhere(['l.biz_type' => $this->biz_type]);
        }
        if ($this->search_date) {
            $start_at = strtotime($this->search_date[0]);
            $end_at = strtotime($this->search_date[1]);
            $query->andWhere(['>=', 'l.created_at', $start_at]);
            $query->andWhere(['<=', 'l.created_at', $end_at]);
        }
        // 导出走全量不分页;$pagination 需先初始化,否则导出分支会 Undefined variable
        $pagination = null;
        if (!$this->is_export) {
            $query->page($pagination, $this->limit, $this->page);
        }

        $list = $query
            ->select('u.nickname,u.avatar_url,l.*')
            ->orderBy('l.id DESC')
            ->asArray()->all();
        // 业务类型中文名:走开放注册表(插件登记),未登记的回落原始 key,不硬编码枚举
        $typeMap = \app\services\IntegralTypeRegistry::getTypeMap((int) (\Yii::$app->mall->id ?? 0));
        foreach ($list as &$item) {
            $item['created_at'] = date('Y-m-d H:i:s', $item['created_at']);
            $bt = (string) ($item['biz_type'] ?? '');
            $item['biz_type_name'] = $bt === '' ? '' : ($typeMap[$bt] ?? $bt);
        }
        unset($item);
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', [
            'list' => $list,
            'pagination' => $pagination,
            'biz_types' => $typeMap, // 供前端筛选下拉(不含历史空值)
        ]);
    }
}
