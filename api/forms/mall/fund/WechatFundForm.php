namespace app\forms\mall\fund;

use app\core\ApiCode;
use app\funds\ManualFund;
use app\funds\WechatFund;
use app\helpers\OptionHelper;
use app\helpers\ResponseHelper;
use app\helpers\WechatPayHelper;
use yii\base\Exception;
use yii\helpers\FileHelper;


class WechatFundForm extends FundModel
{
    public $setting;

    public function rules()
    {
        return [
            [['setting'], 'safe'],
        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        $fund = $this->fund;
        $this->setting['fund_type'] = WechatFund::class;
        $fund[WechatFund::class] = $this->setting;
        OptionHelper::set('funds', $fund, \Yii::$app->mall->id);
        $mpwx = $this->setting['mpwx'];
        $wechat = $this->setting['wechat'];
        if (!is_writeable(\Yii::$app->runtimePath)) {
            chmod(\Yii::$app->runtimePath, 0755);
        }
        $pemDir = \Yii::$app->runtimePath . '/pem';
        if (!is_dir($pemDir)) {
            try {
                FileHelper::createDirectory($pemDir, 0755);
            } catch (Exception $e) {
                \Yii::warning($e->getMessage());
            }
        }
        if ($mpwx) {
            if ($mpwx['cert_pem']) {
                $certPemFile = WechatPayHelper::getApiclientCertPemPath($mpwx['mchid']);
                file_put_contents($certPemFile, $mpwx['cert_pem']);
            }
            if ($mpwx['key_pem']) {
                $keyPemFile = WechatPayHelper::getApiclientKeyPemPath($mpwx['mchid']);
                file_put_contents($keyPemFile, $mpwx['key_pem']);
            }
            if ($mpwx['pub_key']) {
                $pubKeyFile = WechatPayHelper::getWechatPlatformPubKeyPath($mpwx['mchid']);
                file_put_contents($pubKeyFile, $mpwx['pub_key']);
            }
        }
        if ($wechat) {
            if ($wechat['cert_pem']) {
                $certPemFile = WechatPayHelper::getApiclientCertPemPath($wechat['mchid']);
                file_put_contents($certPemFile, $wechat['cert_pem']);
            }
            if ($wechat['key_pem']) {
                $keyPemFile = WechatPayHelper::getApiclientKeyPemPath($wechat['mchid']);
                file_put_contents($keyPemFile, $wechat['key_pem']);
            }
            if ($wechat['pub_key']) {
                $pubKeyFile = WechatPayHelper::getWechatPlatformPubKeyPath($wechat['mchid']);
                file_put_contents($pubKeyFile, $wechat['pub_key']);
            }
        }

        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '保存成功');
    }

    public function search()
    {
        $this->setting = $this->getFund(WechatFund::class);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', $this->setting);
    }
}