    public function save()
    {

        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        if (!$this->appid || !$this->secret || !$this->name) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '请完善必填信息');
        }
        // 注入字段 / 版本号 / 描述 仅上传用，不写入配置（保证版本号默认留空→自动生成）
        $attrs = $this->attributes;
        unset($attrs['inject_mall_id'], $attrs['inject_domain'], $attrs['version'], $attrs['desc']);
        OptionHelper::set('platform_mpwx', $attrs, \Yii::$app->mall->id);
        if ($this->appid) {
            OptionHelper::set($this->appid, ['platform' => ConstantHelper::PLATFORM_MPWX, 'mall_id' => $this->mall_id], \Yii::$app->mall->id);
        }

        $jumpPath = 'others/order/order'; // <-- [重要] 请改成您的小程序订单列表页路径!

        Yii::warning("开始设置小程序订单跳转路径: {$jumpPath}");
        $res = \app\helpers\WechatHelper::set_msg_jump_path($jumpPath, $this->mall_id);

        if (isset($res['errcode']) && $res['errcode'] == 0) {
            Yii::warning("设置小程序订单跳转路径成功。");
        } else {
            Yii::error("设置小程序订单跳转路径失败: " . json_encode($res, JSON_UNESCAPED_UNICODE));
        }

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');
    }


    /**
     * 规范化插件配置 → app.json 的 plugins 结构。
     *
     * 口径就一条:**填了 provider 才算数**。运营在页面上留空的行、或者只填了版本没填 AppID 的行,
     * 一律当没配 —— 宁可不注入(功能不可用),也不能注入一个残缺声明(整个小程序传不上去)。
     *
     * @return array {alias: {version, provider}}
     */
    /**
     * ⛔ 插件声明**一律注入 app.json 顶层(主包)**,不再支持落到分包。
     *
     * 曾经支持过「归属分包」,动机是省主包体积:微信按**声明位置**算插件体积,
     * 写进分包就不占主包。但那条路有个致命前提没人说破 ——
     * **分包里声明的插件,主包代码 `requirePlugin()` 拿不到。**
     *
     * 真实事故:无感积分插件配了 `subpackage=plugins`,因为当时只有
     * `plugins/plaza/auth` 这个页面用它。后来位置上报按微信文档移进 `App.vue` 的
     * onShow(插件文档硬要求在 app.js 里调),那是**主包**,requirePlugin 当场拿不到,
     * 被 try/catch 吞掉只剩一行 console.warn。结果:上传成功、后台配置齐全、
     * 授权流程正常,唯独位置一次都没报上去 —— 微信判不出顾客在场内,
     * 支付通知一条不推,无感积分整条链静默失效。查了很久才定位到这里。
     *
     * 两种配错的代价根本不对等:
     *   放主包放不下 → 上传直接报 "main package source size exceed max limit",**当场知道**
     *   放分包用不了 → 一切正常,功能就是不工作,**没有任何地方会报错**
     * 所以宁可去挤主包体积,也不留这个会静默失效的选项。要腾地方就把
     * 只被单个分包使用的组件下沉到那个分包(见 uniapp/pages.json 的 easycom 精确规则)。
     */

    public static function normalizePlugins($raw): array
    {
        if (!is_array($raw)) {
            return [];
        }
        $out = [];
        foreach ($raw as $i => $row) {
            if (!is_array($row)) {
                continue;
            }
            $provider = trim((string)($row['provider'] ?? ''));
            if ($provider === '') {
                continue;   // 没填 AppID = 没配
            }
            $alias = trim((string)($row['alias'] ?? ''));
            if ($alias === '') {
                $alias = 'plugin' . ($i + 1);   // 兜底别名,保证 key 不冲突
            }
            $version = trim((string)($row['version'] ?? ''));
            $out[$alias] = [
                'version'  => $version !== '' ? $version : 'latest',
                'provider' => $provider,
            ];
        }
        return $out;
    }

    public function search()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $mpwx = OptionHelper::get('platform_mpwx', \Yii::$app->mall->id);
        if (!$mpwx) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '未配置小程序');
        }
        // 本次上传会带哪些插件 —— 声明是上传这一刻注入的,事后从代码包里看不出来,
        // 上传前把实际生效值摆出来,免得运营在"以为带了/以为没带"之间踩坑
        // (没申请到授权却注入 = 该小程序直接传不上去)。
        $mallId = (int)\Yii::$app->mall->id;

        // 当前商城ID / 后端域名 / 主框架当前版本号，供前端「指定域名 / mall_id / 版本号」字段做默认值
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', [
            'mpwx'            => $mpwx,
            'current_mall_id' => $mallId,
            'current_domain'  => rtrim(ServerHelper::getHost(), '/'),
            'current_version' => app_version(),
            // 原始数组供表单编辑;规范化结果供「本次上传会注入什么」预览(填了 provider 才算)
            'plugins'         => is_array($mpwx['plugins'] ?? null) ? $mpwx['plugins'] : [],
            'plugins_preview' => self::normalizePlugins($mpwx['plugins'] ?? []),
            // 「配置改了但没重传」告警 —— 插件声明只在**上传那一刻**注入 app.json,
            // 事后改配置对已经在线上跑的代码包**没有任何影响**。而后端的
            // BcSettingHelper::pluginReady() 只看配置,于是 C 端会照常渲染授权按钮、
            // 跳 plugin://别名/index,而线上包的 app.json 里根本没有这个插件 ——
            // 微信解析不了就当成跨小程序跳转,报
            // "<navigator/> should have app-id ... when using navigate with miniProgram target"。
            // 这个错在后台完全看不出来,只能靠这条提示提前拦住。
            'plugin_stale'    => self::pluginConfigStale($mallId),
            // 可选分包 + 各自余量,给「归属分包」做下拉。手输分包名极易打错,
            // 而打错要等上传失败才知道;顺带把余量算出来,运营一眼就知道该往哪放。
            'subpackages'     => self::listSubpackages(),
        ]);
    }

    /**
     * 代码包里有哪些分包,各自多大、还剩多少余量。
     *
     * 体积用「文件实际字节数」算 —— 这与微信卡的 source size 同口径(它量的是编译后的
     * 源码体积,不是压缩包)。主包同样列出来:插件不填分包就落顶层、体积记到主包头上,
     * 得让运营看见主包还剩多少才敢留空。
     *
     * @return array [{root, size_kb, free_kb, is_main}]
     */
    public static function listSubpackages(): array
    {
        $limitKb = 2048;   // 微信:单个包 source size 上限 2MB
        $base = \Yii::getAlias('@webroot') . '/mp-weixin';
        $ajFile = $base . '/app.json';
        if (!is_file($ajFile)) {
            return [];     // 代码包还没上传,前端降级成手输
        }
        $aj = json_decode((string)file_get_contents($ajFile));
        if (!$aj instanceof \stdClass) {
            return [];
        }

        $dirSize = function (string $dir): int {
            if (!is_dir($dir)) {
                return 0;
            }
            $sum = 0;
            $it = new \RecursiveIteratorIterator(
                new \RecursiveDirectoryIterator($dir, \FilesystemIterator::SKIP_DOTS)
            );
            foreach ($it as $f) {
                if ($f->isFile()) {
                    $sum += $f->getSize();
                }
            }
            return $sum;
        };

        $roots = [];
        $out = [];
        foreach (($aj->subPackages ?? []) as $sp) {
            $root = trim((string)($sp->root ?? ''), '/');
            if ($root === '') {
                continue;
            }
            $roots[] = $root;
            $kb = (int)round($dirSize($base . '/' . $root) / 1024);
            $out[] = [
                'root'    => $root,
                'size_kb' => $kb,
                'free_kb' => $limitKb - $kb,
                'is_main' => false,
            ];
        }

        // 主包 = 整包 - 所有分包
        $totalKb = (int)round($dirSize($base) / 1024);
        $subKb = array_sum(array_column($out, 'size_kb'));
        $mainKb = max(0, $totalKb - $subKb);
        array_unshift($out, [
            'root'    => '',
            'size_kb' => $mainKb,
            'free_kb' => $limitKb - $mainKb,
            'is_main' => true,
        ]);
        return $out;
    }

    /**
     * 插件配置是否「改过但还没重新上传」。
     *
     * 判据:`platform_mpwx` 的最后修改时间 > 最后一次**成功**上传的时间。
     * 返回 null 表示无需提醒(没配插件 / 从没上传过 / 已是最新)。
     *
     * @return array|null ['config_at'=>..., 'upload_at'=>..., 'last_injected'=>'上次上传带的插件']
     */
    public static function pluginConfigStale(int $mallId): ?array
    {
        $decl = self::normalizePlugins(OptionHelper::get('platform_mpwx', $mallId)['plugins'] ?? []);
        if (!$decl) {
            return null;   // 没配插件,无所谓新旧
        }
        $opt = \app\models\Option::find()
            ->where(['name' => 'platform_mpwx', 'mall_id' => $mallId])->one();
        $configAt = (int) ($opt->updated_at ?? 0);
        if ($configAt <= 0) {
            return null;
        }

        $last = MpwxUploadLog::find()
            ->where(['mall_id' => $mallId, 'status' => MpwxUploadLog::STATUS_SUCCESS, 'is_delete' => 0])
            ->orderBy(['id' => SORT_DESC])->one();
        $uploadAt = (int) ($last->created_at ?? 0);
        if ($uploadAt >= $configAt) {
            return null;   // 上传在配置之后,线上包是新的
        }

        return [
            'config_at'     => date('Y-m-d H:i', $configAt),
            'upload_at'     => $uploadAt > 0 ? date('Y-m-d H:i', $uploadAt) : '',
            // 上次上传成功时的 msg 里带着「(已注入插件:xxx)」—— 这是事后唯一能看出
            // 线上包带没带插件的线索(代码包本身看不出来)
            'last_injected' => (string) ($last->msg ?? ''),
            'aliases'       => implode('、', array_keys($decl)),
        ];
    }

