    public function upload()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        if (!$this->appid) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '请先填写 APPID');
        }
        if (!$this->upload_key) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '上传密钥不正确!');
        }
        if (!$this->desc) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '请输入描述信息');
        }
        // 版本号无需手填：留空则按时间自动生成（唯一且递增）
        $version = $this->version ?: date('Y.m.d.Hi');

        $appid  = $this->appid;
        // appid 格式校验：杜绝路径穿越（appid 会拼进文件路径并执行 removeDirectory）
        if (!preg_match('/^wx[0-9a-zA-Z]{6,32}$/', $appid)) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, 'APPID 格式不正确');
        }
        // mall_id：优先用后台手动指定的，留空回退当前商城
        $injectMallId = trim((string)$this->inject_mall_id);
        if ($injectMallId !== '') {
            if (!ctype_digit($injectMallId) || (int)$injectMallId <= 0) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '指定的商城ID格式不正确');
            }
            $mallId = (int)$injectMallId;
        } else {
            $mallId = (int)\Yii::$app->mall->id;
        }
        if ($mallId <= 0) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '无法获取当前商城信息');
        }
        // 后端域名：优先用后台手动指定的，留空回退 ServerHelper::getHost()（.env APP_URL > 请求域名 > option 兜底）
        $injectDomain = trim((string)$this->inject_domain);
        $apiRoot = $injectDomain !== '' ? rtrim($injectDomain, '/') : rtrim(ServerHelper::getHost(), '/');
        if (!$apiRoot) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '无法获取后端域名（请配置 .env 的 APP_URL 或 option 表 domain）');
        }
        if (!preg_match('#^https?://#i', $apiRoot)) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '指定的域名格式不正确，需以 http:// 或 https:// 开头');
        }

        // 标准小程序代码包：uni-app 编译产物，须含 __JX_MALL_ID__ 占位符（先校验模板，避免无谓拷贝/加锁）
        $tplPath = \Yii::getAlias('@webroot') . '/mp-weixin';
        $tplVendor = $tplPath . '/common/vendor.js';
        // app.json 也必须校验 —— 它是插件声明的落点。原来只查 project.config.json 与 vendor.js,
        // app.json 缺失时插件注入会**静默跳过**,包照样传上去,而 C 端跳 plugin:// 直接报错。
        if (!is_dir($tplPath) || !file_exists($tplPath . '/project.config.json')
            || !file_exists($tplVendor) || !file_exists($tplPath . '/app.json')) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '小程序代码包不存在或不完整!');
        }
        if (strpos((string)file_get_contents($tplVendor), '__JX_MALL_ID__') === false) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '代码包缺少 mall_id 占位符，请用带占位符的版本重新编译小程序!');
        }

        // miniprogram-ci CLI（node / ci 路径走 .env 可配：PHP-FPM 的 PATH 常无 node）
        $nodeBin = ($_ENV['MINIPROGRAM_CI_NODE'] ?? '') ?: 'node';
        $ciBin   = ($_ENV['MINIPROGRAM_CI_BIN'] ?? '') ?: (dirname(\Yii::getAlias('@webroot')) . '/uploadserver/node_modules/.bin/miniprogram-ci');
        if (!file_exists($ciBin)) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '未安装 miniprogram-ci，请在 api/uploadserver 执行 npm install（或配置 .env 的 MINIPROGRAM_CI_BIN）');
        }

        // ===== 并发保护 =====
        // ① per-appid 锁：同一小程序串行上传（不同 mall/appid 互不影响，可随意并发）
        $lockKey = "mpwx_upload:{$appid}";
        $lockToken = LockHelper::lock($lockKey, 600); // 10 分钟，覆盖最长上传耗时
        if (!$lockToken) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '该小程序正在上传中，请勿重复提交');
        }
        // ② 唯一工作目录：即使锁失效（如 Redis 不可用）也绝不与其它上传共享目录，根除文件竞争
        $path = \Yii::getAlias('@runtime') . '/mpwx_build/' . $appid . '_' . uniqid() . bin2hex(random_bytes(3));

        $injectedPlugin = [];
        try {
            FileHelper::removeDirectory($path);
            FileHelper::copyDirectory($tplPath, $path);

            // 1. 注入 mall_id 与后端域名 —— 替换 vendor.js 占位符
            //
            // ⛔ 写入必须检查返回值,写完必须**回读验证**。磁盘满/权限不足时 file_put_contents
            //    返回 false 而不抛异常 —— 原实现不看返回值,于是会把一个**没注入**的包传上去:
            //    小程序里 mall_id 还是 '__JX_MALL_ID__',连不上任何商城,而上传显示"成功"。
            //    这类失败在后台完全看不出来,只能靠这里拦住。
            $vendorFile = $path . '/common/vendor.js';
            $vendor = file_get_contents($vendorFile);
            $vendor = str_replace('__JX_MALL_ID__', (string)$mallId, $vendor);
            $vendor = str_replace('__JX_API_ROOT__', $apiRoot, $vendor);
            if (file_put_contents($vendorFile, $vendor) === false) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '写入 vendor.js 失败(磁盘空间或权限)');
            }
            $verify = (string)file_get_contents($vendorFile);
            if (strpos($verify, '__JX_MALL_ID__') !== false || strpos($verify, '__JX_API_ROOT__') !== false) {
                return ResponseHelper::send(ApiCode::CODE_FAIL,
                    '注入校验失败:vendor.js 里仍残留占位符,该包不能上传(否则小程序连不上后端)');
            }

            // 2. 覆写 project.config.json 的 appid
            //
            // 同样用对象模式解码,理由见下面 app.json 那段:关联数组分不清 {} 和 [],
            // 整份重新编码会把空对象写成空数组。这个文件目前恰好没有空对象所以一直没出事,
            // 但那是运气 —— uniapp 换个版本多带一个空配置项就会踩雷,不留这个隐患。
            $pcFile = $path . '/project.config.json';
            $pc = json_decode((string)file_get_contents($pcFile));
            if (!$pc instanceof \stdClass) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, 'project.config.json 解析失败,代码包可能损坏');
            }
            $pc->appid = $appid;
            $pcEncoded = json_encode($pc, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
            if ($pcEncoded === false || file_put_contents($pcFile, $pcEncoded) === false) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '写入 project.config.json 失败(磁盘空间或权限)');
            }

            // 3. 注入小程序插件声明（app.json.plugins）
            //
            // ⚠ 这是整份代码包里**唯一按商城差异化**的地方,原因是微信的硬约束:
            //    app.json 里声明了插件,该小程序就必须先在公众平台申请到这个插件的使用权限,
            //    否则开发者工具预览和 CI 上传都会直接报错。我们一份代码包发所有客户,
            //    写死插件声明等于把资质要求传染给每一个客户。所以按本商城配置在上传这一刻注入,
            //    没配的客户 app.json 保持干净,完全无感。
            //
            // 配置来源是本页自己的 plugins 字段 —— 不去读任何业务插件的开关:
            // 核心不依赖业务插件(CLAUDE.md 红线),且「带不带插件」本就是这个小程序的属性。
            $ajFile = $path . '/app.json';
            // ⚠ 取【当前页面所在商城】的配置,不是 $mallId(那是 inject_mall_id 指定的注入目标)。
            //    appid/upload_key 都来自当前页面的 platform_mpwx,插件配置必须与它们同源,
            //    否则会出现"用 A 商城的密钥传包、却带上 B 商城的插件声明"。
            $declList = self::normalizePlugins(
                OptionHelper::get('platform_mpwx', (int)\Yii::$app->mall->id)['plugins'] ?? []
            );
            // ⛔ 配了插件却注不进去,必须**直接失败**,不能静默传一个没插件的包上去 ——
            //    那正是本条链最坑的形态:后台看配置齐全、上传显示成功,而线上包的 app.json
            //    里没有插件,C 端跳 plugin://别名/index 时微信解析不了、当成跨小程序跳转,
            //    报 "<navigator/> should have app-id ... when using navigate with miniProgram target"。
            //    这个错在后台完全看不出来,只能在这里拦。
            if ($declList) {
                // ⛔ 必须用**对象模式**解码(json_decode 第二参不传 true),不能用 Json::decode ——
                //    后者解成关联数组,而 PHP 的空数组和空对象无法区分:app.json 里的
                //    `"usingComponents": {}` 解成 [] 之后,再编码回去就变成了 `"usingComponents": []`。
                //    微信要求它必须是对象,拿到数组就判内容不合法,CI 报
                //    JSON_CONTENT_ERR(code 10009, path: app.json),整包传不上去。
                //    坑在于:没配插件的商城根本不走这个分支,app.json 原样上传,一切正常;
                //    只有配了插件的商城才会被这一进一出改坏,于是看起来像是「插件的问题」。
                $ajRaw = file_exists($ajFile) ? file_get_contents($ajFile) : '';
                $aj = $ajRaw !== '' ? json_decode($ajRaw) : null;
                if (!$aj instanceof \stdClass) {
                    return ResponseHelper::send(ApiCode::CODE_FAIL,
                        'app.json 缺失或解析失败,无法注入插件声明。已配置插件('
                        . implode('、', array_keys($declList)) . '),不能上传一个没有插件的包');
                }
                // 一律写 app.json 顶层。分包声明主包 requirePlugin 拿不到,是静默失效的坑,
                // 已彻底取消(理由见上面 normalizePlugins 前那段说明)。
                $holder = (isset($aj->plugins) && $aj->plugins instanceof \stdClass)
                    ? $aj->plugins : new \stdClass();
                foreach ($declList as $alias => $conf) {
                    $holder->{$alias} = (object)$conf;   // 每个插件项本身也必须是对象
                }
                $aj->plugins = $holder;

                // 历史遗留:老配置可能把声明落在某个分包里。同一个别名同时出现在顶层和分包,
                // 微信会按分包那份解析 —— 等于这次改成主包白改了。清掉。
                foreach (($aj->subPackages ?? []) as $item) {
                    if (!isset($item->plugins) || !($item->plugins instanceof \stdClass)) {
                        continue;
                    }
                    foreach (array_keys($declList) as $alias) {
                        unset($item->plugins->{$alias});
                    }
                    if ($item->plugins == new \stdClass()) {
                        unset($item->plugins);   // 空对象不必留
                    }
                }
                // 保持中文与斜杠不转义,和 uniapp 产出的 app.json 一致
                $encoded = json_encode($aj, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
                if ($encoded === false || file_put_contents($ajFile, $encoded) === false) {
                    return ResponseHelper::send(ApiCode::CODE_FAIL, '写入 app.json 失败(磁盘空间或权限)');
                }
                // 回读验证:声明必须真的落进 app.json 顶层,每个别名逐个核对。
                $ajBack = json_decode((string)file_get_contents($ajFile));
                foreach (array_keys($declList) as $alias) {
                    if (!isset($ajBack->plugins->{$alias}->provider)) {
                        return ResponseHelper::send(ApiCode::CODE_FAIL,
                            "注入校验失败:app.json 顶层没有插件「{$alias}」,该包不能上传");
                    }
                    // 同名声明不能还留在分包里 —— 留着微信会按分包那份解析,主包照样拿不到
                    foreach (($ajBack->subPackages ?? []) as $item) {
                        if (isset($item->plugins->{$alias})) {
                            return ResponseHelper::send(ApiCode::CODE_FAIL,
                                "注入校验失败:插件「{$alias}」仍残留在分包「"
                                . ($item->root ?? '?') . "」里,该包不能上传");
                        }
                    }
                }
                $injectedPlugin = array_keys($declList);
            }

            // 4. 写入上传私钥
            $keyPath = $path . "/private.{$appid}.key";
            if (file_put_contents($keyPath, $this->upload_key) === false) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '写入上传私钥失败(磁盘空间或权限)');
            }

            // 5. 调用 miniprogram-ci 上传
            //
            // 不加 --enable-es6 / --enable-es7:uni-app 编译到 mp-weixin 时已经把代码降到
            // ES5 了(产物里箭头函数、const/let、async/await 一个都没有,vendor.js 通篇
            // function + var),再开等于让 babel 做一遍无用的二次转换,平白多塞辅助代码。
            //
            // 注意微信卡的是 **source size(编译后的源码体积)**,不是压缩后的包 ——
            // minify 开得再全也压不掉超限,别指望靠压缩参数解决体积问题。
            $cmd = escapeshellarg($nodeBin) . ' ' . escapeshellarg($ciBin) . ' upload'
                . ' --pp ' . escapeshellarg($path)
                . ' --pkp ' . escapeshellarg($keyPath)
                . ' --appid ' . escapeshellarg($appid)
                . ' --uv ' . escapeshellarg($version)
                . ' --ud ' . escapeshellarg($this->desc)
                . ' -r 1'
                . ' --enable-minify'
                . ' --enable-minify-js --enable-minify-wxml --enable-minify-wxss --enable-autoprefixwxss'
                . ' 2>&1';

            @set_time_limit(0); // 上传通常 30s~2min，避免撞 PHP 执行超时
            $output = [];
            $exitCode = 0;
            exec($cmd, $output, $exitCode);
            $outputText = implode("\n", $output);

            if ($exitCode !== 0) {
                // 过滤编译进度噪音（processing:/done:），只保留真正的报错行
                $meaningful = [];
                foreach ($output as $line) {
                    $t = trim($line);
                    if ($t === '' || strpos($t, 'processing:') === 0 || strpos($t, 'done:') === 0) {
                        continue;
                    }
                    $meaningful[] = $t;
                }
                $errMsg = trim(implode("\n", array_slice($meaningful, -8)));
                if (stripos($outputText, 'ip') !== false && stripos($outputText, 'whitelist') !== false) {
                    $errMsg = "服务器 IP 不在小程序「代码上传」白名单内。请到 微信公众平台 → 开发管理 → 开发设置 → 小程序代码上传，把本服务器公网 IP 加入白名单（或关闭白名单）。\n原始：" . $errMsg;
                }
                \Yii::error("[mpwx-upload] appid={$appid} mall_id={$mallId} version={$version} exit={$exitCode} 上传失败:\n{$outputText}", 'mpwx');
                $this->writeUploadLog($appid, $mallId, $version, MpwxUploadLog::STATUS_FAIL, $errMsg ?: $outputText);
                return ResponseHelper::send(ApiCode::CODE_FAIL, '上传失败：' . ($errMsg ?: '请查看服务器日志（channel: mpwx）'));
            }

            // 带没带插件必须让运营看得见:插件声明只在上传这一刻按客户注入,事后从代码包看不出来,
            // 出问题(比如插件授权没批下来就传了)时这行日志是唯一线索。
            $pluginNote = $injectedPlugin ? '（已注入插件：' . implode('、', $injectedPlugin) . '）' : '';
            \Yii::info("[mpwx-upload] appid={$appid} mall_id={$mallId} version={$version} 上传成功 plugins="
                . ($injectedPlugin ? implode(',', $injectedPlugin) : 'none'), 'mpwx');
            $this->writeUploadLog($appid, $mallId, $version, MpwxUploadLog::STATUS_SUCCESS, '上传成功' . $pluginNote);
            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '上传成功，请登录微信公众平台提交审核' . $pluginNote);
        } finally {
            // 清理临时目录（含上传私钥，无论成败都删）+ 释放锁
            FileHelper::removeDirectory($path);
            LockHelper::unlock($lockKey, $lockToken);
        }
    }

    /**
     * 写一条上传记录（成功/失败都记）。写失败不影响上传主流程。
     */
    private function writeUploadLog($appid, $mallId, $version, $status, $msg)
    {
        try {
            $log = new MpwxUploadLog();
            $log->mall_id  = (int)$mallId;
            $log->appid    = (string)$appid;
            $log->version  = (string)$version;
            $log->remark   = (string)$this->desc;
            $log->status   = (int)$status;
            $log->msg      = mb_substr((string)$msg, 0, 2000);
            $log->admin_id = (int)(\Yii::$app->admin->id ?? 0);
            $log->save(false);
        } catch (\Throwable $e) {
            \Yii::warning('[mpwx-upload] 写上传记录失败: ' . $e->getMessage(), 'mpwx');
        }
    }

    /**
     * 上传记录列表（当前商城，按时间倒序）
     */
    public function uploadLogList()
    {
        $mallId = (int)\Yii::$app->mall->id;
        $pagination = null;
        $list = MpwxUploadLog::find()
            ->where(['mall_id' => $mallId, 'is_delete' => 0])
            ->orderBy('id DESC')
            ->page($pagination, (int)($this->limit ?: 10), (int)($this->page ?: 0))
            ->asArray()->all();
        foreach ($list as &$item) {
            $item['status_text']  = (int)$item['status'] === MpwxUploadLog::STATUS_SUCCESS ? '成功' : '失败';
            $item['created_time'] = !empty($item['created_at']) ? date('Y-m-d H:i:s', (int)$item['created_at']) : '';
            $admin = Admin::findOne($item['admin_id']);
            $item['admin_name'] = $admin ? $admin->name : '-';
        }
        unset($item);
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagination]);
    }
