namespace app\forms\mall\user;


use app\core\ApiCode;
use app\helpers\JobHelper;
use app\jobs\user\CheckInviterJob;
use app\models\BaseModel;
use app\models\Level;
use app\models\User;
use app\models\UserUpgradeLog;

class UserLevelChangeForm extends BaseModel
{
    public $user_id;

    public $level;


    public function rules()
    {
        return [
            [['user_id', 'level'], 'integer'],
        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $user = User::getUser($this->user_id);
        if (!$user) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '用户不存在！');
        }

        // 目标等级解析（level==0 表示清为普通用户）
        $targetLevelId = 0;
        $targetWeight = 0;
        if ($this->level != 0) {
            $level = Level::findOne(['level' => $this->level, 'mall_id' => \Yii::$app->mall->id, 'is_delete' => 0]);
            if (!$level) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '等级不存在！');
            }
            $targetLevelId = (int)$level->id;
            $targetWeight = (int)$this->level;
        }

        $db = \Yii::$app->db;
        $tx = $db->beginTransaction();
        $beforeLevelId = 0;
        $changed = false;
        try {
            // 行锁重读真实当前等级:与并发写者(升级Job/会员/台账)串行化、取准确 old
            $cur = \app\services\UserService::lockUserLevelRow((int)$user->id);
            if ($cur === null) {
                $tx->rollBack();
                return $this->apiResponse(ApiCode::CODE_FAIL, '用户不存在！');
            }
            $beforeLevelId = $cur['level_id'];

            // 后台把等级【调低】时,顺手钉上「禁止自动升级」。
            //
            // 不钉的话这次降级会被系统自己推翻:升级引擎按【全量累计】判定
            // (UserLevelUpgradeJob 里写明的口径),用户历史上早就满足了原等级的条件,
            // 下一个订单/团队事件一触发就又升回去,管理员会以为"降级没生效"。
            //
            // 典型场景:用户消费很多升了级,后来因纠纷【线下退了钱】,那笔业绩不该再算。
            // 但线下退款系统里无感知,累计消费一分没少 —— 只能靠人工降级 + 钉住。
            //
            // 只在降级时钉,升级/平级不动;管理员想恢复自动升级,
            // 到用户编辑抽屉里把「禁止自动升级」关掉即可。
            $isDemote = $targetWeight < (int) $cur['level'];

            if ($cur['level'] != $targetWeight || $cur['level_id'] != $targetLevelId) {
                $user->level = $targetWeight;
                $user->level_id = $targetLevelId;
                $user->is_manual = 1;
                $user->level_at = time();
                if ($isDemote) {
                    $user->disable_auto_upgrade = 1;
                }
                if (!$user->save()) {
                    $tx->rollBack();
                    return $this->responseErrorMsg($user);
                }
                $changed = true;
            }

            // 升级日志（reason_by=3 后台编辑），与等级写入同事务
            $log = new UserUpgradeLog();
            $log->mall_id = $user->mall_id;
            $log->user_id = $this->user_id;
            $log->before_level_id = $beforeLevelId;
            $log->after_level_id = $targetLevelId;
            $log->reason_by = 3;
            $log->marks = '后台编辑';
            if (!$log->save()) {
                \Yii::warning($log->getFirstErrors());
            }

            // 团队统计:开了 outbox 就在【本改级事务内】emit(与等级变更原子落库,崩溃不丢);未开则提交后直连增量(见 broadcastLevelChanged)
            if ($changed && \app\services\TeamStatOutbox::enabled((int)$user->mall_id)) {
                \app\services\TeamStatOutbox::emit((int)$user->mall_id, 'level_changed', [
                    'user_id' => (int)$user->id, 'before_level_id' => (int)$beforeLevelId, 'after_level_id' => (int)$targetLevelId,
                ]);
            }

            $tx->commit();
        } catch (\Throwable $e) {
            $tx->rollBack();
            \Yii::error('[后台改级] 异常: ' . $e->getMessage());
            return $this->apiResponse(ApiCode::CODE_FAIL, '保存失败：' . $e->getMessage());
        }

        if ($changed) {
            $this->broadcastLevelChanged($user, $beforeLevelId, $targetLevelId);
        }
        // 降级时钉了「禁止自动升级」,必须在返回里说清楚 ——
        // 这是个有后果的副作用(该用户以后正常达标也不会自动升级了),
        // 静默做掉的话管理员根本不知道,回头查"为什么这人一直升不上去"要查很久。
        $msg = '保存成功';
        if ($changed && $isDemote) {
            $msg = '保存成功。已同时开启「禁止自动升级」—— 否则该用户历史累计业绩仍满足原等级条件，下次下单就会被系统自动升回去。如需恢复自动升级，到用户资料里关掉该开关。';
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, $msg);
    }

    /**
     * 广播等级变化（让 aicare/dealer/distribution/团队统计等订阅方同步）
     *
     * 之前后台手动改等级不触发此事件，导致：
     *   - AicareUserLevelListener 收不到通知 → aicare_member.level 永远停留旧值
     *   - TeamStatUpdater 不刷团队统计 → 排行/统计数据陈旧
     *
     * 与 UserLevelUpgradeJob 保持一致：try-catch 包住，失败不影响主流程。
     *
     * @param User $user 已 save 的用户对象
     * @param int  $beforeLevelId 变化前 level_id
     * @param int  $afterLevelId  变化后 level_id（清零时为 0）
     */
    private function broadcastLevelChanged(User $user, int $beforeLevelId, int $afterLevelId): void
    {
        try {
            // outbox 开启时已在改级事务内 emit(见 save());此处仅在【未开】时直连增量,避免双写
            if (!\app\services\TeamStatOutbox::enabled((int)$user->mall_id)) {
                \app\services\TeamStatUpdater::onLevelChanged($user->id, $user->mall_id, $beforeLevelId, $afterLevelId);
            }
            \Yii::$app->trigger(
                \app\events\UserLevelChangedEvent::EVENT_NAME,
                new \app\events\UserLevelChangedEvent([
                    'user'       => $user,
                    'oldLevelId' => $beforeLevelId,
                    'newLevelId' => $afterLevelId,
                    'source'     => 'manual',
                ])
            );

            // 后台手动改等级后，重算推广资格（is_inviter）：
            // 新等级若 Level.is_inviter=1 则授予推广资格，让 distribution 等依赖 is_inviter 的插件即时生效。
            // CheckInviterJob 幂等（仅对 is_inviter=0 的用户授予，不会重复/误撤），升到 0 级时无影响。
            if ($afterLevelId > 0) {
                JobHelper::push(new CheckInviterJob(['user_id' => $user->id]));
            }

            // 自身等级变化后，触发整条上级链重检：下级等级变化会影响上级"伞下某等级满N人"等团队架构条件。
            // （自动升级路径已在 UserLevelUpgradeJob 内级联，此处覆盖后台手动改级路径）
            \app\jobs\user\UserLevelUpgradeJob::dispatchUplineCheck((int)$user->id, 'level_changed_upline');
        } catch (\Throwable $e) {
            \Yii::error("[UserLevelChangeForm] 等级变化广播失败 user={$user->id}: " . $e->getMessage());
        }
    }
}
