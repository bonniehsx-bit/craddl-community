namespace app\forms\mall\user;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\User;

class UserSearchListForm extends BaseModel
{
    public $user_id;
    public $keyword;
    public $search_date;
    public $month;
    public $day;
    public $year;
    public $sign_time;
    public $level_id;
    public $level;
    public $mobile;
    public $limit; // 结果条数上限(下拉搜索用);不传默认 20,最大 50
    public $page;  // 传了才进分页模式(批量筛人用),返回 pagination;下拉搜索不传,行为不变


    public function rules()
    {
        return [
            [['user_id', 'month', 'day', 'year', 'level_id', 'level', 'limit', 'page'], 'integer'],
            [['keyword', 'mobile'], 'string'],
            [['search_date', 'sign_time'], 'safe']
        ]; // TODO: Change the autogenerated stub
    }


    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // 已注销/删除的用户不应出现在任何选人下拉里
        $query = User::find()->where(['mall_id' => \Yii::$app->mall->id, 'is_delete' => 0]);
        if ($this->keyword) {
            if (is_numeric($this->keyword)) {
                $query->andWhere([
                    'or',
                    ['id' => (int)$this->keyword],
                    ['like', 'mobile', $this->keyword],
                    ['like', 'nickname', $this->keyword]
                ]);
            } else {
                $query->andWhere([
                    'or',
                    ['like', 'nickname', $this->keyword],
                    ['like', 'mobile', $this->keyword]
                ]);
            }
        }
        if ($this->user_id) {
            $query->andWhere(['id' => $this->user_id]);
        }
        $query->andFilterWhere(['month' => $this->month, 'day' => $this->day, 'year' => $this->year]);
        if ($this->search_date && is_array($this->search_date) && count($this->search_date) === 2) {
            // birthday 是 varchar,直接 between 走的是【字符串比较】:
            // '1990-8-8' BETWEEN '1990-08-01' AND '1990-08-31' 会算出 false(位 5 的 '8' > '0'),
            // 明明是 8 月 8 日却搜不出来。DATE() 显式转成日期再比,三种历史写法都对。
            // (User::beforeSave 现在会把新写入的生日归一化成 Y-m-d,这里是给历史脏数据兜底。)
            $query->andWhere(['between', new \yii\db\Expression('DATE(`birthday`)'), $this->search_date[0], $this->search_date[1]]);
        }

        if ($this->sign_time && is_array($this->sign_time) && count($this->sign_time) === 2) {
            // 列名是 created_time 不是 create_time —— 原先写错,前端一用「注册时间」筛选
            // 接口就是 SQLSTATE[42S22] Unknown column 直接 500(生日积分发放页在用)。
            $query->andWhere(['between', 'created_time', $this->sign_time[0], $this->sign_time[1]]);
        }

        if ($this->mobile) {
            $query->andWhere(['like', 'mobile', $this->mobile]);
        }

        if ($this->level) {
            $query->andWhere(['level' => $this->level]);
        }

        if ($this->level_id) {
            $query->andWhere(['level_id' => $this->level_id]);
        }
        // 本接口有两类用法,限流规则不同:
        //   ① 下拉搜索(hrm/clerk/mch 等):不传 page,维持原样 —— 默认 20、上限 50,
        //      不加限制会把整个用户表(数万行)拉回前端。
        //   ② 批量筛人(生日积分发放页):传 page 即进分页模式,返回 total 供翻页。
        //      原先它不传 limit → 只拿到 20 条、页面又没有分页控件,
        //      运营筛「本月生日」以为只有 20 个人,其余的永远发不到积分,界面上还看不出被截断。
        $paged = $this->page !== null && $this->page !== '';
        $limit = (int) $this->limit;
        if ($limit <= 0) {
            $limit = 20;
        } elseif ($limit > ($paged ? 200 : 50)) {
            $limit = $paged ? 200 : 50;   // 分页模式放宽,但仍有硬上限防一次拉爆
        }

        $query->select('id,nickname,avatar_url,birthday,level,level_id,mobile')->orderBy('id desc');

        if (!$paged) {
            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', [
                'list' => $query->limit($limit)->asArray()->all(),
            ]);
        }

        $page  = max(1, (int) $this->page);
        $total = (int) $query->count();
        $list  = $query->offset(($page - 1) * $limit)->limit($limit)->asArray()->all();

        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', [
            'list'       => $list,
            'pagination' => [
                'page'       => $page,
                'limit'      => $limit,
                'total'      => $total,
                'page_count' => (int) ceil($total / $limit),
            ],
        ]);
    }

}