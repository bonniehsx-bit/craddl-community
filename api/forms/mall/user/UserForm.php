namespace app\forms\mall\user;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\User;
use app\services\UserService;

class UserForm extends BaseModel
{
    public $user_id;
    public $remarks;
    public $password;
    public $pay_password; // 6位数字支付密码


    public function rules()
    {
        return [
            [['password'], 'string', 'min' => 6],
            [['user_id'], 'required'],
            [['user_id'], 'integer'],
            [['remarks'], 'string'],
            // match 默认 skipOnEmpty,不会影响 setPassword / remarksChange 等其它方法的校验
            [['pay_password'], 'match', 'pattern' => '/^\d{6}$/', 'message' => '支付密码必须为6位数字'],
        ]; // TODO: Change the autogenerated stub
    }


    public function remarksChange()
    {

        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // 后台备注允许写已注销用户(is_delete=1):注销后运营仍需给这条墓碑记录留笔记
        // (如「客户于 X 日申请注销」)。前端/控制器守卫都把 remarks 作为放行例外,
        // 这里的 is_delete=0 会让那个放行落空,故不过滤 is_delete。mall_id 仍隔离。
        $user = User::findOne(['mall_id' => \Yii::$app->mall->id, 'id' => $this->user_id]);
        if (!$user) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '用户不存在！');
        }
        $user->remarks = $this->remarks;
        if (!$user->save()) {
            return $this->responseErrorMsg($user);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');
    }


    public function setInviter()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $user = User::findOne(['is_delete' => 0, 'mall_id' => $this->mall_id, 'id' => $this->user_id]);
        if (!$user) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '用户不存在！');
        }
        if ($user->is_inviter) {
            $exist = User::find()->andWhere(['parent_id' => $this->user_id, 'is_delete' => 0])->exists();
            if ($exist) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '设置失败，该用户已经邀请了其他会员，请先处理他的直推用户');
            }
            $user->is_inviter = 0;
            $user->inviter_at = 0;
        } else {
            $user->inviter_at = time();
            $user->is_inviter = 1;
        }
        if (!$user->save()) {
            return $this->responseErrorMsg($user);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');
    }

    public function setPassword()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $user = User::findOne(['is_delete' => 0, 'mall_id' => $this->mall_id, 'id' => $this->user_id]);
        if (!$user) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '用户不存在！');
        }
        if (!$this->password) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '请输入密码');
        }
        $user->password = \Yii::$app->security->generatePasswordHash($this->password);
        if (!$user->save()) {
            return $this->responseErrorMsg($user);
        }
        // 改密后踢出所有设备
        UserService::invalidateUserAuth($user->id);
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');
    }

    /**
     * 后台代设/重置用户支付密码。
     * 此前 UserController::actionSetPayPassword 调的就是本方法,但方法从未实现 —— 一调即致命错误。
     *
     * 存储口径与 C 端 /api/user/set-pay-pwd、注册页 MobileSignInForm::applyPayPwd 完全一致:
     * 6位数字 → generatePasswordHash 存入 user.pay_pwd。支付密码不影响登录态,不踢设备。
     */
    public function setPayPassword()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $user = User::findOne(['is_delete' => 0, 'mall_id' => $this->mall_id, 'id' => $this->user_id]);
        if (!$user) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '用户不存在！');
        }
        if (!preg_match('/^\d{6}$/', (string)$this->pay_password)) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '请输入6位数字支付密码');
        }
        $user->pay_pwd = \Yii::$app->security->generatePasswordHash($this->pay_password);
        if (!$user->save()) {
            return $this->responseErrorMsg($user);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '支付密码设置成功');
    }

    // [已移除] accountDel() 原本是一个 toggle 拉黑状态的方法, 但名字和 C 端自助注销冲突,
    // 无任何 controller 绑定它 (死代码). 拉黑/解封统一走 UserBanForm::ban() / UserBanForm::unban().
}
