namespace app\forms\mall\user;


use app\core\ApiCode;
use app\helpers\Helper;
use app\helpers\OptionHelper;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\User;

class UserCreateForm extends BaseModel
{
    public $mobile;
    public $avatar_url;
    public $openid;
    public $remarks;
    public $platform;
    public $nickname;
    public $wechat_no;
    public $password;
    public $is_inviter;
    public $parent_mobile;
    public $parent_id;

    public function rules()
    {
        return [
            [['nickname'], 'required'],
            [['parent_id'], 'integer'],
            [['avatar_url', 'platform', 'parent_mobile', 'is_inviter'], 'string'],
            [['password'], 'default', 'value' => '123456'],
            [['platform'], 'default', 'value' => 'WECHAT'],
            [['mobile', 'avatar_url', 'openid', 'remarks', 'nickname', 'wechat_no', 'password'], 'string'],
        ]; // TODO: Change the autogenerated stub
    }

    public function attributeLabels()
    {
        return [
            'avatar_url' => '头像',
            'nickname' => '昵称',
            'mobile' => '手机号'
        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        $user = new User();
        $user->mall_id = $this->mall_id;
        $user->avatar_url = $this->avatar_url;
        $user->nickname = $this->nickname;
        $user->platform = $this->platform;
        $user->access_token = \Yii::$app->security->generateRandomString();
        $user->auth_key = \Yii::$app->security->generateRandomString();

        $setting = OptionHelper::get('mall_setting', $this->mall_id);
        if (!$user->avatar_url) {
            $user->avatar_url = $setting && isset($setting['avatar_url']) && $setting['avatar_url'] ? $setting['avatar_url'] : "";
        }
        $user->name = $this->nickname;
        if ($this->wechat_no) {
            $user->wechat_no = $this->wechat_no;
        }
        if ($this->password) {
            $user->password = \Yii::$app->security->generatePasswordHash($this->password);
        }
        if ($this->mobile) {
            if (!Helper::isMobile($this->mobile)) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '手机号码格式不正确!');
            }
            $exist = User::find()->andWhere(['mobile' => $this->mobile, 'is_delete' => 0, 'mall_id' => $this->mall_id])->exists();
            if ($exist) {
                return ResponseHelper::send(ApiCode::CODE_SUCCESS, '该手机号码被注册，请换个手机号码!');
            }
            $user->mobile = $this->mobile;
        }
        if ($this->platform == User::PLATFORM_MOBILE) {
            $user->openid = $this->mobile;
        }
        if ($this->is_inviter) {
            $user->is_inviter = 1;
            $user->inviter_at = time();
        }
        if (!$user->save()) {
            return $this->responseErrorMsg($user);
        }
        if ($this->parent_mobile) {
            $parent = User::findOne(['mobile' => $this->parent_mobile, 'mall_id' => $this->mall_id]);
            if ($parent) {
                $user->bindParent($parent->id, true);   // 后台建用户属后台操作,不受登录/插件绑定的守卫限制
            }
        }
        if ($this->parent_id) {
            $parent = User::findOne(['id' => $this->parent_id, 'mall_id' => $this->mall_id]);
            if ($parent) {
                $user->bindParent($parent->id, true);
            }
        }


        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '创建成功!');
    }
}
