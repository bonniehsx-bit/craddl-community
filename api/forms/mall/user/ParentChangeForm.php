namespace app\forms\mall\user;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\User;
use EasyWeChat\Kernel\Exceptions\UnboundServiceException;

class ParentChangeForm extends BaseModel
{

    public $parent_id;

    public $user_id;

    public function rules()
    {
        return [
            [['parent_id', 'user_id'], 'integer']
        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // 必带 mall_id + is_delete=0:否则可改【其他商城】用户的推荐人 = 跨商城篡改关系链。
        $user = User::findOne(['id' => $this->user_id, 'mall_id' => \Yii::$app->mall->id, 'is_delete' => 0]);
        if (!$user) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '用户不存在');
        }
        if (!$this->parent_id) {
            $user->bindParent(0, true);
        } else if ($this->parent_id == -1) {
            $user->bindParent($this->parent_id, true);
        } else {
            // 推荐人也必须同商城:否则可把本商城用户挂到别商城的人名下,跨商城建链。
            $parent = User::findOne(['id' => $this->parent_id, 'mall_id' => \Yii::$app->mall->id, 'is_inviter' => 1, 'is_delete' => 0]);
            if (!$parent) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '推荐人不存在或不具备推广权限');
            }
            try {
                // 后台手动改上级:平台直属 / 已有团队的人也允许改(整队随他一起挪),非后台入口一律不行
                $user->bindParent($this->parent_id, true);
            } catch (\Throwable $e) {
                \Yii::warning($e->getMessage());
                return ResponseHelper::send(ApiCode::CODE_FAIL, $e->getMessage());
            }
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '修改成功');
    }
}
