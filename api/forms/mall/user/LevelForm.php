class LevelForm extends BaseModel
{

    public $id;
    public $name;
    public $level;
    public $pic_url;
    public $detail;
    public $enabled;
    public $upgrade;
    public $is_auto;
    public $upgrade_logic; // 升级条件关系: 0=全部满足(AND) 1=满足任一(OR)
    public $is_discount;
    public $discount;
    public $money;
    public $buy_type;
    public $is_inviter;
    public $invite_num;
    public $invite_level;


    public function rules()
    {
        return [
            [['id', 'level', 'invite_level', 'invite_num', 'enabled', 'is_auto', 'upgrade_logic', 'is_discount', 'buy_type', 'is_inviter'], 'integer'],
            [['pic_url', 'detail'], 'string', 'max' => 255],
