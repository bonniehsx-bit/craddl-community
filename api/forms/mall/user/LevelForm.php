    public function save()
    {
        if (!$this->validate()) {

            return $this->responseErrorInfo();
        }

        // 升级条件防呆:勾了条件却留空阈值会退化为「>=0 恒达标」导致误升;OR 模式勾「无条件」会人人秒升
        $conditions = self::slimGoodsInConditions(SerializeHelper::decode($this->upgrade));
        $condErr = $this->validateUpgradeConditions($conditions);
        if ($condErr !== null) {
            return $this->apiResponse(ApiCode::CODE_FAIL, $condErr);
        }
        // 存不下就在这里拦住:线上严格模式会报数据库错误,宽松模式会静默截断成坏数据
        if (strlen(Json::encode($conditions)) > self::OPTION_VALUE_MAX) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '升级条件内容过多,保存不下,请减少选择的商品');
        }

        if ($this->id) {
            $level = Level::findOne(['id' => $this->id, 'is_delete' => 0, 'mall_id' => \Yii::$app->mall->id]);
            if (!$level) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '等级不存在!');
            }
            if ($level->level != $this->level) {
                // 占用校验用旧权重标量 $level->level(原误传 Level 对象,查询恒不命中、守卫失效)
                $user = User::findOne(['mall_id' => \Yii::$app->mall->id, 'level' => $level->level, 'is_delete' => 0]);
                if ($user) {
                    return $this->apiResponse(ApiCode::CODE_FAIL, '该等级存在对应用户，不可变更等级!');
                }
            }
        } else {
            $level = new Level();
            $level->mall_id = \Yii::$app->mall->id;
            $is_exist = Level::findOne(['level' => $this->level, 'is_delete' => 0, 'mall_id' => \Yii::$app->mall->id]);
            if ($is_exist) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '等级已存在');
            }
        }
        $level->attributes = $this->attributes;
        if (!$this->discount) {
            $level->discount = 0;
            $level->is_discount = 0;
        }

        if (!$level->save()) {
            return $this->responseErrorMsg($level);
        }
        OptionHelper::set('level_upgrade_' . $level->id, $conditions, $level->mall_id);
        OptionHelper::set('level_' . $level->id, $level->attributes, $level->mall_id);

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');
    }

    /** option.value 是 TEXT,最多 65535 字节 */
    const OPTION_VALUE_MAX = 65535;

    /**
     * 「指定商品」类条件里的商品只存 id,同一个条件里重复选的商品只留一个。
     *
     * 后台选商品时前端把整条商品记录(64 个字段:分类对象、成本价、采购价、库存、时间戳……)原样塞进条件,
     * 一个商品约 1.7KB。山言康一个等级选了 27 个商品,level_upgrade_3 就有 64KB,
     * 离 option.value(TEXT,上限 65535 字节)只差 1KB,再加一个商品保存就报「value 超出长度」。
     * 只存 id 后一个商品约 10 字节,一个等级能放五千多个商品。
     *
     * 升级引擎(UserLevelUpgradeJob)只按 id 判断(array_column(…, 'id'));
     * 编辑页要的名称 / 图片 / 价格在打开时按 id 从商品表现查(hydrateGoodsInConditions),显示的是当前价。
     * 按「对象列表里带 id」通用识别,不按条件编号逐个写 —— 以后新加的指定商品条件自动生效。
     * 老数据不用迁移:下次在后台保存该等级时就会被精简。
     */
    public static function slimGoodsInConditions($conditions)
    {
        if (!is_array($conditions)) {
            return $conditions;
        }
        foreach ($conditions as &$cond) {
            if (!is_array($cond)) {
                continue;
            }
            foreach ($cond as $field => $val) {
                if (!self::isGoodsList($val)) {
                    continue;
                }
                $seen = [];
                foreach ($val as $g) {
                    $id = is_array($g) ? (int)($g['id'] ?? 0) : 0;
                    if ($id > 0 && !isset($seen[$id])) {
                        $seen[$id] = ['id' => $id];
                    }
                }
                $cond[$field] = array_values($seen);
            }
        }
        unset($cond);
        return $conditions;
    }

    /**
     * 编辑页打开时,按 id 把商品的名称 / 图片 / 价格补回去(存的时候只存了 id)。
     * 商品被删了照样查得到(软删),名称后面标「已删除」,运营自己决定要不要去掉。
     */
    public static function hydrateGoodsInConditions($conditions, $mallId)
    {
        if (!is_array($conditions)) {
            return $conditions;
        }
        $ids = [];
        foreach ($conditions as $cond) {
            foreach (is_array($cond) ? $cond : [] as $val) {
                if (self::isGoodsList($val)) {
                    $ids = array_merge($ids, array_map('intval', array_column($val, 'id')));
                }
            }
        }
        if (!$ids) {
            return $conditions;
        }
        $goods = Goods::find()->select(['id', 'name', 'cover_pic', 'price', 'is_delete'])
            ->where(['mall_id' => $mallId, 'id' => array_values(array_unique($ids))])
            ->indexBy('id')->asArray()->all();
        foreach ($conditions as &$cond) {
            if (!is_array($cond)) {
                continue;
            }
            foreach ($cond as $field => $val) {
                if (!self::isGoodsList($val)) {
                    continue;
                }
                $cond[$field] = array_values(array_map(function ($g) use ($goods) {
                    $id = (int)($g['id'] ?? 0);
                    $row = $goods[$id] ?? null;
                    if (!$row) {
                        // 本商城查不到(老数据里的脏 id):保留 id,名称用存过的或给个说明
                        return ['id' => $id, 'name' => ($g['name'] ?? '') ?: "商品#{$id}(已不存在)",
                            'cover_pic' => (string)($g['cover_pic'] ?? ''), 'price' => (string)($g['price'] ?? '')];
                    }
                    return ['id' => $id, 'name' => $row['name'] . ((int)$row['is_delete'] ? '(已删除)' : ''),
                        'cover_pic' => (string)$row['cover_pic'], 'price' => (string)$row['price']];
                }, $val));
            }
        }
        unset($cond);
        return $conditions;
    }

    /**
     * 是不是商品列表:每一项都是带 id 的对象,且是商品的样子 ——
     * 选择器带回的整条商品(有 price / cover_pic)、上一版存的 {id,name,cover_pic,price}、这一版存的 {id}。
     * 别把以后可能出现的等级 / 人员对象列表误当商品。
     */
    private static function isGoodsList($val)
    {
        $first = is_array($val) && $val ? reset($val) : null;
        if (!is_array($first) || !array_key_exists('id', $first)) {
            return false;
        }
        return array_key_exists('price', $first) || array_key_exists('cover_pic', $first) || array_keys($first) === ['id'];
    }

    /**
     * 校验升级条件:勾选的条件必须填齐阈值(空值会退化为恒达标),且「无条件」不得与其它条件共存。
     * @param mixed $conditions SerializeHelper::decode 后的条件数组
     * @return string|null 错误文案;null=通过
     */
    private function validateUpgradeConditions($conditions)
    {
        if (!is_array($conditions)) {
            return null;
        }
        $selected = array_values(array_filter($conditions, function ($c) {
            return is_array($c) && !empty($c['selected']);
        }));
        if (empty($selected)) {
            return null; // 未勾任何条件:等级可不参与自动升级，放行
        }

        $hasType3 = false;
        foreach ($selected as $c) {
            $type = (int)($c['type'] ?? -1);
            if ($type === 3) {
                $hasType3 = true;
                continue;
            }
            $err = $this->checkConditionValue($type, $c);
            if ($err !== null) {
                return $err;
            }
        }

        // 「无条件」(type3)与其它条件共存=配置错误:OR 模式人人秒升、AND 模式纯冗余
        if ($hasType3 && count($selected) > 1) {
            return '「无条件」不能与其它升级条件同时勾选：满足任一(OR)会让所有用户直升该等级，全部满足(AND)则它是冗余项。请单独使用「无条件」，或取消它。';
        }
        return null;
    }

    /**
     * 单条升级条件的必填校验(与 UserLevelUpgradeJob::checkConditions 的 type 取值口径对齐)。
     */
    private function checkConditionValue(int $type, array $c)
    {
        $num = function ($v) {
            return is_numeric($v) && (float)$v > 0;
        };
        $arr = function ($v) {
            return is_array($v) && !empty($v);
        };
        switch ($type) {
            case 0: case 4: case 5: case 9: case 11: // 消费额/团队人数/直推有效/团队业绩/直推业绩
                if (!$num($c['value'] ?? null)) return '已勾选的「金额/人数/业绩」类条件，阈值不能为空且需大于 0';
                break;
            case 1: // 购买指定商品
                if (!$arr($c['value'] ?? null)) return '「购买指定商品」需至少选择一个商品';
                break;
            case 2: // 指定身份 + 购买指定商品
                if (!$num($c['value'] ?? null)) return '「指定身份+购买商品」需选择身份等级';
                if (!$arr($c['value1'] ?? null)) return '「指定身份+购买商品」需选择商品';
                break;
            case 6: // 直推某等级及以上满 N 人
                if (!$num($c['value'] ?? null)) return '「直推某等级满N人」需选择目标等级';
                if (!$num($c['value1'] ?? null)) return '「直推某等级满N人」的人数需大于 0';
                break;
            case 7: // 指定身份 + 累购商品数量
                if (!$num($c['value'] ?? null)) return '「指定身份+累购数量」需选择身份等级';
                if (!$num($c['value1'] ?? null)) return '「指定身份+累购数量」需选择商品';
                if (!$num($c['value2'] ?? null)) return '「指定身份+累购数量」的件数需大于 0';
                break;
            case 8: // 指定身份 + 伞下某等级人数
                if (!$num($c['value'] ?? null)) return '「指定身份+伞下某等级人数」需选择身份等级';
                if (!$num($c['value1'] ?? null)) return '「指定身份+伞下某等级人数」需选择目标等级';
                if (!$num($c['value2'] ?? null)) return '「指定身份+伞下某等级人数」的人数需大于 0';
                break;
            case 10: // 多线并行 N 条合格线
                if (!$num($c['value'] ?? null)) return '「多线并行」的线数需大于 0';
                if (!$num($c['value1'] ?? null)) return '「多线并行」需选择目标等级';
                break;
            case 12: // 累计购买指定商品(多选)满 N 件
                if (!$arr($c['value'] ?? null)) return '「累计购买指定商品」需至少选择一个商品';
                if (!$num($c['value1'] ?? null)) return '「累计购买指定商品」的件数需大于 0';
                break;
            case 13: // 直推某等级满 n 人(等级可空=任意、人数可 0=不限)+ 自购组(value4/5) + 团队组(value2/3);两组商品至少配一组
                $hasSelf13 = $arr($c['value4'] ?? null);
                $hasTeam13 = $arr($c['value2'] ?? null);
                if (!$hasSelf13 && !$hasTeam13) return '「直推等级+累购」自购商品、团队商品至少选一组';
                if ($hasSelf13 && !$num($c['value5'] ?? null)) return '已选自购考核商品,自购件数需大于 0';
                if ($hasTeam13 && !$num($c['value3'] ?? null)) return '已选团队考核商品,团队件数需大于 0';
                break;
            case 14: // 两级直推(基础/更高等级可空=任意、人数可 0=不限)+ 自购组(value6/7) + 团队组(value4/5);两组商品至少配一组
                $hasSelf14 = $arr($c['value6'] ?? null);
                $hasTeam14 = $arr($c['value4'] ?? null);
                if (!$hasSelf14 && !$hasTeam14) return '「两级直推+累购」自购商品、团队商品至少选一组';
                if ($hasSelf14 && !$num($c['value7'] ?? null)) return '已选自购考核商品,自购件数需大于 0';
                if ($hasTeam14 && !$num($c['value5'] ?? null)) return '已选团队考核商品,团队件数需大于 0';
                break;
            case 15: // 直推某等级(等级可空=任意、人数可 0=不限)+ (自购A value4 + 团队B value2) 合计满 value3 件
                if (!$arr($c['value4'] ?? null) && !$arr($c['value2'] ?? null)) return '「直推等级+合计累购」自购商品A、团队商品B 至少选一组';
                if (!$num($c['value3'] ?? null)) return '「直推等级+合计累购」的合计件数需大于 0';
                break;
            case 16: // 两级直推(基础/更高等级可空=任意、人数可 0=不限)+ (自购A value6 + 团队B value4) 合计满 value5 件
                if (!$arr($c['value6'] ?? null) && !$arr($c['value4'] ?? null)) return '「两级直推+合计累购」自购商品A、团队商品B 至少选一组';
                if (!$num($c['value5'] ?? null)) return '「两级直推+合计累购」的合计件数需大于 0';
                break;
            case 17: // 单笔订单件数满 N(value=指定商品多选,可空=不限商品;value1=件数)
                if (!$num($c['value1'] ?? null)) return '「一次性购买满N件」的件数需大于 0';
                break;
            // ── 19/20/21 是 12/15/16 的「金额版」,字段位置完全一致,只是阈值单位从件变成元 ──
            case 19: // 累计购买指定商品(多选)满 N 元
                if (!$arr($c['value'] ?? null)) return '「累计购买指定商品(金额)」需至少选择一个商品';
                if (!$num($c['value1'] ?? null)) return '「累计购买指定商品(金额)」的金额需大于 0';
                break;
            case 20: // 直推某等级(可空=任意、人数可 0=不限)+ (自购A value4 + 团队B value2) 合计满 value3 元
                if (!$arr($c['value4'] ?? null) && !$arr($c['value2'] ?? null)) return '「直推等级+合计金额」自购商品A、团队商品B 至少选一组';
                if (!$num($c['value3'] ?? null)) return '「直推等级+合计金额」的合计金额需大于 0';
                break;
            case 21: // 两级直推(可空=任意、人数可 0=不限)+ (自购A value6 + 团队B value4) 合计满 value5 元
                if (!$arr($c['value6'] ?? null) && !$arr($c['value4'] ?? null)) return '「两级直推+合计金额」自购商品A、团队商品B 至少选一组';
                if (!$num($c['value5'] ?? null)) return '「两级直推+合计金额」的合计金额需大于 0';
                break;
        }
        return null;
    }

    public function search()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $level = Level::findOne(['id' => $this->id, 'is_delete' => 0, 'mall_id' => \Yii::$app->mall->id]);
        if (!$level) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '等级不存在!');
        }
        $info = $level->attributes;
        $info['upgrade'] = self::hydrateGoodsInConditions(
            OptionHelper::get('level_upgrade_' . $level->id, $level->mall_id), $level->mall_id
        );
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['level' => $info]);
    }

    public function delete()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $level = Level::findOne(['id' => $this->id, 'is_delete' => 0, 'mall_id' => \Yii::$app->mall->id]);
        if (!$level) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '等级不存在!');
        }
        $user = User::findOne(['mall_id' => \Yii::$app->mall->id, 'level' => $level->level, 'is_delete' => 0]);
        if ($user) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '该等级存在对应用户，不可删除!');
        }
        $level->is_delete = 1;
        $level->save();
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '删除成功');
    }
}
