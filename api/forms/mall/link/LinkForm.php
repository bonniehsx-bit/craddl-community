    public function getList()
    {

        $list = [];
        //获取商城链接
        if ($this->type == 'mall') {

            $list = $this->getMallLinks();
        }
        if ($this->type == "plugin") {
            $list = $this->getPluginLinks();
        }

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list]);
    }

    private function getPluginLinks()
    {
        $menus = [];

        $list = \Yii::$app->plugin->list;
        // 只挂载【当前商城已授权】的插件链接;null = 平台级/无 mall 上下文,视为全部(与 Plugin::getAllPlugins 同源)
        $authorized = \Yii::$app->plugin->resolveAuthorizedPluginNames();

        foreach ($list as $item) {
            // 未授权给本商城的插件,其链接不应被挂载
            if ($authorized !== null && !in_array($item->name, $authorized, true)) {
                continue;
            }
            $plugin = \Yii::$app->plugin->getPlugin($item->name);
            if (!$plugin) {
                continue;
            }
            $links = $plugin->getLinks();
            if (empty($links)) {
                continue; // 该插件没有可挂载的前端链接,不显示空分组
            }
            $menus[] = ['name' => $item->label, 'links' => $links];
        }

        unset($item);
        return $menus;
    }

