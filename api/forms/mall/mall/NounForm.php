namespace app\forms\mall\mall;


use app\core\ApiCode;
use app\helpers\NounHelper;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\Noun;

class NounForm extends BaseModel
{

    public $key;
    public $value;
    public $id;

    public function rules()
    {
        return [
            [['id'], 'integer'],
            [['key', 'value'], 'string']
        ]; // TODO: Change the autogenerated stub
    }


    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // key 必须是完整词库字典（核心 + 已启用插件）中的 key，杜绝自创 key
        if (!array_key_exists($this->key, NounHelper::fullDictionary())) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '未知的词库 key：' . $this->key);
        }
        $model = Noun::findOne(['key' => $this->key, 'mall_id' => $this->mall_id, 'is_delete' => 0]);
        if (!$model) {
            $model=new Noun();
            $model->mall_id = $this->mall_id;
            $model->key = $this->key;
        }
        $model->value = $this->value;
        if (!$model->save()) {
            return $this->responseErrorMsg($model);
        }
        NounHelper::addKey($model->key,$model->value,$model->mall_id);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '保存成功');
    }

    public function delete()
    {
        $model = Noun::findOne(['id' => $this->id, 'mall_id' => $this->mall_id, 'is_delete' => 0]);
        if (!$model) {
            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '名词不存在或已被删除！');
        }
        $model->is_delete=1;
        if (!$model->save()) {
            return $this->responseErrorMsg($model);
        }
        NounHelper::removeKey($model->key,$model->mall_id);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '删除成功');
    }


}