namespace app\forms\mall\mall;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\HotImage;
use app\models\TabGoods;
use yii\helpers\Json;

class TabGoodsForm extends BaseModel
{
    public $id;
    public $name;
    public $list;

    public function rules()
    {
        return [
            [['name'], 'required'],
            [['id'], 'integer'],
            [['list'], 'safe'],
            [['name'], 'string']
        ]; // TODO: Change the autogenerated stub
    }

    public function attributeLabels()
    {
        return [
            'name' => '名称',
        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $model = TabGoods::findOne(['id' => $this->id, 'is_delete' => 0, 'mall_id' => $this->mall_id]);
        if (!$model) {
            $model = new TabGoods();
            $model->mall_id = $this->mall_id;
        }
        $model->name = $this->name;
        if ($this->list) {
            $model->list = Json::encode($this->list);
        } else {
            $model->list = Json::encode([]);
        }

        if (!$model->save()) {
            return $this->responseErrorMsg($model);
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '保存成功！');
    }

    public function search()
    {

        $model = TabGoods::getOne($this->id);
        if (!$model) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '未配置数据');
        }
        $info = $model->attributes;
        $info['list'] = Json::decode($info['list']);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['info' => $info]);
    }

    public function delete()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $model = TabGoods::getOne($this->id);
        if (!$model) {
            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '删除成功！');
        }
        $model->delete();
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '删除成功！');
    }

    public function map()
    {
        $list = TabGoods::find()->andWhere(['mall_id' => $this->mall_id, 'is_delete' => 0])->orderBy('id desc')->select('name as label,id as value')->asArray()
            ->all();
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['map' => $list]);
    }

}