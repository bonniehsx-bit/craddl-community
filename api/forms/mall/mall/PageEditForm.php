namespace app\forms\mall\mall;


use app\core\ApiCode;
use app\helpers\OptionHelper;
use app\helpers\SerializeHelper;
use app\models\BaseModel;
use app\models\DiyPage;
use app\models\Goods;
use yii\helpers\Json;

class PageEditForm extends BaseModel
{
    public $id;
    public $data;
    public $name;
    public $title_color;
    public $text_color;
    public $page_params;

    public function rules()
    {
        return [
            [['id'], 'integer'],
            [['data'], 'safe'],
            [['data'], 'string'],
            [['name', 'title_color', 'text_color', 'page_params'], 'string']
        ]; // TODO: Change the autogenerated stub
    }

    public function search()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $page = DiyPage::findOne(['is_delete' => 0, 'id' => $this->id, 'mall_id' => \Yii::$app->mall->id]);
        if (!$page) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '页面不存在!');
        }
        $data = Json::decode($page->data);
        if (!is_array($data)) {
            $data = [];
        }
        foreach ($data as &$item) {
            // 防御：用户保存时 data 字段可能为 null（拖入后没配置），下面所有分支都要兜底
            if (!isset($item['name'])) {
                continue;
            }
            // 选项卡商品:「按分类自动」的标签按当前分类现取;「手动挑选」的按存的 id 补最新的商品名 / 主图 / 价格
            // (存的可能只有 id,不补的话后台预览和配置列表都是空白卡片)
            if ($item['name'] == 'tab-goods' && !empty($item['data']['list']) && is_array($item['data']['list'])) {
                foreach ($item['data']['list'] as &$tab) {
                    if (!is_array($tab)) {
                        continue;
                    }
                    if (($tab['source'] ?? 'manual') === 'cat') {
                        $ids = \app\helpers\DiyHydrateHelper::idsByCat((int)($tab['cat_id'] ?? 0), (int)\Yii::$app->mall->id,
                            (int)($tab['cat_num'] ?? 6), (string)($tab['cat_sort'] ?? 'sales'));
                    } elseif (!empty($tab['goods_list']) && is_array($tab['goods_list'])) {
                        $ids = array_map(function ($g) {
                            return is_array($g) ? (int)($g['id'] ?? 0) : (int)$g;
                        }, $tab['goods_list']);
                    } else {
                        continue;
                    }
                    $ids = array_values(array_filter(array_map('intval', $ids)));
                    $tab['goods_list'] = $ids ? Goods::find()->select(['id', 'name', 'cover_pic', 'price', 'origin_price', 'sales', 'virtual_sales'])
                        ->where(['id' => $ids, 'mall_id' => \Yii::$app->mall->id, 'is_delete' => 0])
                        ->orderBy([new \yii\db\Expression('FIELD(id, ' . implode(',', $ids) . ')')])
                        ->asArray()->all() : [];
                }
                unset($tab);
                continue;
            }
            // 分类宫格:后台预览也显示真实的分类名 / 分类图 / 商品数
            if ($item['name'] == 'cat-grid') {
                \app\helpers\DiyHydrateHelper::fillCatGrid($item['data'], (int)\Yii::$app->mall->id);
                continue;
            }
            if ($item['name'] == 'goods-group') {
                $arr = isset($item['data']['list']) && is_array($item['data']['list']) ? $item['data']['list'] : [];
                // 「按分类自动」的商品组:后台预览按当前分类现取,和手机端看到的一致
                if (($item['data']['source'] ?? 'manual') === 'cat') {
                    $arr = \app\helpers\DiyHydrateHelper::idsByCat((int)($item['data']['cat_id'] ?? 0), (int)\Yii::$app->mall->id,
                        (int)($item['data']['cat_num'] ?? 6), (string)($item['data']['cat_sort'] ?? 'sales'));
                }

                if (!empty($arr)) {
                    // 防御：array_filter + array_map 强转 int，杜绝 SQL 拼接里出现非数字
                    $arr = array_values(array_filter(array_map('intval', $arr)));
                    if (empty($arr)) {
                        $item['data']['list'] = [];
                        continue;
                    }
                    $idsStr = implode(',', $arr);
                    // 关键：加 mall_id 过滤，防止跨商城拉到别 mall 的商品（B1 安全漏洞）
                    $list = Goods::find()
                        ->andWhere([
                            'id' => $arr,
                            'mall_id' => \Yii::$app->mall->id,
                            'is_delete' => 0,
                            'status' => 1,
                        ])
                        ->orderBy([new \yii\db\Expression("FIELD(id, $idsStr)")])
                        ->asArray()->all();
                    $item['data']['list'] = count($list) ? $list : [];
                } else {
                    if (!is_array($item['data'] ?? null)) {
                        $item['data'] = [];
                    }
                    $item['data']['list'] = [];
                }
            }
        }
        unset($item);
        $page->data = $data;
        $page->page_params = $page->page_params ? Json::decode($page->page_params) : null;
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['page' => $page]);
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $page = DiyPage::findOne(['is_delete' => 0, 'id' => $this->id, 'mall_id' => $this->mall_id]);
        if (!$page) {
            $page = new DiyPage();
            $page->mall_id = $this->mall_id;
        }
        $data = Json::decode($this->data);
        if (!is_array($data)) {
            $data = [];
        }
        foreach ($data as &$item) {
            if (!isset($item['name'])) {
                continue;
            }
            // 防御：用户刚添加未配置时 $item['data'] 是 null，下面任何 ['data']['list'] 解引用都会 fatal
            if ($item['name'] == 'dynamic-goods') {
                if (!is_array($item['data'] ?? null)) {
                    $item['data'] = [];
                }
                $item['data']['list'] = [];
            }
            if ($item['name'] == 'goods-group') {
                $list = (is_array($item['data'] ?? null) && isset($item['data']['list']) && is_array($item['data']['list']))
                    ? $item['data']['list']
                    : [];
                $arr = [];
                foreach ($list as $goods) {
                    // 兼容两种入参：纯 ID 数组（前端拖拽后没经过 search 回填）/ 完整 goods 对象数组（正常路径）
                    if (is_array($goods) && isset($goods['id'])) {
                        $arr[] = (int) $goods['id'];
                    } elseif (is_numeric($goods)) {
                        $arr[] = (int) $goods;
                    }
                }
                if (!is_array($item['data'] ?? null)) {
                    $item['data'] = [];
                }
                $item['data']['list'] = $arr;
            }
        }
        unset($item);
        $this->data = Json::encode($data);
        $page->data = $this->data;
        $page->title_color = $this->title_color;
        $page->text_color = $this->text_color;
        $page->name = $this->name;
        $page->page_params = $this->page_params ? (is_string($this->page_params) ? $this->page_params : Json::encode($this->page_params)) : null;
        if (!$page->save()) {
            return $this->responseErrorMsg($page);
        }
        if ($page->is_home) {
            OptionHelper::set('diy_home_name', $page->name, $this->mall_id);
            OptionHelper::set('diy_home', SerializeHelper::decode($page->data), $this->mall_id);
        }
        // 关键：回传 page->id，让前端在"新建"/"另存为"路径能拿到新主键，
        // 避免下一次保存又走新建分支产生重复 INSERT（B2/B3 修复）
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功!', ['id' => (int) $page->id]);
    }

    public function delete()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $page = DiyPage::findOne(['is_delete' => 0, 'id' => $this->id, 'mall_id' => $this->mall_id]);
        if (!$page) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '页面不存在或已被删除!');
        }
        $page->is_delete = 1;
        if (!$page->save()) {
            return $this->responseErrorMsg($page);
        }

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '删除成功');
    }

    public function setHome()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        DiyPage::updateAll(['is_home' => 0], ['is_delete' => 0, 'is_home' => 1, 'mall_id' => $this->mall_id]);
        $page = DiyPage::findOne(['is_delete' => 0, 'id' => $this->id, 'mall_id' => $this->mall_id]);
        if (!$page) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '页面不存在或已被删除!');
        }
        $page->is_home = 1;
        if (!$page->save()) {
            return $this->responseErrorMsg($page);
        }
        OptionHelper::set('diy_home_name', $page->name, $this->mall_id);
        OptionHelper::set('diy_home', SerializeHelper::decode($page->data), $this->mall_id);
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '设置成功');
    }

    /**
     * 设置某个 diy 页面为"审核版页面"（每 mall 唯一）
     *
     * 当 VersionHelper::checkIsAuditMode() 命中时，C 端首页接口将返回此页面而非 is_home 主页，
     * 用于 App Store / 微信小程序审核期间隐藏敏感内容。
     */
    public function setAuditPage()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // 同 mall 内只保留当前一个 is_audit_page=1
        DiyPage::updateAll(
            ['is_audit_page' => 0],
            ['is_delete' => 0, 'is_audit_page' => 1, 'mall_id' => $this->mall_id]
        );
        $page = DiyPage::findOne(['is_delete' => 0, 'id' => $this->id, 'mall_id' => $this->mall_id]);
        if (!$page) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '页面不存在或已被删除!');
        }
        $page->is_audit_page = 1;
        if (!$page->save()) {
            return $this->responseErrorMsg($page);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '已设为审核版页面');
    }

    /**
     * 取消"审核版页面"标记（清空后 mall 内无审核版页面，审核版本将 fallback 到 is_home 主页）
     */
    public function unsetAuditPage()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $page = DiyPage::findOne(['is_delete' => 0, 'id' => $this->id, 'mall_id' => $this->mall_id]);
        if (!$page) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '页面不存在或已被删除!');
        }
        $page->is_audit_page = 0;
        if (!$page->save()) {
            return $this->responseErrorMsg($page);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '已取消审核版标记');
    }
}
