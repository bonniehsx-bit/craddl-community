namespace app\forms\mall\mall;


use app\core\ApiCode;
use app\helpers\HtmlHelper;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\File;
use app\models\FileGroup;

class FileHtmlForm extends BaseModel
{

    public $group_id;

    public $html;


    public function rules()
    {
        return [
            [['group_id'], 'integer'],
            [['html'], 'string']
        ]; // TODO: Change the autogenerated stub
    }


    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $urls = HtmlHelper::getImgsFromHtml($this->html);
        $urls = array_unique($urls);

        $i = 0;
        foreach ($urls as $url) {
            $file = new File();
            $file->thumb_url = $url;
            $file->mall_id = $this->mall_id;
            $file->admin_id = \Yii::$app->admin->id;
            $file->location = 'local';
            $file->type = 'image';
            $file->group_id = $this->group_id ?? 0;
            $file->name = 'html_' . date('YmdHis') . rand(1000, 9999);
            $file->url = $url;
            if (!$file->save()) {
                return $this->responseErrorMsg($file);
            }
            $i++;
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '成功获取.' . $i . '张图片');
    }

    public function getGroup()
    {
        $list = FileGroup::find()->andWhere(['mall_id' => $this->mall_id, 'is_delete' => 0])->orderBy('id desc')->asArray()->all();
        array_unshift($list, ['id' => 0, 'name' => '未分组']);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['list' => $list]);
    }

    public function delete()
    {
        $file = File::findOne(['mall_id' => $this->mall_id, 'id' => $this->id]);
        if (!$file) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '文件不存在!');
        }
        $path = $file->path;
        if (!$file->delete()) {
            return $this->responseErrorMsg($file);
        }
        if ($path) {
            try {
                unlink($path);
            } catch (\Exception $e) {

            }
        }
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '删除成功');
    }
}