namespace app\forms\mall\mall;


use app\core\ApiCode;
use app\forms\mall\link\LinkForm;
use app\helpers\CacheHelper;
use app\helpers\ResponseHelper;
use app\helpers\SerializeHelper;
use app\models\BaseModel;

class PagePathForm extends BaseModel
{
    public $page_path;
    public $name;

    public function rules()
    {
        return [
            [['page_path', 'name'], 'string']
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $list = $this->getPathList();
        $h5Root = \Yii::$app->request->hostInfo . '/h5';
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'h5Root' => $h5Root, 'mall_id' => \Yii::$app->mall->id]);
    }


    private function getPathList()
    {
        // 核心商城链接：保留 getMallLinks 的分组名（核心页面 / 商城与商品 / 用户中心 ...）
        $result = [];
        $form = new LinkForm();
        foreach ($form->getMallLinks() as $group) {
            $groupName = $group['name'] ?? '其他';
            foreach (($group['links'] ?? []) as $link) {
                $result[] = [
                    'name'       => $link['name'],
                    'page'       => $link['url'],
                    'group'      => $groupName,
                    'group_type' => 'core', // 核心
                ];
            }
        }
        // 插件链接：用插件中文名(label)作分组
        $result = array_merge($result, $this->getPluginLinks());
        return $result;
    }

    private function getPluginLinks()
    {
        // ⚠ 只列**当前商城已授权**的插件页面。
        // 原来直接遍历 \Yii::$app->plugin->list —— 那是「平台上所有已安装插件」,与商城无关,
        // 结果 A 商城的后台能看到 B 商城才买的插件页面路径,配到装修里点开就是空白/报错。
        // 判定口径与后台菜单、路由完全一致(MenuTreeForm / RouterListForm 都用它),不另起一套。
        $enabled = \app\models\MallPlugin::enabledPlugins((int) \Yii::$app->mall->id);

        $list = \Yii::$app->plugin->list;
        $result = [];
        foreach ($list as $item) {
            if (!in_array($item->name, $enabled, true)) {
                continue; // 本商城未授权
            }
            $plugin = \Yii::$app->plugin->getPlugin($item->name);
            if (!$plugin) {
                continue;
            }
            $groupName = $plugin->getLabel();
            foreach ((array) $plugin->getLinks() as $link) {
                // 防御:getLinks() 由各插件自行声明,少写一个键不该让整页 500。
                // (plaza 曾把 url 误写成 route,直接导致本接口报 Undefined array key "url"。)
                if (!is_array($link) || empty($link['url']) || empty($link['name'])) {
                    \Yii::warning('[页面路径] 插件 ' . $item->name . ' 的 getLinks() 存在缺 name/url 的项,已跳过:'
                        . json_encode($link, JSON_UNESCAPED_UNICODE|JSON_UNESCAPED_SLASHES), 'mall');
                    continue;
                }
                $result[] = [
                    'name'       => $link['name'],
                    'page'       => $link['url'],
                    'group'      => $groupName,
                    'group_type' => 'plugin', // 插件
                ];
            }
        }
        return $result;
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $list = $this->getPathList();
        foreach ($list as &$item) {
            if ($item['page'] == $this->page_path) {
                $item['name'] = $this->name;
            }
        }
        unset($item);
        CacheHelper::set('page_list_' . \Yii::$app->mall->id, $list);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '保存成功');
    }
}
