namespace app\forms\mall\plugin;

use app\core\ApiCode;
use app\helpers\PluginEntryHelper;
use app\helpers\ServerHelper;
use app\models\BaseModel;
use app\models\MallPlugin;
use app\models\Menu;
use app\models\Plugin;
use app\models\RoleMenu;


class PluginListForm extends BaseModel
{
    public $keyword;

    public function rules()
    {
        return [
            [['keyword'], 'string'],

        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        $query = MallPlugin::find()->alias('m')
            ->innerJoin(['p' => Plugin::tableName()], 'm.plugin=p.name');
        $query->andFilterWhere(['like', 'p.label', $this->keyword]);
        $list = $query->andWhere(['m.mall_id' => $this->mall_id, 'm.is_delete' => 0, 'p.is_delete' => 0])->select('p.*')->asArray()->all();
        $adminId = \Yii::$app->admin->id;
        $shortcuts = \app\models\AdminPluginShortcut::find()->where([
            'admin_id' => $adminId, 
            'mall_id' => $this->mall_id, 
            'is_delete' => 0
        ])->select('plugin_name')->column();

        // 入口路由统一由 PluginEntryHelper 解析,一次批量算完。
        //
        // 这里原先是在 foreach 里逐个插件 `Menu::find()->orderBy('order_num asc')->scalar()`,
        // 除了 N+1,那条查询还漏了四件事,直接导致「点进应用不是侧边栏第一项」:
        //   ① 把该插件所有层级的菜单拉平只比 order_num —— 而 order_num 只在同层级内有意义。
        //      plaza 就是这么落到三级目录下的「租户管理」(order=0),而侧边栏第一项是顶层的「数据概览」;
        //   ② 没有 is_delete=0,已删除的菜单也会被选中;
        //   ③ 没有 hidden=0,会跳到商户特意隐藏掉的页面;
        //   ④ 没套 MallMenuOption 的商户自定义(custom_path / custom_sort),
        //      商户改过菜单路径或顺序,这里还按原始值算。
        // PluginEntryHelper 这四条全都处理了,并且按侧边栏的树形顺序深度优先取第一个可落地页面。
        //
        // ⛔ 操作员只列他角色有菜单权限的应用,入口也只在这些菜单里挑(口径同侧边栏 RouterListForm)。
        //    应用中心现在是顶栏常驻入口,不过滤的话操作员会看到一堆点进去 403 / 空白的应用。
        $allowedMenuIds = null;
        $identity = \Yii::$app->admin->identity ?? null;
        if ($identity && !$identity->isMallSuper()) {
            $allowedMenuIds = RoleMenu::find()->alias('r')
                ->innerJoin(['mm' => Menu::tableName()], 'mm.menu_id = r.menu_id')
                ->andWhere(['r.role_id' => (int)$identity->role_id])
                ->select('r.menu_id')->column();
            $allowedPlugins = $allowedMenuIds ? array_flip(Menu::find()->select('plugin')->distinct()
                ->where(['menu_id' => $allowedMenuIds, 'menu_type' => ['M', 'C']])->column()) : [];
            $list = array_values(array_filter($list, function ($i) use ($allowedPlugins) {
                return isset($allowedPlugins[$i['name']]);
            }));
        }
        $entries = PluginEntryHelper::resolve(array_column($list, 'name'), (int)$this->mall_id, $allowedMenuIds);

        foreach ($list as &$item) {
            // 取不到(插件没有任何可见菜单)时保留原来的猜测式兜底,避免前端拿到空路由;
            // has_entry=false 让应用中心把它灰掉、点了提示,而不是跳一个大概率 404 的地址
            $item['has_entry'] = isset($entries[$item['name']]);
            $item['route_path'] = $entries[$item['name']] ?? ('/plugins/' . $item['name'] . '/index');
            $item['path'] = $item['route_path']; // 兼容旧接口
            $item['is_shortcut'] = in_array($item['name'], $shortcuts) ? true : false;
            
            // 兼容旧默认图片地址，商城应用与平台插件列表共用同一品牌默认值。
            $uploadedImg = !empty($item['pic_url']) ? $item['pic_url'] : ($item['logo'] ?? '');
            $item['pic_url'] = \app\helpers\PluginHelper::resolveLogo($item['name'], $uploadedImg);

            // 矢量图标（插件 getIcon() 声明的 element-ui 图标类名）。
            // 不依赖文件/host，前端在无真实上传 logo 时用它渲染，杜绝 404/跨域裂图。
            $item['icon'] = '';
            $pluginClass = 'app\\plugins\\' . $item['name'] . '\\Plugin';
            if (class_exists($pluginClass)) {
                try {
                    $item['icon'] = (string)(new $pluginClass())->getIcon();
                } catch (\Throwable $e) {
                    $item['icon'] = '';
                }
            }
        }

        unset($item);

        $newList = [];
        /**
         * @var MallPlugin[] $list
         */
        $group1 = ['group_name' => '分润类', 'description' => '增进代理商积极性', 'list' => [], 'plugin_pic' => ServerHelper::getHost() . '/statics/icons/plugin_bg1.png'];
        $group2 = ['group_name' => '营销类', 'description' => '促进用户二次复购', 'list' => [], 'plugin_pic' => ServerHelper::getHost() . '/statics/icons/plugin_bg1.png'];
        $group3 = ['group_name' => '工具类', 'description' => '高效管理商城业务', 'list' => [], 'plugin_pic' => ServerHelper::getHost() . '/statics/icons/plugin_bg1.png'];
        $group4 = ['group_name' => '客户定制类', 'description' => '面向特定客户的定制功能', 'list' => [], 'plugin_pic' => ServerHelper::getHost() . '/statics/icons/plugin_bg1.png'];

        foreach ($list as $item) {
            $item['status'] = 1;
            if ($item['type'] == \app\plugins\Plugin::TYPE_COMMISSION) {
                $group1['list'][] = $item;
            }

            if ($item['type'] == \app\plugins\Plugin::TYPE_MARKET) {
                $group2['list'][] = $item;
            }
            if ($item['type'] == \app\plugins\Plugin::TYPE_TOOL) {
                $group3['list'][] = $item;
            }
            if ($item['type'] == \app\plugins\Plugin::TYPE_CUSTOM) {
                $group4['list'][] = $item;
            }
        }
        $newList[] = $group1;
        $newList[] = $group2;
        $newList[] = $group3;
        // 客户定制类:仅在确有定制插件时才展示该分组,避免空分类卡片
        if (!empty($group4['list'])) {
            $newList[] = $group4;
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $newList]);
    }
}
