namespace app\forms\admin;


use app\core\ApiCode;
use app\models\Admin;
use app\models\BaseModel;

class PasswordChangeForm extends BaseModel
{
    public $id;

    public $password;

    public $newPassword;

    public function rules()
    {
        return [
            [['password', 'newPassword'], 'required'],
            [['password', 'newPassword'], 'string', 'max' => 64],

        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        /**
         * @var Admin $admin
         */
        $admin = \Yii::$app->admin->identity;
        if (!$admin) {
            return $this->apiResponse(ApiCode::CODE_NOT_LOGIN, '请先登录');
        }
        // 校验原密码。存储哈希非法(空/老格式/被截断,如从外部直接写库或老系统导入的账号)时,
        // validatePassword 会抛 InvalidArgumentException(而非返回 false),裸调直接 500。
        $hashUsable = true;
        $oldOk = false;
        try {
            $oldOk = \Yii::$app->security->validatePassword($this->password, (string)$admin->password);
        } catch (\yii\base\InvalidArgumentException $e) {
            $hashUsable = false; // 存储哈希本身损坏 → 该账号没有可用密码
        }
        if ($hashUsable) {
            // 正常路径:哈希可用,必须验对原密码
            if (!$oldOk) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '原密码不正确!');
            }
        } else {
            // 自愈:哈希损坏=账号无可用密码(也无法用密码登录)。当前会话已通过后台鉴权,
            // 允许直接设置新密码把坏哈希修好——否则超管自己哈希坏了会陷入
            // 「改密要原密码 → 原密码验不了 → 又无人可重置」的死胡同。
            // 不构成越权:会话持有者本就有完整后台权限,这只是修复而非提权。留痕便于审计。
            \Yii::warning(
                "[admin] id={$admin->id} username={$admin->username} 存储密码哈希非法,已由本人在改密时自愈重置",
                'security'
            );
        }
        $admin->password = \Yii::$app->security->generatePasswordHash($this->newPassword);
        if (!$admin->save()) {
            return $this->responseErrorMsg($admin);
        }
        // 改密后踢出所有设备
        Admin::invalidateAuth($admin->id);
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');
    }
}
