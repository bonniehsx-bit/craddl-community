namespace app\forms\admin;


use app\core\ApiCode;
use app\models\BaseModel;

class PluginForm extends BaseModel
{
    public $name;
    public $logo;

    public function rules()
    {
        return [
            [['name'], 'required'],
            [['name', 'logo'], 'string']
        ]; // TODO: Change the autogenerated stub
    }


    public function install()
    {

        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        /**
         * 1、下载代码
         */


        try {
            $res = \Yii::$app->plugin->install($this->name);
        } catch (\Exception $e) {
            return $this->apiResponse(ApiCode::CODE_FAIL, $e->getMessage());
        }
        if (!$res) {
            return $this->apiResponse(ApiCode::CODE_SUCCESS, '安装失败');
        }
        $this->syncCron(); // 新装插件的定时任务同步进 Redis(sync 只含已安装插件)
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '安装成功');
    }

    public function uninstall()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $plugin = \app\models\Plugin::findOne(['name' => $this->name, 'is_delete' => 0]);
        if (!$plugin) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '插件未安装或不存在！');
        }
        $plugin->is_delete = 1;
        if (!$plugin->save()) {
            return $this->responseErrorMsg($plugin);
        }
        $this->syncCron(); // 卸载后把该插件的定时任务从 Redis 移除
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '卸载成功');
    }

    /**
     * 插件安装/卸载后:重新同步 cron 到 Redis。
     * 现在 crontab/sync 只含【已安装插件】的任务,故装/卸后需刷新,否则 Redis 配置滞后
     * (新装插件任务缺失 / 已卸插件任务残留)。失败只告警,不影响安装/卸载主流程。
     */
    private function syncCron(): void
    {
        try {
            \app\services\CronTaskService::syncToRedis();
        } catch (\Throwable $e) {
            \Yii::warning('[PluginForm] 插件变更后 cron 同步失败: ' . $e->getMessage(), 'crontab');
        }
    }


    /**
     * 彻底删除插件目录文件(危险操作)。
     * 仅允许删除【未安装】的插件(DB 无 is_delete=0 记录):已卸载或从未安装的本地插件目录。
     * 已安装插件禁止直接删文件,必须先卸载,避免运行时引用缺失导致系统异常。
     */
    public function delete()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $name = (string)$this->name;
        // 安全红线:插件标识只能是目录名(字母数字下划线),严防 ../ 等路径穿越
        if (!preg_match('/^[a-zA-Z0-9_]+$/', $name)) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '非法的插件标识');
        }
        // 已安装(is_delete=0)禁止删文件,必须先卸载
        $installed = \app\models\Plugin::findOne(['name' => $name, 'is_delete' => 0]);
        if ($installed) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '该插件仍处于已安装状态,请先卸载后再删除文件');
        }

        $baseDir = \Yii::$app->basePath . '/plugins';
        $targetDir = $baseDir . '/' . $name;
        $realBase = realpath($baseDir);
        $realTarget = realpath($targetDir);
        if ($realTarget === false || !is_dir($realTarget)) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '插件目录不存在,可能已被删除');
        }
        // realpath 双保险:确认目标确实位于 plugins 目录下(防软链逃逸/穿越)
        if ($realBase === false || strpos($realTarget, $realBase . DIRECTORY_SEPARATOR) !== 0) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '插件目录路径异常,已阻止删除');
        }

        try {
            \yii\helpers\FileHelper::removeDirectory($realTarget);
        } catch (\Throwable $e) {
            \Yii::error('[PluginForm::delete] 删除插件目录失败: ' . $e->getMessage());
            return $this->apiResponse(ApiCode::CODE_FAIL, '删除失败:' . $e->getMessage());
        }
        // 清理该插件遗留的软删除记录(is_delete=1),避免孤儿数据影响将来同名重装
        \app\models\Plugin::deleteAll(['name' => $name, 'is_delete' => 1]);
        $this->syncCron(); // 目录删除后刷新 cron,清掉可能残留的该插件任务
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '插件文件已彻底删除');
    }

    public function setLogo()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $plugin = \app\models\Plugin::findOne(['name' => $this->name, 'is_delete' => 0]);
        if (!$plugin) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '插件未安装或不存在！');
        }

        if (!$this->logo) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '请选择logo');
        }
        $plugin->logo = $this->logo;
        if (!$plugin->save()) {
            return $this->responseErrorMsg($plugin);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');
    }

    /**
     * @Author: 动力宇宙 ganxiaohao
     * @Date: 2020-11-22
     * @Time: 17:15
     * @Note:插件更新
     */
    public function update()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        try {
            $res = \Yii::$app->plugin->update($this->name);
        } catch (\Exception $e) {
            return $this->apiResponse(ApiCode::CODE_FAIL, $e->getMessage());
        }
        if (!$res) {
            return $this->apiResponse(ApiCode::CODE_SUCCESS, '安装失败');
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '安装成功');
    }
}
