namespace app\forms\admin;


use app\core\ApiCode;
use app\models\BaseModel;

class PluginListForm extends BaseModel
{
    public $keyword;
    public $limit;
    public $page;


    public function rules()
    {
        return [
            [['page', 'limit'], 'integer'],
            [['limit'], 'default', 'value' => 10],
            [['keyword'], 'string']

        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        $list = \Yii::$app->plugin->scanPluginList(); //只获取本地插件
        $newList = [];
        foreach ($list as $plugin) {
            // scanPluginList() 直接返回实例化对象；getPlugin() 找不到类时返回 false，跳过
            if (!$plugin) {
                continue;
            }
            $exist = \app\models\Plugin::find()->where(['name' => $plugin->getName(), 'is_delete' => 0])->one();

            $item                 = [];
            $item['is_local']     = 1;
            $item['status']       = 0;
            $item['is_update']    = 0;
            $item['name']         = $plugin->getName();
            $item['label']        = $plugin->getLabel();
            $item['local_version'] = $plugin->getVersion();
            $item['dsc']          = $plugin->getDsc();
            $item['type']         = $plugin->getType(); // fix: 之前从未赋值，导致分组失效

            // 有版本更新检测（与 DB 记录对比）
            if ($exist && $plugin->getVersion() != $exist->version) {
                $item['is_update'] = 1; // fix: 之前与未定义的 $item['version'] 比较，且逻辑值反了
            }

            // 默认 Logo 统一解析，保留自定义上传图片，不在列表读取时回写配置。
            $item['logo'] = \app\helpers\PluginHelper::resolveLogo($item['name'], $exist ? $exist->logo : '');

            if ($exist) {
                $item['status'] = 1;
            }

            // 分组名映射（与 Plugin 类型常量对齐：0分润 1营销 2工具 3客户定制）
            $typeNames = [
                \app\plugins\Plugin::TYPE_COMMISSION => '分润类',
                \app\plugins\Plugin::TYPE_MARKET     => '营销类',
                \app\plugins\Plugin::TYPE_TOOL       => '工具类',
                \app\plugins\Plugin::TYPE_CUSTOM     => '客户定制类',
            ];
            $item['type']       = (int)$item['type'];
            $item['group_name'] = $typeNames[$item['type']] ?? '其他';

            $newList[] = $item;
        }
        $list = $newList;
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list]);
    }
}
