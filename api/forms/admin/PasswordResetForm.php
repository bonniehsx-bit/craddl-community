namespace app\forms\admin;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\Admin;
use app\models\BaseModel;

class PasswordResetForm extends BaseModel
{
    public $id;
    public $password;

    public function rules()
    {
        return [
            [['id','password'], 'required'],
            [['password'],'string'],
        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        /** @var Admin $current */
        $current = \Yii::$app->admin->identity;
        if (!$current) {
            return ResponseHelper::send(ApiCode::CODE_NOT_LOGIN, '请先登录');
        }

        // SaaS 隔离：非超管只能重置【本商城】内的账号，防止跨商城/越权改密
        $cond = ['id' => $this->id, 'is_delete' => 0];
        if ($current->admin_type != Admin::ADMIN_TYPE_SUPER) {
            $cond['mall_id'] = \Yii::$app->mall->id ?? 0;
        }
        $admin = Admin::findOne($cond);
        if (!$admin) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '用户不存在或无权操作');
        }

        // 权限层级：非超管不得重置 >= 自己权限等级的账号（admin_type 越小权限越高）
        // 例：店主(1)只能改操作员(2)，改不了其他店主/超管；操作员(2)改不了店主/超管
        if ($current->admin_type != Admin::ADMIN_TYPE_SUPER
            && (int)$admin->admin_type <= (int)$current->admin_type) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '无权重置该账号密码');
        }

        if(!$this->password){
            return  ResponseHelper::send(ApiCode::CODE_FAIL,'请输入密码');
        }
        $admin->password = \Yii::$app->security->generatePasswordHash($this->password);
        if (!$admin->save()) {
            return $this->responseErrorMsg($admin);
        }
        // 改密后踢出所有设备
        Admin::invalidateAuth($admin->id);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS,'重置成功!');
    }

}