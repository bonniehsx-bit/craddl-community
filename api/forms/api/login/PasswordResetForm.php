namespace app\forms\api\login;


use app\core\ApiCode;
use app\helpers\CacheHelper;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\User;
use app\services\UserService;

class PasswordResetForm extends BaseModel
{
    public $phone_ticket; // type=2 时:手机号授权接口签发的一次性凭证
    public $password;
    public $code;

    public $type;

    public $mobile;

    public function rules()
    {
        return [
            [['password'], 'required', 'message' => '请输入新密码'],
            [['type'], 'integer'],
            [['code', 'password', 'mobile', 'phone_ticket'], 'string'],
            [['password'], 'string', 'min' => 6, 'tooShort' => '密码不能少于6位'],
        ]; // TODO: Change the autogenerated stub
    }


    public function reset()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // type=2(小程序「使用手机号验证」):号码只认服务端签发的凭证,不认前端传的 mobile。
        // 原来带 type=2 就整段跳过验证码,又直接信前端的号码 ——
        // 不用登录、不用验证码,拿别人的手机号就能把别人的密码改掉(账号接管)
        if ((int) $this->type === 2) {
            $mobile = MpwxPhoneForm::peekTicket($this->phone_ticket, (int) $this->mall_id);
            if ($mobile === null) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '手机号验证已过期,请重新获取');
            }
            $this->mobile = $mobile;
        } else {
            // 同登录:带失败计数,避免被无限次试码直接重置掉别人的密码
            list($ok, $msg) = CacheHelper::verifySmsCode($this->mobile, $this->code);
            if (!$ok) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, $msg);
            }
        }
        // 限定本商城:同一个手机号在别的商城也可能有账号,原来可能改到别人商城的那个
        $user = User::findOne(['mobile' => $this->mobile, 'mall_id' => $this->mall_id, 'is_delete' => 0, 'status' => User::STATUS_NORMAL]);
        if (!$user) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '账号不存在');
        }
        $user->password = \Yii::$app->security->generatePasswordHash($this->password);
        if (!$user->save()) {
            return $this->responseErrorMsg($user);
        }
        // 改密后踢出所有设备
        UserService::invalidateUserAuth($user->id);
        CacheHelper::remove(CacheHelper::smsCodeKey($this->mobile));
        MpwxPhoneForm::dropTicket($this->phone_ticket);   // 凭证一次性
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '密码修改成功，去登录吧！');
    }

}