namespace app\forms\api\login;


use app\core\ApiCode;
use app\helpers\CacheHelper;
use app\helpers\HttpHelper;
use app\helpers\ResponseHelper;
use app\helpers\WechatHelper;
use app\models\BaseModel;

class MpwxPhoneForm extends BaseModel
{
    public $code;
    public $encryptedData;
    public $iv;


    public function rules()
    {
        return [
            [['code', 'iv', 'encryptedData'], 'string']
        ]; // TODO: Change the autogenerated stub
    }


    public function getPhone()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        WechatHelper::init($this->mall_id);
        $app = \Yii::$app->wechat->miniProgram;
        $mobile = null;
        if (!$mobile && $this->code) {
            $realToken = $app->getAccessToken()->getToken();
            $result = HttpHelper::postRaw("https://api.weixin.qq.com/wxa/business/getuserphonenumber?access_token=$realToken", ['code' => $this->code]);
            if (!isset($result['errcode'])) {
                \Yii::warning($result);
                return ResponseHelper::send(ApiCode::CODE_FAIL, '登录发生错误，请重试或联系我们');
            }
            if (!$result['errcode']) {
                $mobile = $result['phone_info']['purePhoneNumber'];
            }
            if ($result['errcode'] == 40001) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, $result['errmsg']);
            }
        }
        if (!$mobile) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '未获取到手机号');
        }
        // 手机号给前端只是为了显示;真正提交(快捷注册、微信验证重置密码)必须带 phone_ticket,
        // 服务端从凭证里取号。原来那两个接口直接信前端传来的 mobile,
        // 带上 type=2 就能跳过短信验证码 —— 任何人都能把别人的密码改掉、拿别人的号注册
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '登录成功', [
            'mobile'       => $mobile,
            'phone_ticket' => self::issueTicket($mobile, (int) $this->mall_id),
        ]);
    }

    /** 凭证有效期:从授权手机号到点提交,10 分钟足够 */
    const TICKET_TTL = 600;

    private static function ticketKey(string $ticket): string
    {
        return 'mpwx_phone_ticket_' . $ticket;
    }

    /** 签发一次性凭证:记住「这个号码是刚从微信授权拿到的、属于哪个商城」 */
    public static function issueTicket(string $mobile, int $mallId): string
    {
        $ticket = bin2hex(random_bytes(16));
        CacheHelper::set(self::ticketKey($ticket), ['mobile' => $mobile, 'mall_id' => $mallId], self::TICKET_TTL);
        return $ticket;
    }

    /**
     * 用凭证换手机号(只看不删):过期、伪造、别的商城签的都返回 null。
     * 业务成功后再 dropTicket,中途校验失败(比如密码太短)不用让用户重新授权。
     */
    public static function peekTicket(?string $ticket, int $mallId): ?string
    {
        $ticket = (string) $ticket;
        if (!preg_match('/^[0-9a-f]{32}$/', $ticket)) {
            return null;
        }
        $data = CacheHelper::get(self::ticketKey($ticket));
        if (!is_array($data) || (int) ($data['mall_id'] ?? -1) !== $mallId || empty($data['mobile'])) {
            return null;
        }
        return (string) $data['mobile'];
    }

    public static function dropTicket(?string $ticket): void
    {
        if (preg_match('/^[0-9a-f]{32}$/', (string) $ticket)) {
            CacheHelper::remove(self::ticketKey((string) $ticket));
        }
    }
}
