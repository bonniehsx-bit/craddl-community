namespace app\forms\api\login;


use app\core\ApiCode;
use app\helpers\CacheHelper;
use app\helpers\OptionHelper;
use app\helpers\ResponseHelper;
use app\helpers\SmsHelper;
use app\models\BaseModel;

class SmsCodeForm extends BaseModel
{
    public $mobile;

    public function rules()
    {
        return [
            [['mobile'], 'required'],
            [['mobile'], 'string']
        ]; // TODO: Change the autogenerated stub
    }

    public function attributeLabels()
    {
        return [
            'mobile' => '手机号'
        ]; // TODO: Change the autogenerated stub
    }

    public function getCode()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $mall_setting = OptionHelper::get('mall_setting', $this->mall_id);
        if ($mall_setting && $mall_setting['is_dev'] == 1 && $mall_setting['default_sms_code']) {
            //发送短信
            CacheHelper::setSmsCode($this->mobile, $mall_setting['default_sms_code'], 180);
            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '已发送');
        }
        $code = CacheHelper::get(CacheHelper::smsCodeKey($this->mobile));
        if ($code) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '请勿频繁获取验证码!');
        }

        $ip = \Yii::$app->request->userIP;
        $ipCacheKey = 'sms_ip_limit_' . $ip;
        $ipCount = CacheHelper::get($ipCacheKey) ?: 0;
        if ($ipCount >= 10) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '您的IP请求次数过多，请稍后再试');
        }
        CacheHelper::set($ipCacheKey, $ipCount + 1, 3600);

        // 按手机号的日上限:IP 那道换个代理就绕开了,而短信是按条计费的。
        // 计数只在**发送成功后**才加(见下),发失败不该扣人家配额。
        //
        // 兜底取 10 而不是 0(不限制):这个配置项是新加的,存量商城的 mall_setting 里
        // 根本没有这个键,兜底给 0 的话加固对它们一个都不生效,得管理员逐个进后台
        // 保存一次才有用 —— 那等于白做。10 次/天对正常用户绰绰有余,
        // 真有高频场景可以在后台调大,填 0 即关闭。
        $dayLimit = (int)($mall_setting['sms_day_limit'] ?? 10);
        $dayKey = 'sms_day_' . (int)$this->mall_id . '_' . $this->mobile . '_' . date('Ymd');
        if ($dayLimit > 0 && (int)CacheHelper::get($dayKey) >= $dayLimit) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '今日验证码获取次数已达上限，请明天再试');
        }

        // random_int 而非 mt_rand:后者是 Mersenne Twister,内部状态可以由若干次输出反推,
        // 而验证码场景下攻击者能合法拿到自己手机上的连续多个码。
        $code = random_int(100000, 999999);

        CacheHelper::setSmsCode($this->mobile, $code, 180);

        // 渠道分发、模板取值、签名前置全在 SmsHelper::sendVerifyCode 里。
        // 这里原先是把那一整套(读 setting → if aliyun / if tx / if dxb → 各自构造
        // EasySms config)复制了一份,和 sendNotify 读同一批配置字段却各写各的,
        // 结果 dxb 分支漏了 applyDxbSign(),同一商城「通知带签名、验证码不带」。
        $res = SmsHelper::sendVerifyCode((int)$this->mall_id, (string)$this->mobile, (string)$code);

        if (($res['code'] ?? ApiCode::CODE_FAIL) !== ApiCode::CODE_SUCCESS) {
            // 发失败要把上面预存的码清掉,否则用户收不到短信、这 180 秒里
            // 再点「获取验证码」会被上面那道「请勿频繁获取」挡住,等于卡死。
            CacheHelper::remove(CacheHelper::smsCodeKey($this->mobile));
            return $this->apiResponse(ApiCode::CODE_FAIL, $res['msg'] ?? '验证码发送失败，请重试');
        }

        // 发出去了才计入日配额,TTL 到当天结束为止(跨自然日自动归零)
        if ($dayLimit > 0) {
            $ttl = max(60, strtotime('tomorrow') - time());
            CacheHelper::set($dayKey, (int)CacheHelper::get($dayKey) + 1, $ttl);
        }

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '发送成功');
    }
}
