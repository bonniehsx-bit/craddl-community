namespace app\forms\api\user;

use app\core\ApiCode;
use app\helpers\BaiduHelper;
use app\helpers\ResponseHelper;
use app\helpers\UserHelper;
use app\models\BaseModel;
use app\models\UserAddress;
use yii\helpers\Json;

class AddressAnalyseSaveForm extends BaseModel
{

    public $content;

    public function rules()
    {
        return [
            [['content'], 'required']
        ]; // TODO: Change the autogenerated stub
    }


    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        if (!is_array($this->content)) {
            $this->content = Json::decode($this->content);
        }
        if (!$this->content['phonenum']) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '手机号不存在!');
        }
        if (!$this->content['person']) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '联系人不能为空!');
        }

        $address = new UserAddress();
        $address->user_id = UserHelper::getMyId();
        $address->mall_id = $this->mall_id;
        $address->province_code = $this->content['province_code'];
        $address->city_code = $this->content['city_code'];
        $address->county_code = $this->content['county_code'];
        $address->town_code = $this->content['town_code'];
        $address->province_name = $this->content['province'];
        $address->city_name = $this->content['city'];
        $address->county_name = $this->content['county'];
        $address->town_name = $this->content['town'];
        $address->mobile = $this->content['phonenum'];
        $address->name = $this->content['person'];
        $address->area = $address->province_name . ' ' . $address->city_name . ' ' . $address->county_name;
        $address->detail = $this->content['detail'];
        $address->address = $address->area . ' ' . $address->detail;
        if (!$address->save()) {
            return $this->responseErrorMsg($address);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '保存成功');


    }
}