namespace app\forms\api\user;


use app\core\ApiCode;
use app\helpers\JobHelper;
use app\helpers\QrcodeHelper;
use app\helpers\ResponseHelper;
use app\helpers\ServerHelper;
use app\jobs\common\UnlinkJob;
use app\models\BaseModel;

class TempQrcodeForm extends BaseModel
{
    public $code;


    public function rules()
    {
        return [
            [['code'], 'string']
        ]; // TODO: Change the autogenerated stub
    }

    public function getQrcode()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $res = QrcodeHelper::create($this->code);
        JobHelper::push(new UnlinkJob(['path' => $res['path']]), 10);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['url' => ServerHelper::getHost() . $res['file_name']]);
    }
}
