namespace app\forms\api\user;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\helpers\UserHelper;
use app\helpers\WechatHelper;


use app\models\BaseModel;
use app\models\User;
use EasyWeChat\Kernel\Exceptions\InvalidConfigException;

class BindMpwxForm extends BaseModel
{
    public $code;
    public $encryptedData;
    public $iv;
    public $access_token;
    public $openId;
    public $unionId;
    public $avatarUrl;
    public $nickName;
    public $mobile;
    public $password;
    private $mpwx_try_times = 0;
    public $session_key;
    public $wechat_info_key;
    public $auth_code;


    public function rules()
    {
        return [
            [['code', 'iv', 'encryptedData', 'auth_code', 'openId', 'unionId', 'nickName', 'avatarUrl', 'mobile', 'password', 'session_key', 'wechat_info_key'], 'string']
        ]; // TODO: Change the autogenerated stub
    }

    public function bind()
    {
        WechatHelper::init($this->mall_id);
        $app = \Yii::$app->wechat->miniProgram;
        if (!$app) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '小程序配置错误');
        }
        try {
            $session = $app->getUtils()->codeToSession($this->code);
        } catch (\Exception $e) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '小程序配置错误');
        }
        if (isset($session['errcode']) && in_array($session['errcode'], [40029])) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, $session['errmsg']);
        }
        if (isset($session['errcode']) && in_array($session['errcode'], [40163])) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '登录失败，请重试');
        }
        $openid = $session['openid'];
        $unionid = isset($session['unionid']) ? $session['unionid'] : '';
        $user = UserHelper::getUser();
        if ($unionid) {
            $exist = User::find()->andWhere(['!=', 'id', UserHelper::getMyId()])->andWhere(['mall_id' => $this->mall_id, 'status' => User::STATUS_NORMAL, 'union_id' => $unionid])->exists();
            if ($exist) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, '微信信息已绑定其他账号');
            }
            $user->union_id = $unionid;
        }
        $exist = User::find()->andWhere(['!=', 'id', UserHelper::getMyId()])->andWhere(['mall_id' => $this->mall_id, 'status' => User::STATUS_NORMAL, 'mpwx_openid' => $openid])->exists();
        if ($exist) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '微信信息已绑定其他账号');
        }
        $user->mpwx_openid = $openid;
        $user->save();
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '绑定成功');
    }
}
