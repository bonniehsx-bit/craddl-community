namespace app\forms\api\user;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\helpers\UserHelper;
use app\models\BaseModel;
use app\models\Goods;
use app\services\goods\StandaloneGoodsGuard;
use app\models\GoodsFavorite;

class GoodsFavoriteListForm extends BaseModel
{

    public $page;

    public function rules()
    {
        return [
            [['page'], 'integer'],
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        $query = GoodsFavorite::find()->alias('f')->innerJoin(['g' => Goods::tableName()], 'g.id=f.goods_id');
        // 插件专属商品不进收藏列表
        if ($c = StandaloneGoodsGuard::listCondition('g.type')) {
            $query->andWhere($c);
        }
        $query->andWhere(['f.is_delete' => 0, 'g.is_delete' => 0]);
        $query->andWhere(['f.user_id' => UserHelper::getMyId()]);
        $list = $query->page($pagination, $this->limit, $this->page)->orderBy('f.id desc')->select('g.*')->asArray()->all();

        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['pagination' => $pagination, 'list' => $list]);
    }
}
