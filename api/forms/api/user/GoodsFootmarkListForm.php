namespace app\forms\api\user;


use app\services\goods\StandaloneGoodsGuard;
use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\helpers\UserHelper;
use app\models\BaseModel;
use app\models\Goods;
use app\models\GoodsFootmark;

class GoodsFootmarkListForm extends BaseModel
{
    public $page;
    public $limit = 10;

    public function rules()
    {
        return [
            [['limit', 'page'], 'integer'],
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $query = GoodsFootmark::find()->alias('f')
            ->where(['f.mall_id' => \Yii::$app->mall->id, 'f.is_delete' => 0, 'f.user_id' => UserHelper::getMyId()])
            ->innerJoin(['g' => Goods::tableName()], 'g.id=f.goods_id');
        $query->andWhere(['g.mall_id' => \Yii::$app->mall->id, 'g.is_delete' => 0]);
        // 插件专属商品不进足迹
        if ($c = StandaloneGoodsGuard::listCondition('g.type')) {
            $query->andWhere($c);
        }

        // 「最后浏览时间」。写入侧 GoodsFootMarkJob 按 user+goods 去重,重复浏览只更新
        // updated_at,所以取 updated_at;老数据可能没有,用 created_at 兜底。
        // ⚠ 两个都是 INT 时间戳,不能拿去和日期字符串比。
        $lastViewAt = 'GREATEST(IFNULL(f.updated_at, 0), IFNULL(f.created_at, 0))';
        // 兼容旧版本并发留下的重复行：按商品合并次数，列表只展示一次。
        $query->groupBy('g.id');

        $list = $query->page($pagionation, $this->limit, $this->page)
            // 除了商品本身,必须把浏览时间一起吐给前端 —— 足迹页要靠它分组,
            // 只 select('g.*') 的话前端拿到的和普通商品列表没有任何区别。
            ->select(['g.id', 'g.name', 'g.cover_pic', 'g.price', 'g.origin_price', 'g.sales', 'g.virtual_sales', 'g.unit', 'g.is_negotiable',
                'view_count' => new \yii\db\Expression('SUM(f.view_count)'),
                'footmark_time' => new \yii\db\Expression('MAX(' . $lastViewAt . ')')])
            // 原来完全没有 ORDER BY,page() 也不加,顺序由 InnoDB 决定 ——
            // 实测最近浏览的商品根本排不进第一页。足迹必须按时间倒序。
            // id 作次级排序,保证同一秒内的多条顺序稳定,翻页不会重复或漏项。
            ->orderBy(new \yii\db\Expression('MAX(' . $lastViewAt . ') DESC, MAX(f.id) DESC'))
            ->asArray()->all();
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagionation]);
    }
}
