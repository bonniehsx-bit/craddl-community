namespace app\forms\api\pay;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\CommonPayOrder;

class AppPayDataForm extends BaseModel
{
    public $order_no;
    public $pay_order_id;

    public function rules()
    {
        return [
            [['pay_order_id'], 'required'],
            [['order_no'], 'string'],
        ]; // TODO: Change the autogenerated stub
    }

    public function search()
    {

        $order = CommonPayOrder::findOne(['id' => $this->pay_order_id, 'is_pay' => 0]);
        if (!$order) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '订单不存在或已支付');
        }
        $data['order_no'] = $order->order_no;
        $data['pay_order_id'] = $order->id;
        $data['pay_price'] = $order->pay_price;
        if ($order->pay_price <= 0) {
            if (!$order->pay()) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '支付失败', ['error' => $order->getErrors()]);
            }
            return $this->apiResponse(ApiCode::CODE_FAIL, '支付成功', ['is_pay' => 1]);
        }
        if ($order->is_pay) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '订单已经支付');
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['order_info' => $data]);
    }

}