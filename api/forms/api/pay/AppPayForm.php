namespace app\forms\api\pay;


use app\core\ApiCode;
use app\helpers\ConstantHelper;
use app\helpers\ResponseHelper;
use app\helpers\WechatHelper;
use app\models\BaseModel;
use app\models\CommonPayOrder;

class AppPayForm extends BaseModel
{
    public $order_no; //union_order_id
    public $code;
    public $is_wechat; //表示是H5代付

    public $openid;

    public function rules()
    {
        return [
            [['is_wechat'], 'integer'],
            [['order_no', 'code', 'openid'], 'string'],
            [['order_no'], 'required']
        ]; // TODO: Change the autogenerated stub
    }


    public function pay()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $order = CommonPayOrder::findOne(['order_no' => $this->order_no, 'is_pay' => 0]);
        if (!$order) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '订单不存在或已支付');
        }
        if (!$this->is_wechat) {
            \Yii::$app->platform = ConstantHelper::PLATFORM_MPWX;
            WechatHelper::init($order->mall_id);
            $app = \Yii::$app->wechat->miniProgram;
            if (!$app) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '小程序配置失败');
            }
            try {
                $session = $app->getUtils()->codeToSession($this->code);
            } catch (\Exception $e) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '小程序配置错误');
            }
            $openId = $session['openid']; //用户的openID
            if (isset($session['errcode']) && in_array($session['errcode'], [40029])) {
                return ResponseHelper::send(ApiCode::CODE_FAIL, $session['errmsg']);
            }
            $order->pay_openid = $openId;
        } else {
            \Yii::$app->platform = ConstantHelper::PLATFORM_WECHAT;
            $order->pay_openid = $this->openid;
        }
        if (!$order->pay_openid) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '获取openid失败!');
        }

        $order->save();

        $res['data']['is_pay'] = 0;
        return $res;
    }
}
