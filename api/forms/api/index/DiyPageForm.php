namespace app\forms\api\index;


use app\core\ApiCode;
use app\models\BaseModel;
use app\models\DiyPage;
use yii\helpers\Json;

class DiyPageForm extends BaseModel
{

    public $id;

    public function rules()
    {
        return [
            [['id'], 'integer'],

        ]; // TODO: Change the autogenerated stub
    }

    public function getPageData()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $page = DiyPage::findOne(['is_delete' => 0, 'id' => $this->id, 'mall_id' => \Yii::$app->mall->id]);
        if (!$page) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '页面找不到');
        }
        $name = $page->name;
        $data = Json::decode($page->data);

        // 商品组 / 选项卡商品 / 分类宫格的实时数据(会员价、商品权限、分类商品数),统一见 DiyHydrateHelper
        \app\helpers\DiyHydrateHelper::hydrate($data, (int)\Yii::$app->mall->id);
        unset($item);
        // 页面背景色(后台「页面设置」里配,存在 page_params.bg_color;没配为空串,手机端保持默认底色)
        $pageParams = $page->page_params ? Json::decode($page->page_params) : [];
        $bgColor = is_array($pageParams) && !empty($pageParams['bg_color']) ? (string)$pageParams['bg_color'] : '';
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['page_data' => $data, 'title_color' => $page->title_color, 'text_color' => $page->text_color, 'name' => $name, 'bg_color' => $bgColor]);
    }
}
