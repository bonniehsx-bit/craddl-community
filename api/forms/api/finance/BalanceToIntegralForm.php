namespace app\forms\api\finance;


use app\core\ApiCode;
use app\helpers\BalanceLogHelper;
use app\helpers\OptionHelper;
use app\helpers\ResponseHelper;
use app\helpers\UserHelper;
use app\models\BaseModel;

/**
 * C 端 - 余额兑积分(核心旧版,读 cash_setting)
 *
 * @deprecated 已有功能相同的插件版 app\plugins\withdraw\forms\api\transfer\BalanceToIntegralForm
 *   (校验更严:实时读库 + bccomp 精度比较,配置读 withdraw_setting.finance)。
 *   本类因老前端仍挂在 FinanceController/BalanceController 路由上而保留,新端一律走插件版;
 *   两份都已收口到核心积分网关 IntegralService::grant('balance_to_integral')。
 */
class BalanceToIntegralForm extends BaseModel
{

    public $balance;

    public function rules()
    {
        return [
            [['balance'], 'number']
        ]; // TODO: Change the autogenerated stub
    }


    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $setting = OptionHelper::get('cash_setting', $this->mall_id);
        if (!$setting) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '未配置余额转积分');
        }
        if (!isset($setting['is_balance_to_integral']) || !isset($setting['one_rmb_to_integral'])) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '未配置余额转积分');
        }
        $total_integral = bcmul($this->balance, floatval($setting['one_rmb_to_integral']));
        if ($total_integral > 0) {
            $userId = UserHelper::getMyId();
            // 🐛 补事务:原先「扣余额」与「加积分」各自独立执行,扣款成功后加分抛异常
            // 会导致用户余额没了、积分没到(资损)。两步必须原子。
            $tx = \Yii::$app->db->beginTransaction();
            try {
                BalanceLogHelper::sub($userId, $this->balance, '兑换' . $total_integral . '积分');
                // 走核心积分网关,业务类型 balance_to_integral
                (new \app\services\IntegralService())->grant($userId, $total_integral, 'balance_to_integral', [
                    'title'   => '余额兑换积分',
                    'content' => '余额兑换积分,使用余额:' . $this->balance,
                ]);
                $tx->commit();
            } catch (\Throwable $e) {
                $tx->rollBack();
                return ResponseHelper::send(ApiCode::CODE_FAIL, $e->getMessage());
            }
            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '兑换成功');
        }
        return ResponseHelper::send(ApiCode::CODE_FAIL, '兑换失败');
    }
}