namespace app\forms\api\cart;


use app\core\ApiCode;

use app\models\Attr;
use app\models\BaseModel;
use app\models\Cart;
use app\models\Goods;


class CartListForm extends BaseModel
{

    public $page;
    public $limit;
    public $status;
    public $keyword;
    public $mch_id;


    public function rules()
    {
        return [
            [['page', 'limit', 'mch_id'], 'integer'],
            [['keyword'], 'string'],
            [['limit'], 'default', 'value' => 10]
        ]; // TODO: Change the autogenerated stub
    }


    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $query = Cart::find()
            ->alias('c')
            ->leftJoin(['g' => Goods::tableName()], 'g.id=c.goods_id')
            ->where(['c.mall_id' => \Yii::$app->mall->id, 'c.is_delete' => 0, 'c.user_id' => \Yii::$app->user->identity->id]);
        if ($this->mch_id) {
            $query->andWhere(['g.mch_id' => $this->mch_id]);
        }
        if ($this->keyword) {
            $query->andWhere(['like', 'g.name', $this->keyword]);
        }
        $list = $query->page($pagination, $this->limit, $this->page)->orderBy('id DESC')->select('c.*,g.cover_pic,g.name,g.price,g.is_attr,g.mch_id')->asArray()->all();
        $newArr = [];
        foreach ($list as $item) {
            $item['is_valid'] = 1;
            $item['selected'] = false;
            $item['checked'] = false;
            $item['num'] = intval($item['num']);
            $item['attr_name'] = '默认';
            if ($item['is_attr']) {
                $attr = Attr::findOne(['is_delete' => 0, 'goods_id' => $item['goods_id'], 'id' => $item['goods_attr_id']]);
                if ($attr) {
                    $item['attr_name'] = $attr->attr_name;
                    $item['price'] = $attr->price;
                } else {
                    $item['is_valid'] = 0;
                }
            }

            if ($item['is_valid']) {
                $newArr[] = $item;
            }
        }

        // 补会员价/插件代理价:与下单实付同口径(OrderPricingService 也是
        // 「base = 规格价或商品价 → applyLevelDiscountToPrice」),否则购物车显示原价、
        // 下单却按会员价扣,前后对不上。
        // ⚠ 必须放在上面规格价赋值之后:有规格时 base 应是 attr->price 而非 goods.price。
        // ⚠ idKey 传 goods_id:本列表 select 了 c.*,其 id 是 cart.id,用默认 'id' 会张冠李戴。
        \app\helpers\GoodsMemberPriceHelper::applyToArrayList(
            $newArr,
            \app\helpers\GoodsMemberPriceHelper::currentLevelId(),
            'price',
            'goods_id'
        );

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $newArr, 'pagination' => $pagination]);
    }
}
