namespace app\forms\api\cart;


use app\core\ApiCode;
use app\helpers\SerializeHelper;
use app\helpers\UserHelper;
use app\models\BaseModel;
use app\models\Cart;
use yii\helpers\Json;

class CartEditForm extends BaseModel
{
    public $edit_data;

    public $is_delete;
    public $id;
    public $num;


    public function rules()
    {
        return [
            [['is_delete', 'id', 'num'], 'integer'],
            [['edit_data'], 'safe']
        ]; // TODO: Change the autogenerated stub
    }

    public function save()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // 先校验整批数量，再写入，保留当前用户归属校验与删除分支。
        try {
            if ($this->id) {
                \app\services\order\OrderInputGuard::assertQuantity($this->num);
            } else {
                $this->edit_data = is_string($this->edit_data) ? Json::decode($this->edit_data) : $this->edit_data;
                if (!is_array($this->edit_data)) {
                    throw new \InvalidArgumentException('数据格式错误');
                }
                foreach ($this->edit_data as $row) {
                    if (!is_array($row)) {
                        throw new \InvalidArgumentException('购物车数据格式错误');
                    }
                    if (!$this->is_delete) {
                        \app\services\order\OrderInputGuard::assertQuantity($row['num'] ?? null);
                    }
                }
            }
        } catch (\InvalidArgumentException $e) {
            return $this->apiResponse(ApiCode::CODE_FAIL, $e->getMessage());
        }
        if ($this->id) {
            //来自编辑
            // ⚠ 必须限定当前用户:只按 id 改的话,任何登录用户传别人的购物车 id 就能改数量
            $count = Cart::updateAll(['num' => (int)$this->num], [
                'id' => $this->id,
                'user_id' => UserHelper::getMyId(),
                'is_delete' => 0,
            ]);
            if (!$count && !Cart::find()->where(['id' => $this->id, 'user_id' => UserHelper::getMyId(), 'is_delete' => 0])->exists()) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '商品不存在');
            }
            return $this->apiResponse(ApiCode::CODE_SUCCESS, '编辑完成');
        }
        foreach ($this->edit_data as $row) {
            $cart = Cart::findOne(['user_id' => UserHelper::getMyId(), 'id' => $row['id'], 'is_delete' => 0]);
            if (!$cart) {
                return $this->apiResponse(ApiCode::CODE_FAIL, '商品不存在');
            }
            if (!$this->is_delete) {
                $cart->num = (int)$row['num'];
            } else {
                $cart->is_delete = 1;
            }

            $cart->save();
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '编辑完成');
    }
}
