namespace app\forms\api\wechat;


use app\core\ApiCode;
use app\helpers\OptionHelper;
use app\helpers\ServerHelper;
use app\helpers\SerializeHelper;
use app\models\BaseModel;
use yii\helpers\Json;

class WechatForm extends BaseModel
{

    public $url;

    public function rules()
    {
        return [
            [['url'], 'string']

        ]; // TODO: Change the autogenerated stub
    }

    /**
     * 生成公众号 JS-SDK 签名配置。
     *
     * ⚠ 失败时必须**如实返回失败**,不能像原实现那样吞掉异常再回 code=0 + 空 jssdk:
     * 前端见 code==0 就照常 `wx.config({appId: undefined, signature: undefined, ...})`,
     * 必然 config 失败 → 只看到一句笼统的「JS-SDK 配置失败」,真实原因(没配公众号 /
     * 域名没加白 / ticket 拉不到)全丢了,而且前端还会把这个坏配置缓存 50 分钟。
     * 多商户场景尤其容易踩:子商城常常压根没配公众号。
     */
    public function getJssdk()
    {
        $mallId = (int) \Yii::$app->mall->id;
        $mall_setting = OptionHelper::get('mall_setting', $mallId);
        $default_share = $this->buildDefaultShare($mall_setting);

        // 前置:没配公众号就别往下走了,报错更直白。
        // ⚠ 字段名是 appid + **secret**(不是 appsecret)—— 以后台 forms/mall/platform/WechatForm
        // 保存的结构、以及 WechatHelper::init() 读取的键为准。写错会把「已配置」误判成「未配置」。
        $platform = OptionHelper::get('platform_wechat', $mallId);
        if (empty($platform['appid']) || empty($platform['secret'])) {
            \Yii::warning("[WechatJssdk] mall={$mallId} 未配置公众号 appid/appsecret,JS-SDK 不可用", __METHOD__);
            return $this->apiResponse(ApiCode::CODE_FAIL, '本商城未配置微信公众号,无法使用扫码/分享等微信能力', [
                'jssdk' => [], 'default_share' => $default_share, 'reason' => 'no_official_account',
            ]);
        }

        try {
            $utils = \Yii::$app->wechat->app->getUtils();
            $jssdk = $utils->buildJsSdkConfig(
                $this->url,
                ['updateAppMessageShareData', 'updateTimelineShareData', 'chooseWXPay', 'scanQRCode'],
                [],   // openTagList
                false // debug —— 原代码在这后面多传了一个 false,SDK 只收 4 个参数,多的被静默忽略
            );
        } catch (\Throwable $e) {
            // 常见原因:appid/secret 错、jsapi_ticket 拉取失败(IP 白名单)、
            // 当前域名未加入公众号后台「设置-公众号设置-功能设置-JS接口安全域名」
            \Yii::error('[WechatJssdk] mall=' . $mallId . ' 签名生成失败: ' . $e->getMessage() . ' | url=' . $this->url, __METHOD__);
            return $this->apiResponse(ApiCode::CODE_FAIL, '微信 JS-SDK 签名生成失败,请检查公众号配置与 JS 接口安全域名', [
                'jssdk' => [], 'default_share' => $default_share, 'reason' => 'sign_failed',
            ]);
        }

        // 兜底:SDK 没抛异常但没给出 appId/signature 的情况也当失败,
        // 否则前端拿着半截配置去 config,报出来的错一样没法定位
        if (empty($jssdk['appId']) || empty($jssdk['signature'])) {
            \Yii::error('[WechatJssdk] mall=' . $mallId . ' 返回的配置缺 appId/signature | url=' . $this->url, __METHOD__);
            return $this->apiResponse(ApiCode::CODE_FAIL, '微信 JS-SDK 配置不完整,请检查公众号配置', [
                'jssdk' => [], 'default_share' => $default_share, 'reason' => 'incomplete',
            ]);
        }

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['jssdk' => $jssdk, 'default_share' => $default_share]);
    }

    /**
     * 组装 H5 分享卡片的默认信息(标题 / 描述 / 图)。
     *
     * 三项各走一条兜底链,专用配置优先、商城基础信息垫底:
     *   标题  share_title → 商城名称
     *   描述  share_desc  → 商城简介
     *   图    share_pic   → 商城 LOGO
     * 后台原先就有「全局分享标题」这个配置项,但分享代码一直读的是商城名称,配了不生效;
     * 描述和分享图则干脆没有专用配置,只能跟着商城简介/LOGO 走 —— 商城简介多数没填,
     * 于是分享卡片长期只有一行标题,看着就很空。
     *
     * 图必须是**绝对 URL**:微信抓不到相对路径,结果就是卡片没图。上传组件存的可能是
     * /uploads/xxx.png 这种相对路径,这里统一补全站点前缀。
     */
    private function buildDefaultShare(array $mallSetting): array
    {
        $pick = function (...$candidates) {
            foreach ($candidates as $v) {
                $v = trim((string) $v);
                if ($v !== '') {
                    return $v;
                }
            }
            return '';
        };

        return [
            // 键名沿用 logo/name/detail —— 前端已按这三个键读,换名会让旧版小程序/H5 拿不到值
            'name'   => $pick($mallSetting['share_title'] ?? '', $mallSetting['name'] ?? ''),
            'detail' => $pick($mallSetting['share_desc'] ?? '', $mallSetting['detail'] ?? ''),
            'logo'   => $this->absoluteUrl($pick($mallSetting['share_pic'] ?? '', $mallSetting['logo'] ?? '')),
        ];
    }

    /**
     * 相对路径补成绝对 URL;已经是 http(s):// 或协议相对(//)的原样返回。
     */
    private function absoluteUrl(string $url): string
    {
        $url = trim($url);
        if ($url === '' || preg_match('#^(https?:)?//#i', $url)) {
            return $url;
        }
        // 走项目现成的 ServerHelper::getHost():APP_URL → 请求域名 → option.domain 三级兜底,
        // 比自己读 request->hostInfo 稳(控制台/队列里没有 request)。
        // ⚠ 别用 Yii::$app->params['host'] —— 那是**数据库主机**,不是站点域名。
        $host = rtrim((string) ServerHelper::getHost(), '/');
        if ($host === '') {
            return $url;   // 拿不到站点地址就别瞎拼,原样返回总好过拼出个错的
        }
        return $host . '/' . ltrim($url, '/');
    }

}
