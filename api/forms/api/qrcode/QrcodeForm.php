namespace app\forms\api\qrcode;


use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use Endroid\QrCode\QrCode;

class QrcodeForm extends BaseModel
{

    public $path;
    public $params;
    public $type; //0普通二维码  1 小程序码

    public $content;
    public function rules()
    {
        return [
            [['path', 'params', 'content'], 'string'],
            [['type'], 'integer']
        ]; // TODO: Change the autogenerated stub
    }

    public function generate()
    {

        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        if ($this->type) {
        }

        $mall = \Yii::$app->mall;
        $user_id = \Yii::$app->user->identity->id;
        $qrCode = new QrCode("{$this->path}&mall_id={$mall->id}&pid={$user_id}");
        $qrCode->setSize(200);
        $qrCode->setMargin(10);
        $baseWebPath = \Yii::$app->basePath . '/web';
        $baseWebUrl = \Yii::$app->request->hostInfo . \Yii::$app->request->baseUrl;
        $saveName = md5($this->params) . '.png';
        $savePath = '/qrcode/' . \Yii::$app->user->identity->id . '/';
        $saveFile = $baseWebPath . $savePath . $saveName;
        if (!is_dir($baseWebPath . $savePath)) {
            if (!make_dir($baseWebPath . $savePath)) {
                throw new \Exception('上传失败，创建文件夹失败`'
                    . $baseWebPath . $savePath
                    . '`，请检查目录写入权限。');
            }
        }
        $qrCode->writeFile($saveFile);
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['url' => $baseWebUrl . $savePath . $saveName]);
    }

    /**
     * [核心实现] 生成二维码的 Base64 (Data URI) 字符串
     */
    public function generateBase64()
    {
        // 1. 验证 content 字段是必须的
        if (empty($this->content)) {
            return ResponseHelper::send(ApiCode::CODE_FAIL, '参数 content 不能为空');
        }

        try {
            // 2. 实例化 QrCode 对象
            $qrCode = new QrCode($this->content);
            $qrCode->setSize(300); // 可以根据需要调整尺寸
            $qrCode->setMargin(10);

            // 3. [关键] 调用 writeDataUri() 方法
            $dataUri = $qrCode->writeDataUri();

            // 4. 返回 Base64 字符串
            return ResponseHelper::send(ApiCode::CODE_SUCCESS, '生成成功', ['base64' => $dataUri]);
        } catch (\Exception $e) {
            \Yii::error("生成二维码Base64失败: " . $e->getMessage());
            return ResponseHelper::send(ApiCode::CODE_FAIL, '二维码生成失败，请稍后重试');
        }
    }
}
