namespace app\forms\api\mall;


use app\core\ApiCode;
use app\models\BaseModel;
use app\models\DiyPage;
use app\models\FreightTpl;

class FreightListForm extends BaseModel
{
    public $limit;
    public $page;
    public $enabled;
    public $is_all;

    public function rules()
    {
        return [
            [['page', 'limit', 'enabled', 'is_all'], 'integer'],
            [['limit'], 'default', 'value' => 10]
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $query = FreightTpl::find()->where(['mall_id' => \Yii::$app->mall->id, 'is_delete' => 0]);
        $query->andWhere(['enabled' => 1]);
        if ($this->is_all) {
            $list = $query->orderBy('id DESC')->asArray()->all();
        } else {
            $list = $query->page($pagination, $this->limit, $this->page)->orderBy('id DESC')->asArray()->all();
        }

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagination]);
    }
}
