namespace app\forms\api\mall;

use app\services\goods\StandaloneGoodsGuard;
use app\core\ApiCode;
use app\helpers\ResponseHelper;
use app\models\BaseModel;
use app\models\Cat;
use app\models\Goods;
use app\models\GoodsCat;
use app\models\GoodsInfo;
use app\models\TabGoods;
use yii\helpers\Json;

class TabGoodsForm extends BaseModel
{

    public $id;

    public function rules()
    {
        return [
            [['id'], 'required'],
            [['id'], 'integer'],
        ];
        // TODO: Change the autogenerated stub
    }

    public function search()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        $model = TabGoods::findOne(['is_delete' => 0, 'id' => $this->id, 'mall_id' => $this->mall_id]);
        if (!$model) {
            return [
                'code' => 1,
                'msg' => '标签组不存在!'
            ];
        }
        $list = Json::decode($model->list);

        foreach ($list as &$item) {
            $type = $item['type'];
            $cat_id = $item['cat_id'];
            $goods_list = $item['list'];
            if ($type == 0) {
                $query = Goods::find()
                    ->where(['mall_id' => $this->mall_id, 'is_delete' => 0, 'status' => 1]);
                if ($cat_id) {
                    $cids = [$cat_id];
                    $cat = Cat::findOne(['id' => $cat_id, 'is_delete' => 0]);
                    if ($cat->type == 0) {
                        $cids1 = Cat::find()->where(['is_delete' => 0])->andWhere(['parent_id' => $cat_id])->select('id')->column();
                        if ($cids1) {
                            $cids2 = Cat::find()->where(['is_delete' => 0])->andWhere(['parent_id' => $cids1])->select('id')->column();
                            if ($cids2) {
                                $cids = array_merge($cids, $cids1, $cids2);
                            } else {
                                $cids = array_merge($cids, $cids1);
                            }
                        }
                    }
                    if ($cat->type == 1) {
                        $cids1 = Cat::find()->where(['is_delete' => 0])->andWhere(['parent_id' => $cat_id])->select('id')->column();
                        $cids = array_merge($cids, $cids1);
                    }
                    $gids = GoodsCat::find()->where(['cat_id' => $cids])->select('goods_id')->column();
                    $query->andWhere(['id' => $gids]);
                    $goods_list = $query->orderBy('sort ASC,id DESC')->asArray()->all();
                    //商品权限
                }
            }
            if (!\Yii::$app->user->isGuest) {  //商品浏览权限
                $level = \Yii::$app->user->identity->level_id;
            } else {
                $level = -1;
            }
            $newList = [];
            // 权限过滤:批量取 GoodsInfo(替换原先每商品 Goods::findOne + GoodsInfo::findOne 的双重 N+1)
            $tabGids = array_column(array_filter($goods_list, 'is_array'), 'id');
            $infoMap = $tabGids ? GoodsInfo::find()->where(['goods_id' => $tabGids])->indexBy('goods_id')->asArray()->all() : [];
            // 插件专属商品(来信、充值……)不进商城:按分类取的和后台手选的都要剔除(手选的存的是商品快照,没有 type)
            $hiddenIds = [];
            if ($tabGids && ($c = StandaloneGoodsGuard::listCondition('type'))) {
                $hiddenIds = array_flip(Goods::find()->select('id')->where(['id' => $tabGids])->andWhere(['not', $c])->column());
            }
            foreach ($goods_list as $goods) {
                if (!is_array($goods) || !isset($goods['id'])) {
                    $newList[] = $goods;
                    continue;
                }
                if (isset($hiddenIds[$goods['id']])) {
                    continue;
                }
                $goodsInfo = $infoMap[$goods['id']] ?? null;
                if (!$goodsInfo || empty($goodsInfo['permission'])) {
                    $newList[] = $goods;
                } else {
                    $permission = Json::decode($goodsInfo['permission']);
                    if ($permission) {
                        if (!empty($permission['explode_is_level'])) {
                            if (in_array($level, $permission['explode_level_ids'] ?? [])) {
                                $newList[] = $goods;
                            }
                        } else {
                            $newList[] = $goods;
                        }
                    }
                }
            }
            // 会员价/插件代理价:批量套用(替换原先逐商品 findOne + getLevelPrice 的 N+1;$level 为 level_id,游客-1→0)
            \app\helpers\GoodsMemberPriceHelper::applyToArrayList($newList, $level > 0 ? $level : 0);
            $item['list'] = $newList;
        }
        unset($item);
        return ResponseHelper::send(ApiCode::CODE_SUCCESS, '', ['list' => $list]);

    }
}