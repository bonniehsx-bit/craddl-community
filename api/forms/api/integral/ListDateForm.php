namespace app\forms\api\integral;


use app\core\ApiCode;
use app\helpers\UserHelper;
use app\models\BalanceLog;
use app\models\BaseModel;
use app\models\IntegralLog;

class ListDateForm extends BaseModel
{

    public $status;
    public $page;
    public $limit;
    public $type;

    public function rules()
    {
        return [
            [['type'], 'integer'],
            [['page', 'limit', 'status'], 'integer'],
            [['limit'], 'default', 'value' => 20]
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        $query = IntegralLog::find()->where(['user_id' => \Yii::$app->user->identity->id, 'is_delete' => 0]);
        if ($this->type == 0) {
            $query->andWhere(['type' => $this->type]);
        }
        if ($this->type == 1) {
            $query->andWhere(['type' => $this->type]);
        }
        $list = $query
            ->page($pagination, $this->limit, $this->page)
            ->orderBy('id DESC')
            ->groupBy('month_at')
            ->select('month_at')
            ->orderBy('id desc')
            ->asArray()
            ->all();
        foreach ($list as &$item) {
            $query = IntegralLog::find()
                ->andWhere(['user_id' => UserHelper::getMyId()])
                ->andWhere(['month_at' => $item['month_at']]);
            if ($this->type == 0) {
                $query->andWhere(['type' => $this->type]);
            }
            if ($this->type == 1) {
                $query->andWhere(['type' => $this->type]);
            }
            $item['list'] = $query->orderBy('id desc')
                ->asArray()
                ->all();
            $income = IntegralLog::find()
                ->andWhere(['user_id' => UserHelper::getMyId()])
                ->andWhere(['month_at' => $item['month_at'], 'type' => 1])->sum('integral');
            $expense = IntegralLog::find()
                ->andWhere(['user_id' => UserHelper::getMyId()])
                ->andWhere(['month_at' => $item['month_at'], 'type' => 0])
                ->sum('integral');
            $item['income'] = (float)$income;
            $item['expense'] = (float)$expense;
            $item['active'] = 0;
            $item['is_load_more'] = false;
        }
        unset($item);
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagination]);
    }
}
