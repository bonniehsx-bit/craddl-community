namespace app\forms\api\goods;


use app\core\ApiCode;
use app\helpers\StringHelper;
use app\models\BaseModel;
use app\models\GoodsComment;
use app\models\User;
use yii\helpers\Json;

class GoodsCommentListForm extends BaseModel
{

    public $page;
    public $goods_id;

    public $limit;

    public function rules()
    {
        return [
            [['goods_id'], 'required'],
            [['page', 'limit', 'goods_id'], 'integer'],
            [['limit'], 'default', 'value' => 10]
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        $total = GoodsComment::find()->where(['goods_id' => $this->goods_id, 'is_delete' => 0])->count();
        $sum = GoodsComment::find()->where(['goods_id' => $this->goods_id, 'is_delete' => 0])->sum('grade_level');

        $total = $total ? $total : 1;
        $sum = intval($sum / $total);

        $list = GoodsComment::find()->alias('c')
            ->leftJoin(['u' => User::tableName()], 'u.id=c.user_id')
            ->where(['c.goods_id' => $this->goods_id, 'c.is_delete' => 0, 'is_second' => 0])
            ->select('u.nickname,u.avatar_url,c.*');

        $pagination = null;
        $list = $list->page($pagination, $this->limit, $this->page)
            ->orderBy('c.id DESC')
            ->asArray()
            ->all();


        foreach ($list as &$item) {
            $item['nickname'] = StringHelper::replaceMiddleKeepEnds($item['nickname']);
            // 解码图片列表
            try {
                if (!empty($item['pic_list'])) {
                    $decoded = Json::decode($item['pic_list']);
                    if (is_string($decoded)) {
                        $secondDecode = json_decode($decoded, true);
                        if (json_last_error() === JSON_ERROR_NONE && is_array($secondDecode)) {
                            $decoded = $secondDecode;
                        }
                    }
                    $item['pic_list'] = is_array($decoded) ? $decoded : [];
                } else {
                    $item['pic_list'] = [];
                }
            } catch (\Exception $e) {
                $item['pic_list'] = [];
            }

            $second = GoodsComment::find()
                ->alias('c')
                ->leftJoin(['u' => User::tableName()], 'u.id=c.user_id')
                ->where(['c.goods_id' => $this->goods_id, 'c.is_delete' => 0, 'c.user_id' => $item['user_id'], 'c.order_id' => $item['order_id']])
                ->andWhere(['c.is_second' => 1])
                ->select('u.nickname,u.avatar_url,c.*')
                ->asArray()
                ->one();

            if ($second) {
                $second['nickname'] = StringHelper::replaceMiddleKeepEnds($second['nickname']);
                // 解码追评图片
                try {
                    if (!empty($second['pic_list'])) {
                        $decoded = Json::decode($second['pic_list']);
                        if (is_string($decoded)) {
                            $secondDecode = json_decode($decoded, true);
                            if (json_last_error() === JSON_ERROR_NONE && is_array($secondDecode)) {
                                $decoded = $secondDecode;
                            }
                        }
                        $second['pic_list'] = is_array($decoded) ? $decoded : [];
                    } else {
                        $second['pic_list'] = [];
                    }
                } catch (\Exception $e) {
                    $second['pic_list'] = [];
                }
            }
            $item['second'] = $second;
        }
        unset($item);

        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagination, 'total' => $total, 'sum' => $sum]);
    }
}
