namespace app\forms\common\express;

use app\core\ApiCode;
use app\helpers\CacheHelper;
use app\helpers\ExpressHelper;
use app\helpers\ResponseHelper;
use app\helpers\SerializeHelper;
use app\models\ExpressSetting;
use app\services\KdniaoService;
use Finecho\Logistics\Logistics;
use Yii;
use yii\helpers\Json;
use yii\httpclient\Client;

class ExpressQueryForm extends \app\models\BaseModel
{
    public $express_no;
    public $express_name;
    public $express_code;
    public $express_key;
    public $mall_id;
    public $mobile;


    public function rules()
    {
        return [
            [['express_no'], 'required'],
            [['mall_id'], 'integer'],
            [['mobile'], 'string'],
            [['express_name', 'express_no', 'express_code', 'express_key'], 'string'],
        ]; // TODO: Change the autogenerated stub
    }


    public function search()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }

        // --- [核心优化] 引入缓存 ---
        $cacheKey = "express_query_{$this->express_code}_{$this->express_no}";

        $result = CacheHelper::get($cacheKey);

        if ($result) {
            Yii::warning("命中快递查询缓存: {$cacheKey}");
            return $this->apiResponse(ApiCode::CODE_SUCCESS, $result['msg'], ['list' => $result['list']]);
        }

        Yii::warning("未命中缓存，开始实时查询快递: {$cacheKey}");

        try {
            // --- [核心优化] 调用服务层 ---
            $kdniaoService = new KdniaoService($this->mall_id);
            $customerName = $this->mobile ? substr($this->mobile, -4) : '';
            $result = $kdniaoService->query($this->express_no, $customerName);
            // 查询成功后，将结果缓存30分钟

            CacheHelper::set($cacheKey, $result, 60);
            return $this->apiResponse(ApiCode::CODE_SUCCESS, $result['msg'], ['list' => $result['list']]);
        } catch (\Exception $e) {
            // 即使API查询失败，也返回一个友好的提示，而不是程序崩溃
            return $this->apiResponse(ApiCode::CODE_FAIL, $e->getMessage());
        }
    }
}
