namespace app\forms\common\file;


use app\core\ApiCode;
use app\helpers\UserHelper;
use app\models\BaseModel;
use app\models\FileGroup;

class FileGroupDeleteForm extends BaseModel
{


    public $id;

    public function rules()
    {
        return [
            [['id'], 'required'],
            [['id'], 'integer']

        ]; // TODO: Change the autogenerated stub
    }

    public function delete()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // 原来只按 id 删,任一商城都能删掉别家的分组。
        //
        // 归属条件对齐 FileGroupEditForm 的**创建**口径 ——「建的时候写了什么,删就按什么找」。
        // 不参照 FileGroupListForm:它在 $user->mch_id == 0 时那个分支不成立、退化成完全不过滤,
        // 照抄等于把它的缺陷也抄过来。
        //
        // 也不能一刀切写死当前商城:文件组是三态归属(站点级 admin_id、商城级 mall_id、
        // 商户级 mch_id),且无 mall 上下文时创建的记录 mall_id 为 0,一刀切会让这些
        // 变成「列表里看得见、点删除却报不存在」。
        $condition = ['id' => $this->id, 'is_delete' => 0];
        $user = UserHelper::getUser();
        if ($user) {
            // 与创建时 `$group->mall_id = $user->mall_id; $group->mch_id = $user->mch_id ?? 0;` 对称。
            // mall_id 不能省:普通用户 mch_id 为 0,只按 mch_id 过滤等于「任意商城的平台级分组」都能删。
            $condition['mall_id'] = $user->mall_id;
            $condition['mch_id'] = $user->mch_id ?? 0;
        } else {
            $condition['mall_id'] = \Yii::$app->mall ? \Yii::$app->mall->id : 0;
        }
        $group = FileGroup::findOne($condition);
        if (!$group) {
            return $this->apiResponse(ApiCode::CODE_FAIL, '文件组不存在或已被删除');
        }
        $group->is_delete = 1;
        if (!$group->save()) {
            return $this->responseErrorMsg($group);
        }
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '删除成功');
    }
}
