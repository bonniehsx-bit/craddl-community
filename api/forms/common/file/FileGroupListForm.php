namespace app\forms\common\file;

use app\core\ApiCode;
use app\helpers\UserHelper;
use app\models\BaseModel;
use app\models\FileGroup;
use app\models\User;

class FileGroupListForm extends BaseModel
{


    public $keyword;
    public $is_site;

    public function rules()
    {
        return [
            [['keyword'], 'string'],
            [['is_site'], 'integer']
        ]; // TODO: Change the autogenerated stub
    }

    public function getList()
    {
        $query = FileGroup::find()->where(['is_delete' => 0]);
        $user = UserHelper::getUser();
        if (!$user) {
            if ($this->is_site) {
                $query = FileGroup::find()->andWhere(['admin_id' => \Yii::$app->admin->identity->id, 'is_site' => $this->is_site, 'is_delete' => 0]);
            } else {
                if (\Yii::$app->mall) {
                    $query = FileGroup::find()->andWhere(['mall_id' => \Yii::$app->mall->id, 'mch_id' => 0, 'is_site' => 0, 'is_delete' => 0]);
                } else {
                    $query = FileGroup::find()->andWhere(['mall_id' => 0, 'is_site' => 0, 'is_delete' => 0]);
                }
            }
        } else {
            if ($user->mch_id) {
                $query = FileGroup::find()->andWhere(['mch_id' => $user->mch_id, 'is_delete' => 0]);
            }
        }
        if ($this->keyword) {
            $query->andWhere(['like', 'name', $this->keyword]);
        }
        $list = $query->asArray()->all();
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list]);
    }
}
