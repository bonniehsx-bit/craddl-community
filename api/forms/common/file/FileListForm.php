namespace app\forms\common\file;


use app\core\ApiCode;
use app\helpers\UserHelper;
use app\models\BaseModel;
use app\models\File;

class FileListForm extends BaseModel
{

    public $type;
    public $page;
    public $limit;
    public $keyword;
    public $group_id;
    public $is_site;

    public function rules()
    {
        return [
            [['type', 'keyword'], 'string'],
            [['limit', 'page', 'group_id', 'is_site'], 'integer'],
            [['limit'], 'default', 'value' => 14],
            [['type'], 'default', 'value' => 'image']
        ]; // TODO: Change the autogenerated stub
    }


    public function getList()
    {
        if (!$this->validate()) {
            return $this->responseErrorInfo();
        }
        // 选择器可选每页 15/30/50/100,这里封顶 100,防止一次拉全表
        $this->limit = max(1, min(100, (int) $this->limit));
        $query = File::find()->where(['is_delete' => 0]);
        if ($this->is_site == 1 && \Yii::$app->user->isGuest) {
            $query = $query->andWhere(['admin_id' => \Yii::$app->admin->identity->id, 'is_site' => 1]); // 站点管理页面
        } else {
            if (isset(\Yii::$app->mall) && \Yii::$app->mall) {
                if (\Yii::$app->user->isGuest) {
                    $query = $query->andWhere(['mall_id' => \Yii::$app->mall->id, 'user_id' => 0, 'is_site' => 0]); // 后台管理员请求的
                } else {
                    $user = UserHelper::getUser();
                    if ($user && $user->mch_id) {
                        $query = $query->andWhere(['mch_id' => $user->mch_id, 'is_site' => 0]);
                    } elseif ($user) {
                        $query = $query->andWhere(['user_id' => $user->id, 'is_site' => 0]);
                    }
                }
            } else {
                $query->andWhere(['mall_id' => 0, 'is_site' => 0]);
                \Yii::warning('========== fall back to mall_id = 0 ==========');
            }
        }


        $query->andWhere(['type' => $this->type]);
        if ($this->keyword) {
            $query->andWhere(['like', 'name', $this->keyword]);
        }
        if ($this->group_id) {
            $query->andWhere(['group_id' => $this->group_id]);
        }
        $pagination = null;
        $list = $query->page($pagination, $this->limit, $this->page)->orderBy('id DESC')->asArray()->all();
        return $this->apiResponse(ApiCode::CODE_SUCCESS, '', ['list' => $list, 'pagination' => $pagination]);
    }

}